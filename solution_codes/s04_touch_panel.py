# s04_touch_panel.py - แผงควบคุม LED บนจอสัมผัส
# วิธีรัน: 1) บนจอบอร์ด แตะการ์ด Playground ค้างไว้ (widget เกิดบนหน้านี้เท่านั้น)
#          2) ปรับสีหรือข้อความปุ่มได้ตามใจทีม แล้วส่งขึ้นบอร์ดดูผลทุกครั้ง
#          3) กด Program to Device แล้วมองสองที่พร้อมกัน: จอ กับ หลอด LED จริง
#
# คาบนี้เราสร้างหน้า Controls ของทีมเราเอง นิ้วแตะกระจกที่ CM55
# กลายเป็นเหตุการณ์ในคิว แล้วโค้ด Python ที่ CM33 มารับด้วย ui.poll()
# โจทย์จริงของคาบนี้ไม่ใช่ "กดแล้วไฟติด" แต่คือ "จอกับไฟจริงต้องตรงกันเสมอ"
#
# ดูที่จอ: ซ้ายคือสามแถว แถวละหนึ่งดวง มีไฟสถานะ ปุ่มเปิด และปุ่มปิด แยกกันคนละปุ่ม
#         ขวาคือตัวเลขสรุปกับคำสั่งทั้งชุด บรรทัดสถานะอยู่ข้างหัวเรื่องบนสุด
#         ส่วนกล่องยืนยันซ่อนไว้กลางจอ โผล่เฉพาะตอนสั่ง "ปิดทั้งหมด"
# กับดัก : ปุ่มเดียวที่กดแล้วสลับไปมา บอกไม่ได้ว่าตอนนี้อยู่สถานะไหน คนกดต้องเดา
#         และถ้าเดาผิด ก็สั่งตรงข้ามกับที่ตั้งใจ - แผงควบคุมจริงจึงแยกเปิดกับปิด
#         เสมอ ปุ่ม "เปิด" ที่กดซ้ำสิบครั้งต้องได้ผลเดียวกับกดครั้งเดียว

import ui
import gpio
import time

# ---------- ข้อมูลของแผงควบคุม (ปรับสีหรือข้อความได้ตามใจทีม) ----------
BTN_TEXT = ["แดง", "เขียว", "น้ำเงิน"]              # สามสีของแผง เรียงตรงกับ LED_IDX ข้างล่าง
COL_ON = [0xE53935, 0x43A047, 0x1E88E5]           # สีไฟสถานะตอนติด เรียงตรงกับ BTN_TEXT
COL_OFF = 0x171B22                                 # สีเทาของปุ่มที่ไม่ได้กำลังทำงาน
COL_TEXT, COL_DIM, COL_CARD = 0xE8EAED, 0x9AA3AF, 0x171B22

# แผงนี้คุม "สามสี" ไม่ใช่ "ทุกดวงบนบอร์ด" - เลขดวงของแต่ละสีถามจากชื่อที่เฟิร์มแวร์รายงาน
# บอร์ดที่รายงานครบ RGB_RED / RGB_GREEN / RGB_BLUE (Dev Kit) ใช้ชื่อ เพราะเลขดวงอาจเปลี่ยนในรุ่นถัดไป
# บอร์ดที่ไม่ครบ (Eva Kit: ดวง 0 1 2 คือ แดง เขียว น้ำเงิน แม้ดวงที่ 2 จะชื่อ "RGB_RED") ใช้เลขตรง ๆ
LED_NAMES = gpio.board_info()["led_names"]
RGB_NAMES = ("RGB_RED", "RGB_GREEN", "RGB_BLUE")
if all(n in LED_NAMES for n in RGB_NAMES):
    LED_IDX = [LED_NAMES.index(n) for n in RGB_NAMES]
else:
    LED_IDX = [0, 1, 2]

# ความจริงของโปรแกรมอยู่ที่ list นี้ที่เดียว
# ห้ามไปอ่านจากฮาร์ดแวร์: gpio.led(2).value() ตอบระดับของขา ไม่ใช่สิ่งที่เราสั่ง
# และหลัง brightness() หรือ hold() ขาจะถูกทิ้งไว้ต่ำ ค่าที่ได้จึงเป็น 0
led_on = [False] * len(LED_IDX)

# --- ท่าที่ 1: เตรียมหน้าจอให้ว่าง แล้วปักหัวเรื่อง ---
# ui.screen() ล้าง widget ที่กลุ่มก่อนหน้าทิ้งค้างไว้ ไม่งั้นเรานับโควตาผิด
ui.screen()
time.sleep_ms(200)                                 # ให้ CM55 ล้างเสร็จก่อนยิงคำสั่งชุดใหม่

# value= ของ Label คือ "ขนาดฟอนต์" (16/20/24/28) ไม่ใช่ค่าตัวเลขใด ๆ
# 28 คือหัวเรื่อง 20 คือค่าที่ต้องอ่าน 16 คือป้ายกำกับชั้นรอง - สามชั้นนี้คือลำดับสายตา
# ผังหน้าจอ: หัวเรื่อง+สถานะ y=8..45 · สามแถวคำสั่งรายดวง y=52..380 · การ์ดคำสั่งรวม x=520..768
ui.Label("แผงควบคุม LED ของทีม", x=24, y=8, color=COL_TEXT, value=28)
status = ui.Label("พร้อมรับคำสั่ง", x=360, y=12, color=COL_DIM, value=20)

# --- ท่าที่ 2: สามแถว แถวละหนึ่งดวง เปิดกับปิดแยกกันคนละปุ่ม ---
# ทำไมไม่ใช้ปุ่มเดียวสลับ: ปุ่มสลับบอกไม่ได้ว่าตอนนี้อยู่สถานะไหน คนกดต้องอ่านจาก
# ที่อื่นแล้วเดา ส่วนปุ่มเปิดกับปุ่มปิดที่แยกกัน กดแล้วได้ผลเดิมเสมอไม่ว่าจะกดกี่ครั้ง
# ซึ่งสำคัญมากตอนสัญญาณสั่นหรือคนกดซ้ำเพราะไม่แน่ใจ
#
# สามแถวนี้ไม่มีการ์ดรองอยู่ข้างหลัง เพราะปุ่มสูง 88 px สามแถวที่เว้นห่างกัน 32 px
# กินความสูง 328 px จาก 398 px ที่มี ถ้าใส่กรอบการ์ดเข้าไปด้วย แถวล่างสุดจะถูกดันตกจอ
ROW_TOP = 52           # ขอบบนของแถวแรก
ROW_PITCH = 120        # ปุ่มสูง 88 + ระยะระหว่างเป้าสัมผัส 32 = 120
lamps = []
btn_on = []
btn_off = []
for i in range(len(LED_IDX)):
    y = ROW_TOP + i * ROW_PITCH
    # ไฟสถานะบอกว่า "ตอนนี้เป็นยังไง" ปุ่มบอกว่า "สั่งอะไรได้"
    # สองอย่างนี้คนละหน้าที่ จึงต้องเป็นคนละชิ้นบนจอ ไม่ใช่ปุ่มที่เปลี่ยนสีเอง
    lamps.append(ui.Led(x=24, y=y + 20, w=48, h=48, color=COL_ON[i], value=0))
    ui.Label(BTN_TEXT[i], x=88, y=y + 32, color=COL_DIM, value=16)
    btn_on.append(ui.Button("เปิด", x=184, y=y, w=144, h=88, color=0x30A46C, value=20))
    btn_off.append(ui.Button("ปิด", x=360, y=y, w=144, h=88, color=0x3A4150, value=20))

# เก็บหมายเลขประจำตัวไว้ เพราะเหตุการณ์บอกมาแค่ handle ไม่ได้บอกชื่อปุ่ม
on_ids = [b.id() for b in btn_on]
off_ids = [b.id() for b in btn_off]

# --- ท่าที่ 3: คำสั่งทั้งชุด กับตัวเลขสรุป ---
# ปุ่มล่างของการ์ดนี้จบที่ y=340 พอดี ต่ำกว่านั้นคือมุมที่ปุ่ม Console จองไว้
ui.Panel(x=520, y=48, w=248, h=308, color=COL_CARD, min=COL_DIM, max=12, value=1)
# ตัวเลขมาพร้อมพิสัยของมันเสมอ ป้ายกำกับแยกอีกบรรทัดจึงไม่จำเป็น และไม่มีที่ให้ด้วย
lbl_count = ui.Label("ติดอยู่ 0 จาก " + str(len(LED_IDX)) + " ดวง", x=536, y=60,
                     color=COL_TEXT, value=20)
ui.Label("คำสั่งทั้งชุด", x=536, y=96, color=COL_DIM, value=16)
btn_all_on = ui.Button("เปิดทั้งหมด", x=536, y=132, w=216, h=88, color=0x30A46C, value=20)
btn_all_off = ui.Button("ปิดทั้งหมด", x=536, y=252, w=216, h=88, color=0x3A4150, value=20)

# กล่องยืนยัน: "ปิดทั้งหมด" แตะทีเดียวเปลี่ยนของจริงทุกดวงในแผงพร้อมกัน
# คำยืนยันจึงต้องบอกสิ่งที่จะเกิด ไม่ใช่ถามลอย ๆ ว่า "แน่ใจไหม"
# ปุ่มในตัว MsgBox เองยังไม่ส่งเหตุการณ์กลับมาให้ Python เห็น (เฟิร์มแวร์ผูก
# callback ไว้กับ ui.Button เท่านั้น) จึงใช้ ui.Button จริงสองปุ่มเป็นคำตอบ
box = ui.MsgBox("ปิดทั้งหมด\nไฟทุกสีจะดับพร้อมกัน", x=48, y=88, w=496, h=160,
                color=COL_CARD)
btn_yes = ui.Button("ปิดทั้งหมด", x=568, y=88, w=152, h=88, color=0x3A4150, value=20)
btn_no = ui.Button("ไม่ปิด", x=568, y=208, w=152, h=88, color=0x3A4150, value=20)
box.hide()
btn_yes.hide()
btn_no.hide()

# --- ท่าที่ 4: ประตูเดียวที่เปลี่ยนสถานะไฟได้ ---
def show_status():
    # อ่านจาก led_on อย่างเดียว ไม่ถามฮาร์ดแวร์ จึงเชื่อถือได้เสมอ
    n = 0
    for i in range(len(LED_IDX)):
        if led_on[i]:
            n += 1
    # ตัวเลขมาพร้อมพิสัยของมันเสมอ "ติดอยู่ 2" ไม่บอกอะไร "2 จาก 3" บอกทันที
    lbl_count.text("ติดอยู่ " + str(n) + " จาก " + str(len(LED_IDX)) + " ดวง")

def set_led(i, on):
    # ทุกเส้นทางที่เปลี่ยนไฟต้องผ่านฟังก์ชันนี้ ถ้ามีที่ไหนสั่ง gpio ตรง ๆ
    # วันหนึ่งจอกับไฟจริงจะไม่ตรงกัน แล้วเราจะหาไม่เจอว่าใครเป็นคนสั่ง
    # นี่คือรูปทรงที่ examples/s04/03_switch_matches_led.py สรุปไว้ทั้งไฟล์ - ให้มีฟังก์ชันเดียว
    # ที่มีสิทธิ์เปลี่ยนสถานะไฟ แล้วบังคับทุกเส้นทางให้ผ่านประตูนั้น เหตุผลอยู่ที่บรรทัดสุดท้าย
    # ของไฟล์นั้น: ผู้ใช้เชื่อจอ ไม่ได้เชื่อหลอดไฟ จอที่พูดไม่ตรงกับของจริงจึงร้ายกว่าจอที่ดับ
    # i คือแถวของแผง (0 แดง 1 เขียว 2 น้ำเงิน) ส่วนเลขดวงจริงอยู่ที่ LED_IDX[i]
    led_on[i] = on                                 # 1) จำไว้ก่อน
    if on:
        gpio.led(LED_IDX[i]).on()                  # 2) สั่งของจริง
        lamps[i].value(1)                          # 3) ไฟบนจอสะท้อนของจริง
    else:
        gpio.led(LED_IDX[i]).off()
        # value(0) ทำให้ไฟหรี่ ไม่ใช่หาย โดยตั้งใจ - ดวงที่หายไปตอนดับ
        # ทำให้คนดูแยกไม่ออกว่าดับจริงหรือจอเสีย
        lamps[i].value(0)
    show_status()                                  # 4) รายงานขึ้นจอทุกครั้ง ไม่มีข้อยกเว้น

# --- ท่าที่ 5: เริ่มจากสถานะที่เรารู้แน่ ---
# ไม่ "สมมติ" ว่าไฟดับอยู่ แต่สั่งให้ดับ เผื่อโปรแกรมก่อนหน้าทิ้งไฟติดค้างไว้
for i in range(len(LED_IDX)):
    set_led(i, False)

asking = False
print("แผงควบคุมพร้อมแล้ว แตะปุ่มบนจอ แล้วมองหลอดไฟจริงบนบอร์ดด้วย")

# --- ท่าที่ 6: event loop - poll แล้ว dispatch แล้ว act แล้ว sleep ---
while True:
    # กฎข้อ 1: ต้องเรียก ui.poll() ทุกรอบ ไม่งั้นจอจะซ่อน widget ไว้ราว 2 วินาที
    # poll คืน list ของ dict ครั้งละไม่เกิน 8 เหตุการณ์ ถ้ามีมากกว่านั้นต้องรอบถัดไป
    for ev in ui.poll():
        h = ev['handle']
        t = ev['type']
        if t != 'clicked':
            # ตารางว่าตัวควบคุมชนิดไหนส่ง type อะไร ดูได้จาก examples/s04/02_event_types.py
            # ซึ่งพิมพ์เหตุการณ์จริงออกมาให้อ่านทีละใบ แทนที่จะให้เราท่องเอา
            continue

        if h in on_ids:
            # สั่งเปิด ไม่ใช่สั่งสลับ กดซ้ำสิบครั้งได้ผลเดียวกับกดครั้งเดียว
            set_led(on_ids.index(h), True)
            status.text("สั่งเปิด " + BTN_TEXT[on_ids.index(h)])
        elif h in off_ids:
            set_led(off_ids.index(h), False)
            status.text("สั่งปิด " + BTN_TEXT[off_ids.index(h)])
        elif h == btn_all_on.id():
            for i in range(len(LED_IDX)):
                set_led(i, True)
            status.text("เปิดครบทุกสี")
        elif h == btn_all_off.id() and not asking:
            # คำสั่งที่เปลี่ยนของจริงหลายชิ้นพร้อมกัน ต้องถามก่อนเสมอ
            asking = True
            box.show()
            btn_yes.show()
            btn_no.show()
            status.hide()
        elif h == btn_yes.id() and asking:
            asking = False
            for i in range(len(LED_IDX)):
                set_led(i, False)
            box.hide()
            btn_yes.hide()
            btn_no.hide()
            status.text("ปิดครบทุกสี")
            status.show()
        elif h == btn_no.id() and asking:
            asking = False
            box.hide()
            btn_yes.hide()
            btn_no.hide()
            status.show()

    # กฎข้อ 2: หน่วงอย่างน้อย 50 ms คืนเวลาให้ระบบไปวาดจอ
    # หน้านี้มี widget 24 ตัวและไม่มีเซนเซอร์ จึงใช้ 50 ได้ ถ้าเป็นแดชบอร์ดหนักต้อง 200
    # เพดานอยู่ที่ 64 ตัว และ examples/s04/06_layout_budget.py วางกริดปุ่มให้ดูจนชนโควตา
    # พร้อมตรวจเขตห้ามวางที่มุมขวาล่างซึ่งเป็นของปุ่ม Console
    # อ่านก่อนจะเติม widget ของทีมเข้าไปในหน้านี้ จะได้ไม่ไปเจอ RuntimeError ตอนโค้ดยาวแล้ว
    time.sleep_ms(50)
