# เวลาสามตัวตั้งต้นจาก ticks_ms() ค่าเดียวกัน ถ้าเรียกสามครั้งแยกกัน
# ค่าจะต่างกันเล็กน้อยและทำให้รอบแรกเพี้ยนไปไม่กี่มิลลิวินาที
t0 = time.ticks_ms()
last_step = t0
last_change = t0
last_ui = t0
chase_on = True        # ไฟวิ่งเดินอยู่ไหม - ปุ่มบนจอเป็นคนเปลี่ยนค่านี้
asking = False         # กำลังรอคำตอบจากกล่องยืนยันอยู่ไหม
last_sec = -1          # วินาทีที่เพิ่งเขียนลงจอ กันไม่ให้เขียนซ้ำเร็วกว่า 1 ครั้งต่อวินาที

while time.ticks_diff(time.ticks_ms(), t0) < RUN_MS:
    now = time.ticks_ms()      # ขอเวลาครั้งเดียวต่อรอบ แล้วใช้ร่วมกันทั้งสองงาน

    # --- ท่าที่ 3: ไฟวิ่งตามนาฬิกา ไม่ใช่ตาม sleep ---
    if chase_on and time.ticks_diff(now, last_step) >= STEP_MS:
        gpio.led(led_index).off()              # ดับดวงเดิมก่อน
        # % NUM_LEDS คือหัวใจของคำว่าวิ่งวน พอถึง NUM_LEDS เศษของการหารด้วย NUM_LEDS คือ 0
        led_index = (led_index + 1) % NUM_LEDS # เลื่อนไปดวงถัดไป วนกลับที่ 0 เอง
        gpio.led(led_index).on()               # จุดดวงใหม่ (ลำดับดับก่อน-จุดทีหลังห้ามสลับ)
        last_step = now                        # ต้องอยู่ใน if เท่านั้น ไม่งั้นไฟจะไม่วิ่งเลย
        # ไฟบนจอสะท้อนหลอดจริง ดวงที่ดับจะหรี่ ไม่ใช่หายไป
        for k in range(NUM_LEDS):
            led_ui[k].value(1 if k == led_index else 0)

    # --- ท่าที่ 4: อ่านปุ่มทุกรอบ แต่เชื่อเฉพาะค่าที่นิ่งแล้ว ---
    raw = btn.is_pressed()

    if raw != last_raw:
        # ค่าเพิ่งขยับ ยังไม่เชื่อ แค่จับเวลาใหม่
        last_raw = raw
        last_change = now
    elif raw != stable and time.ticks_diff(now, last_change) >= DEBOUNCE_MS:
        # นิ่งครบ DEBOUNCE_MS แล้ว ถึงจะยอมรับเป็นค่าจริง
        # ตัวเลข 40 ms ไม่ใช่เลขศักดิ์สิทธิ์ examples/s03/05_debounce_count.py เดินตัวนับดิบ
        # กับตัวนับกันเด้งไว้ข้างกัน ให้ลองกดช้าสิบครั้งแล้วกดรัวสิบครั้ง แล้วอ่านส่วนต่างเอาเอง
        # นั่นคือวิธีเลือกค่านี้ให้เหมาะกับปุ่มตรงหน้า แทนที่จะลอกเลขของคนอื่นมาใช้
        stable = raw
        if stable:
            # ถ้าเอา if stable: ออก ตอนปล่อยปุ่มก็ผ่านทางนี้ด้วย เลขจะเพิ่มทีละสอง
            count += 1
            # พิมพ์เมื่อมีเหตุการณ์ ไม่ใช่พิมพ์ทุกรอบ ไม่งั้นจอโดนยิง 200 บรรทัดต่อวินาที
            lcd.print("กดครั้งที่", count)

    # --- ท่าที่ 4 ครึ่งหลัง: จอกับปุ่มบนจอ เดินคนละจังหวะกับสองงานข้างบน ---
    # ไม่เรียก ui.poll() ทุกรอบลูป เพราะทุกครั้งคือการยิง IPC ข้ามคอร์ - 200 ครั้ง
    # ต่อวินาทีเพื่อรอนิ้วที่มาถึงวินาทีละครั้ง คือการจ่ายแพงกว่าที่ได้มาก
    if time.ticks_diff(now, last_ui) >= UI_MS:
        last_ui = now
        led_btn.value(1 if stable else 0)

        # ตัวเลขที่คนต้องอ่าน เขียนใหม่ไม่เกินวินาทีละครั้ง และอยู่ตำแหน่งเดิมเสมอ
        left_s = (RUN_MS - time.ticks_diff(now, t0)) // 1000
        if left_s != last_sec:
            last_sec = left_s
            seg_count.text(str(count))
            lbl_left.text(str(left_s) + " วิ")
            bar_left.value(left_s)

        for ev in ui.poll():
            if ev["type"] != "clicked":
                continue
            if ev["handle"] == btn_run.id():
                # คำสั่งเดินไม่ต้องยืนยัน เพราะมันย้อนกลับได้ด้วยปุ่มข้าง ๆ ทันที
                chase_on = True
                lbl_status.text("ไฟวิ่งกำลังเดิน")
            elif ev["handle"] == btn_stop.id() and not asking:
                # คำสั่งที่ทำให้ของจริงหยุด ต้องถามก่อน และคำถามต้องบอกสิ่งที่จะเกิด
                asking = True
                box.show()
                btn_yes.show()
                btn_no.show()
                lbl_status.hide()
            elif ev["handle"] == btn_yes.id() and asking:
                asking = False
                chase_on = False
                for k in range(NUM_LEDS):
                    gpio.led(k).off()
                    led_ui[k].value(0)
                lbl_status.text("หยุดแล้ว ไฟดับทุกดวง")
                box.hide()
                btn_yes.hide()
                btn_no.hide()
                lbl_status.show()
            elif ev["handle"] == btn_no.id() and asking:
                asking = False
                box.hide()
                btn_yes.hide()
                btn_no.hide()
                lbl_status.show()

    time.sleep_ms(POLL_MS)                     # จุดเดียวที่โปรแกรมยอมพัก

# --- ท่าที่ 5: ดับไฟ แล้วสรุปผลปิดท้าย ---
# โปรแกรมฝังตัวที่จบแล้วทิ้งไฟติดค้าง ถือว่าจบไม่เรียบร้อย คนถัดไปจะไม่รู้ว่าไฟมาจากใคร
# examples/s03/02_led_blink.py เจอเรื่องเดียวกันในรูปแบบที่เล็กกว่า คือจบลูปด้วย toggle()
# จำนวนคี่แล้วไฟค้างติดโดยไม่ได้ตั้งใจ - ปิดท้ายด้วย off() เสมอ ไม่ว่าตรรกะข้างบนจะเป็นอย่างไร
for i in range(NUM_LEDS):
    gpio.led(i).off()
    led_ui[i].value(0)

# จอต้องบอกด้วยว่ารอบนี้จบแล้ว ไม่ใช่ค้างเลขเดิมไว้เฉย ๆ ให้คนเดินมาดูเข้าใจผิด
# ว่าโปรแกรมยังเดินอยู่ - ค่าที่ค้างต้องระบุว่ามันไม่ใช่ค่าปัจจุบัน
seg_count.text(str(count))
bar_left.value(0)
lbl_left.text("0 วิ")
lbl_status.text("รอบนี้จบแล้ว ตัวเลขข้างบนคือค่าสุดท้าย")
ui.poll()

# str(count) จำเป็นเพราะกำลังต่อสตริงด้วย + เพื่อแทรกตัวเลขไว้กลางแท็ก <span>
# ถ้าใช้จุลภาคแบบ lcd.print("...", count) จะได้ช่องว่างเกินติดขอบแท็ก
lcd.print("<span class=ok>จบรอบทดสอบ กดปุ่มทั้งหมด " + str(count) + " ครั้ง</span>")

print("โปรแกรมจบแล้ว - ไฟทุกดวงถูกดับเรียบร้อย")
