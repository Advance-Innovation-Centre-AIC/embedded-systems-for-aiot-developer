# จานสีของแผงควบคุม สีจัดสงวนไว้ให้สถานะผิดปกติ ค่าปกติเป็นตัวหนังสือขาวบนการ์ดเข้ม
COL_TEXT, COL_DIM = 0xE8EAED, 0x9AA3AF
COL_CARD = 0x171B22
COL_OK, COL_WARN, COL_BAD = 0x30A46C, 0xF5A623, 0xE5484D

# เกณฑ์ยอมรับหน่วยองศา ผู้ใช้ตั้งเองได้ ไม่ใช่ค่าคงที่ที่ฝังอยู่ในโค้ด
# งานวางระดับแต่ละงานยอมได้ไม่เท่ากัน วางกล้องกับวางตู้เย็นคนละเกณฑ์กัน
TOL_MIN, TOL_MAX, TOL_STEP = 1, 30, 1
tol = 5

# --- ท่าที่ 1: บอร์ดนี้ไม่ต้องปลุกเซนเซอร์ ---
# IMU ของ Eva Kit อยู่บนบัสที่คอร์จอ (CM55) ถือไว้คนเดียว ฝั่ง Python ไม่ได้
# คุยกับชิปเอง แต่ขอค่าที่คอร์จออ่านเก็บไว้ให้ทุก 200 ms จึงเรียก motion() ได้เลย
# sensors.init() บนบอร์ดนี้จะโยน OSError ทันที ไม่ใช่ค้าง อย่าใส่กลับเข้ามา
#
# หลังรีเซ็ต คอร์จอเริ่มตอบเรื่องเซนเซอร์ราว 13 วินาที การอ่านครั้งแรก
# จึงนิ่งได้ถึง 16 วินาที ครั้งถัดไปเร็วปกติ อุ่นเครื่องหนึ่งครั้งตรงนี้
# ให้การรอไปเกิดก่อนสร้างหน้าปัด ไม่ใช่ตอนแถบควรจะขยับแล้ว
try:
    sensors.bmi270.motion()
except OSError:
    print("คอร์จอยังไม่ตอบรอบแรก จะลองใหม่ในลูป")

# --- ท่าที่ 2: สองแกน สองแถบ และไม้บรรทัดที่บอกพิสัยของมันเอง ---
# ตัวเลของศาลอย ๆ ตอบไม่ได้ว่า 7 องศาคือเอียงมากหรือน้อย ไม้บรรทัด -90 ถึง 90
# ที่วางอยู่ใต้แถบตอบให้ทันทีโดยไม่ต้องอธิบาย และ Seg7 ยังเก็บทศนิยมไว้ให้อ่านละเอียด
# ผังหน้าจอ: หัวเรื่อง+คุณภาพของค่า y=8..40 · การ์ดวัดสองแกน y=48..176
#            การ์ดเทียบเกณฑ์ x=616..768 · การ์ดตั้งค่าและคำสั่ง y=192..380
ui.Label("เครื่องวัดระดับดิจิทัลสองแกน", x=24, y=8, color=COL_TEXT, value=24)

# คุณภาพของค่าเขียนเป็นคำ ไม่ใช่เป็นสีอย่างเดียว บรรทัดนี้จึงผ่านการทดสอบขาวดำได้เอง
# และอยู่ตำแหน่งคงที่ข้างหัวเรื่อง คนอ่านรู้ตลอดว่าต้องมองที่ไหนถึงจะรู้ว่าเลขเชื่อได้ไหม
lbl_health = ui.Label("กำลังวัดอยู่", x=416, y=12, color=COL_DIM, value=20)
health = "กำลังวัดอยู่"     # ข้อความล่าสุดของบรรทัดคุณภาพ คิดใหม่วินาทีละครั้ง

# สองแกนวางเคียงกันแทนที่จะวางซ้อนกัน ไม้บรรทัดจึงสั้นลงแต่ได้ความสูงคืนมา 100 พิกเซล
# ซึ่งเป็นความสูงที่แถวปุ่มข้างล่างต้องใช้ - ปุ่มสูง 88 px ไม่มีทางบีบให้เตี้ยกว่านี้ได้
ui.Panel(x=24, y=48, w=576, h=128, color=COL_CARD, min=COL_DIM, max=12, value=1)
ui.Label("ROLL เอียงซ้าย-ขวา (องศา)", x=40, y=60, color=COL_DIM, value=16)
roll_bar = ui.Bar(x=40, y=96, w=160, h=16, color=0x4A9EFF, min=-90, max=90, value=0)
roll_scale = ui.Scale(x=40, y=112, w=160, h=44, color=COL_TEXT, min=-90, max=90)
# ไม้บรรทัดกว้าง 160 พิกเซล ใส่ 9 ขีดและใส่ตัวเลขทุกขีดที่สี่ = -90 0 90
# เดิมเป็น 13 ขีดบนไม้บรรทัด 296 พิกเซล พอไม้บรรทัดสั้นลงครึ่งหนึ่ง ตัวเลขจะเบียดกัน
roll_scale.ticks(9, 4)
roll_seg = ui.Seg7("+00.0", x=216, y=96, w=96, h=56, color=COL_TEXT)

ui.Label("PITCH เอียงหน้า-หลัง (องศา)", x=328, y=60, color=COL_DIM, value=16)
pitch_bar = ui.Bar(x=328, y=96, w=160, h=16, color=0x4A9EFF, min=-90, max=90, value=0)
pitch_scale = ui.Scale(x=328, y=112, w=160, h=44, color=COL_TEXT, min=-90, max=90)
pitch_scale.ticks(9, 4)
pitch_seg = ui.Seg7("+00.0", x=504, y=96, w=80, h=56, color=COL_TEXT)

# ไฟสองดวงแทนตัวหนังสือสี: ถ่ายจอเป็นขาวดำแล้วยังแยกออกว่าดวงไหนติด
# ส่วนคำว่า OK สีเขียวกับ NG สีแดง พอเป็นขาวดำแล้วแยกไม่ออกเลย
ui.Panel(x=616, y=48, w=152, h=128, color=COL_CARD, min=COL_DIM, max=12, value=1)
led_in = ui.Led(x=632, y=72, w=48, h=48, color=COL_OK, value=1)
led_out = ui.Led(x=704, y=72, w=48, h=48, color=COL_BAD, value=0)
ui.Label("ผ่าน", x=632, y=128, color=COL_DIM, value=16)
ui.Label("เกิน", x=696, y=128, color=COL_DIM, value=16)

# เกณฑ์ยอมรับ: ผู้ใช้ตั้งเองด้วยปุ่มสองปุ่ม ไม่ใช่ค่าคงที่ในโค้ด
# ui.Spinbox หนีบค่าให้อยู่ในพิสัยของมันเอง คนตั้งจึงตั้งเกินพิสัยไม่ได้เลย
# ข้อควรรู้ของจอสัมผัส: spinbox เปล่า ๆ นิ้วเปลี่ยนค่าไม่ได้ เพราะการแตะแค่เลือก
# ตำแหน่งหลัก ตัวที่เพิ่มลดค่าจริงคือปุ่มสองปุ่มข้าง ๆ นี้
#
# ห้าเป้าสัมผัสเรียงแถวเดียว เว้นห่างกัน 32 px และปุ่มขวาสุดจบที่ x=752 y=328
# ซึ่งอยู่เหนือมุมที่ปุ่ม Console จองไว้ (x>690 และ y>340) พอดี
ui.Panel(x=24, y=192, w=744, h=188, color=COL_CARD, min=COL_DIM, max=12, value=1)
ui.Label("เกณฑ์ยอมรับ (องศา)", x=40, y=204, color=COL_DIM, value=16)
sp_tol = ui.Spinbox(x=40, y=240, w=96, h=88, color=COL_TEXT,
                    min=TOL_MIN, max=TOL_MAX, value=tol)
# ค่าตั้งต้นของช่องคือสี่หลัก ถ้าไม่บอกจะเห็น 0005 ซึ่งอ่านแล้วสะดุด
sp_tol.digits(2, 0)
btn_dn = ui.Button("ลด", x=168, y=240, w=88, h=88, color=0x171B22, value=20)
btn_up = ui.Button("เพิ่ม", x=288, y=240, w=88, h=88, color=0x171B22, value=20)

# ปุ่มสั่งงานสองปุ่ม แยกหน้าที่กันคนละปุ่ม ไม่มีปุ่มไหนสลับสองความหมายในตัวเดียว
ui.Label("คำสั่ง", x=472, y=204, color=COL_DIM, value=16)
zero_btn = ui.Button("ตั้งศูนย์", x=472, y=240, w=144, h=88, color=0x30A46C, value=20)
zero_id = zero_btn.id()      # เก็บ .id() ตั้งแต่ตอนสร้าง เพราะในลูปเราจะเทียบกับตัวเลขนี้
exit_btn = ui.Button("จบการวัด", x=648, y=240, w=104, h=88, color=0x171B22, value=20)
exit_id = exit_btn.id()
ref = ui.Label("อ้างอิง R +0.0  P +0.0", x=40, y=336, color=COL_DIM, value=16)

# ตัวกรองมีความจำ สองสัญญาณจึงต้องใช้สองตัวเสมอ - นี่คือความต่างระหว่างฟังก์ชันกับอ็อบเจกต์
# ถ้าใช้ตัวเดียวป้อนสลับกัน ค่าทั้งสองแกนจะกวนกันจนอ่านไม่ได้เรื่อง
# examples/s06/01_imu_step_counter.py วางท่าเดียวกันนี้ในงานที่ง่ายกว่า คือสัญญาณเส้นเดียว
# ตัวกรองตัวเดียว และวาดเส้นดิบไว้ข้างเส้นที่กรองแล้วตลอดเวลา - ถ้าอยากพิสูจน์ว่า alpha 0.2
# ให้ผลอย่างไรกับข้อมูลจริงจาก IMU ตัวนี้ ไฟล์นั้นคือที่ที่ดูได้โดยไม่ต้องรื้อหน้าปัดของเราทิ้ง
ema_roll = dsp.EMA(alpha=0.2)
ema_pitch = dsp.EMA(alpha=0.2)
roll_zero = 0.0
pitch_zero = 0.0

roll, pitch = 0.0, 0.0
roll_f, pitch_f = 0.0, 0.0
last_sec = -1        # วินาทีที่เพิ่งเขียนตัวเลขลงจอ กันไม่ให้เขียนถี่กว่าวินาทีละครั้ง


def clamp90(v):
    # แถบตั้งช่วงไว้ -90..90 ถ้าส่งค่าเกินเข้าไป มันจะไปติดปลาย ครอบไว้ก่อนใช้เสมอ
    return 90.0 if v > 90.0 else (-90.0 if v < -90.0 else v)


running = True
while running:
    ok_read = True
    try:
        # --- ท่าที่ 3: อ่านหกแกนจาก snapshot ชุดเดียว แล้วแปลงเป็นองศา ---
        # motion() ได้หกแกนจากการอ่านครั้งเดียวกันของคอร์จอ จึงเป็นชุดที่สอดคล้องกัน
        # และถามข้ามคอร์แค่รอบเดียว ต่างจากเรียก acceleration() แล้ว gyroscope() ซึ่งถามสองรอบ
        ax, ay, az, gx, gy, gz = sensors.bmi270.motion()
        # ลำดับที่คืนคือ (roll, pitch) ไม่ใช่ (pitch, roll) - สลับเมื่อไรแถบจะวิ่งผิดแกน
        roll, pitch = dsp.tilt(ax, ay, az)
    except OSError:
        # อ่านพลาดหนึ่งรอบไม่ควรทำให้หน้าปัดดับทั้งหน้า ใช้ค่าเดิมไปก่อนแล้วลองใหม่รอบหน้า
        ok_read = False

    if ok_read:
        # --- ท่าที่ 4: กรองความสั่น แล้วหักค่าอ้างอิงที่ตั้งศูนย์ไว้ ---
        roll_f = ema_roll.update(roll)
        pitch_f = ema_pitch.update(pitch)

    # ลำดับสำคัญมาก: กรองก่อน แล้วค่อยหักค่าศูนย์ เพราะตอนกดปุ่มตั้งศูนย์
    # เราต้องเก็บ roll_f (ค่าที่กรองแล้ว) ไม่ใช่ค่าดิบที่กำลังสั่นอยู่พอดี
    roll_show = roll_f - roll_zero
    pitch_show = pitch_f - pitch_zero

    # --- ท่าที่ 5: รับเหตุการณ์จากจอ ---
    for ev in ui.poll():
        h = ev['handle']
        if h == zero_id:
            # "ตั้งศูนย์" ไม่ได้แก้ค่าที่วัดได้ แต่ย้ายจุดอ้างอิงมาที่ท่าปัจจุบัน
            # เครื่องมือวัดที่ดีไม่ได้แปลว่าค่าดิบแม่นเป๊ะ แต่แปลว่าผู้ใช้กำหนดจุดอ้างอิงเองได้
            # และเก็บ roll_f ไม่ใช่ roll ด้วยเหตุผลเดียวกับที่ examples/s06/02_imu_fall_detection.py
            # ไม่ยอมตัดสินจากค่าพุ่งค่าเดียว - การตัดสินใจที่ยืนอยู่บนค่าที่ยังสั่น จะสั่นตามไปด้วย
            # ทั้งชีวิตของมัน ที่นั่นเป็นเรื่องเตือนผิด ที่นี่เป็นเรื่องแถบที่ไม่มีวันกลับมาศูนย์จริง ๆ
            roll_zero = roll_f
            pitch_zero = pitch_f
            ref.text("อ้างอิง R {:+.1f}  P {:+.1f}".format(roll_zero, pitch_zero))
        elif h == exit_id:
            running = False
        elif h == btn_up.id():
            # ปุ่มเพิ่มกับปุ่มลดแยกกันคนละปุ่ม ปุ่มเดียวที่สลับสองทิศ คนกดจะเดาไม่ออก
            tol = min(TOL_MAX, tol + TOL_STEP)
            sp_tol.value(tol)
        elif h == btn_dn.id():
            tol = max(TOL_MIN, tol - TOL_STEP)
            sp_tol.value(tol)

    # --- ท่าที่ 6: ส่งค่าขึ้นหน้าปัด แล้วเว้นจังหวะ ---
    # แถบรับจำนวนเต็มเท่านั้น จึง int() หลังครอบช่วงแล้ว ส่วน Seg7 รับสตริงจึงเก็บทศนิยมไว้ได้
    # แถบกับไฟขยับได้ทุกรอบ เพราะตาคนอ่าน "ตำแหน่ง" ได้โดยไม่ต้องหยุดอ่านตัวเลข
    roll_bar.value(int(clamp90(roll_show)))
    pitch_bar.value(int(clamp90(pitch_show)))

    # หนึ่งดวงติดเท่านั้น แผงที่ติดพร้อมกันหลายดวงคือแผงที่อ่านไม่ออก
    in_tol = abs(roll_show) <= tol and abs(pitch_show) <= tol
    led_in.value(1 if in_tol else 0)
    led_out.value(0 if in_tol else 1)

    # ตัวเลขที่คนต้องอ่าน เขียนใหม่ไม่เกินวินาทีละครั้ง และอยู่ตำแหน่งเดิมเสมอ
    # ตัวเลขทศนิยมที่วิ่งห้าครั้งต่อวินาที คือตัวเลขที่อ่านไม่ทัน แล้วคนจะเลิกอ่านมันไปเลย
    sec = time.ticks_ms() // 1000
    if sec != last_sec:
        last_sec = sec
        roll_seg.text("{:+.1f}".format(roll_show))
        pitch_seg.text("{:+.1f}".format(pitch_show))
        # ตั้งสีก่อนแล้วค่อยเขียนข้อความ สองบรรทัดนี้เป็นคำสั่งคนละครั้งข้ามคอร์
        # ถ้าเขียนข้อความก่อน จะมีเสี้ยววินาทีที่ข้อความใหม่ยังใส่สีของสถานะเก่าอยู่
        if not ok_read:
            lbl_health.color(COL_WARN)
            health = "ค่าค้าง นี่คือค่าล่าสุด"
        elif in_tol:
            lbl_health.color(COL_DIM)
            health = "อยู่ในเกณฑ์ {} องศา".format(tol)
        else:
            lbl_health.color(COL_BAD)
            health = "เอียงเกินเกณฑ์ {} องศา".format(tol)

    # --- ชีพจรของช่องทางข้ามคอร์: ส่งบรรทัดสถานะซ้ำทุกรอบโดยตั้งใจ ---
    # ฝั่งจอมีตัวจับเวลาสองจังหวะ โหมดเร็ว 5 ms กับโหมดปกติ 200 ms และมันจะอยู่
    # โหมดเร็วต่อไปอีก 500 ms ทุกครั้งที่ได้รับคำสั่ง "เขียนข้อความ" หรือ "ย้าย/ย่อ/เปลี่ยนสี"
