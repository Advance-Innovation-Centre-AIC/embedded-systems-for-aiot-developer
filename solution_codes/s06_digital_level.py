#         ขวาบนคือไฟสองดวงบอกว่าผ่านเกณฑ์หรือเกิน การ์ดล่างคือเกณฑ์ยอมรับกับปุ่มสั่งงาน
#         ส่วนคุณภาพของค่าที่กำลังอ่านอยู่ เขียนเป็นคำไว้ข้างหัวเรื่องบนสุด
# กับดัก : ui.Scale ไม่มีเข็มและไม่รับ .value() มันคือไม้บรรทัด ตัวที่ขยับคือ ui.Bar
#         ที่วางทับ ส่วน ui.Led สั่ง .value(0) แล้ว "หรี่" ไม่ใช่ "หาย" โดยตั้งใจ
#         ไฟแผงควบคุมที่หายไปตอนดับ ทำให้คนดูแยกไม่ออกว่าดับจริงหรือจอเสีย

