# s02_ai_observer.py - สมุดบันทึกผลการทดลอง แล้วพาบอร์ดขึ้นเน็ต
# วิธีรัน: 1) ทดลองกับบอร์ดจริงจนได้ผลครบ 3 แถว แล้วจดลงตัวแปร TRIALS
#          2) แตะการ์ด Playground บนจอบอร์ดค้างไว้ ก่อนส่งโค้ดขึ้นไป
#          3) กด Program to Device แล้วอ่านตารางกับบรรทัดสรุปบนจอ
#
# ไฟล์นี้ทำสองอย่างที่คาบ 2 ต้องการ อย่างแรกคือเอาผลที่เราจดมาด้วยมือขึ้นจอ
# ให้คนอื่นอ่านเป็นตารางได้ อย่างที่สองคือพาบอร์ดออกเน็ตแล้วรายงานเลข IP กลับมา
# สองอย่างนี้รวมกันคือรูปแบบของเครื่องมือหน้างานแทบทุกตัว - วัด จด แล้วรายงานออกไป
# ชุดตัวอย่างสามไฟล์ของคาบนี้อยู่ที่ examples/s02/ เปิดคู่กับไฟล์นี้ได้เลย
#
# ดูที่จอ: ซ้ายคือตารางผลการทดลองที่เติมทีละแถวตอนรัน ขวาคือไฟสถานะลิงก์สองดวง
#         ล่างคือมาตรวัดเวลาต่อเฉลี่ย เทียบกับเพดาน 85 วินาทีที่รอจริงได้
# กับดัก : ตารางนี้เป็นค่าที่ทีมจดมาด้วยมือ ไม่ใช่ค่าที่บอร์ดวัดสด ๆ ตอนนี้
#         หน้าจอจึงต้องเขียนกำกับไว้ ค่าที่ไม่บอกว่าตัวเองมาจากไหน คือค่าที่เชื่อไม่ได้

import lcd
import time
import ui
import wifi

# ---------- ค่าที่ทีมต้องแก้ก่อนรัน (อยู่บนสุดที่เดียว หาเจอโดยไม่ต้องอ่านทั้งไฟล์) ----------
# ทำไมยกขึ้นบนสุด: ทีมถัดไปที่มาอ่านต่อ แก้แค่ก้อนนี้ก็ได้รายงานของตัวเอง
# ถ้าเอา SSID ไปฝังกลางไฟล์ คนอ่านต้องไล่ทั้งไฟล์เพื่อหามัน
TEAM_NAME = "BentoBuilders"
WIFI_SSID = "AIoT-Class"
WIFI_PASS = "<รหัสผ่านของห้องเรียน>"

# --- ท่าที่ 1: เปิดสมุดบันทึกของทีม ---
# ท่าเปิดเหมือนคาบ 1 ทุกประการ และนั่นคือประเด็น - ท่าที่พิสูจน์แล้วว่าใช้ได้
# ควรเป็นท่าเดิม เพราะถ้าท่านี้เงียบ ท่าที่เหลือเขียนไปก็ไม่มีทางเห็นผล
lcd.clear()
lcd.console("<h2>บันทึกการต่อเน็ต - คาบ 2</h2>")
lcd.console("<span class=muted>ทีม " + TEAM_NAME + " - บันทึกผลการทดลอง</span>")

# --- ท่าที่ 2: ผลการทดลองที่จดมาจากบอร์ด ---
# แต่ละแถว: (ชื่อสิ่งที่ทดลอง, เงื่อนไขที่ทำ, ได้ผลไหม, เวลาที่ใช้เป็น ms)
# ใช้ tuple ไม่ใช่ dict เพราะทุกแถวมีสี่ช่องเท่ากันและลำดับมีความหมายคงที่
# tuple จึงกระชับกว่าและกินหน่วยความจำน้อยกว่า - บน heap 64 KB นี่ไม่ใช่เรื่องเล็ก
#
# สามแถวที่ใส่ไว้เป็นข้อมูลตัวอย่างจากรอบเก่า ทีมต้องเขียนทับด้วยผลของตัวเองให้ครบ
# ช่อง hit ที่เป็น False ยังบอกไม่ได้ว่าล้มเหลวเพราะอะไร ซึ่งเป็นคนละเรื่องกับ "ไม่ได้ผล"
# examples/s02/03_your_link_rule.py เล่าเคสนี้ไว้ตรง ๆ ว่าความล้มเหลวมีได้หลายแบบ
# และกฎที่มองเห็นแค่แบบเดียวจะรายงานน้อยกว่าความจริง โดยไม่มี error ให้จับสักบรรทัด
TRIALS = [
    ("2.4GHz", "ยืนข้างเราเตอร์", True, 3180),
    ("2.4GHz", "เดินไปสุดห้อง", True, 9240),
    ("5GHz", "ยืนข้างเราเตอร์", False, 85000),
]

# --- ท่าที่ 3: กางหน้ารายงานบนจอ ก่อนจะมีข้อมูลอะไรไปใส่ ---
# ลิ้นชัก Console เก็บบรรทัดไว้ให้เราอ่านย้อนหลัง แต่คนที่เดินมาดูโต๊ะเราตอนนี้
# ต้องการหน้าเดียวที่ตอบได้ทันทีว่า "ทดลองไปกี่รอบ ผลเป็นยังไง แล้วตอนนี้ต่ออยู่ไหม"
# หน้าจอจึงสร้างก่อน แล้วค่อยเติมข้อมูลลงไประหว่างทาง ไม่ใช่รอจนจบแล้วค่อยวาดทีเดียว
COL_TEXT, COL_DIM = 0xFFFFFF, 0xA0B4CC
COL_CARD, COL_OK, COL_BAD = 0x142240, 0x00E676, 0xFF5252
WAIT_CEILING_MS = 85000        # เพดานที่คนยืนรอจริงได้ ก่อนจะสรุปว่าบอร์ดแฮงก์

ui.screen()
time.sleep_ms(200)

# ui.Table แทนการเรียง ui.Label เอง เพราะสี่คอลัมน์ที่ความยาวไม่เท่ากันทุกแถว
# ถ้าจัดด้วยมือจะเยื้องกันจนอ่านไม่ออกทันทีที่ทีมเปลี่ยนข้อความในช่อง cond
# แถวหนึ่งสูงราว 70 พิกเซล และจะสูงเป็นสองเท่าทันทีที่ข้อความในช่องยาวเกิน
# ความกว้างคอลัมน์แล้วตัดบรรทัด - ตั้ง col_width ให้พอกับข้อความที่ยาวที่สุดเสมอ
tbl = ui.Table(x=16, y=34, w=500, h=352, cols=4)
tbl.col_width(0, 120)
tbl.col_width(1, 190)
tbl.col_width(2, 90)
tbl.col_width(3, 100)
tbl.add_row("ย่าน", "เงื่อนไข", "ผล", "ms")

ui.Label("ผลการทดลองของทีม " + TEAM_NAME, x=16, y=6, color=COL_TEXT, value=20)

# ไฟสองดวงบอกสถานะลิงก์ ติดทีละดวงเสมอ - แผงที่ติดพร้อมกันสองดวงคือแผงที่อ่านไม่ออก
ui.Panel(x=522, y=34, w=254, h=352, color=COL_CARD, min=COL_DIM, max=12, value=1)
ui.Label("สถานะลิงก์ตอนนี้", x=536, y=42, color=COL_DIM, value=16)
led_up = ui.Led(x=540, y=70, w=34, h=34, color=COL_OK, value=0)
ui.Label("ต่ออยู่", x=584, y=76, color=COL_DIM, value=18)
led_down = ui.Led(x=540, y=112, w=34, h=34, color=COL_BAD, value=1)
ui.Label("ยังไม่ต่อ", x=584, y=118, color=COL_DIM, value=18)
lbl_ip = ui.Label("IP: ยังไม่มี", x=536, y=162, color=COL_DIM, value=18)

# ที่มาของค่าต้องอยู่บนหน้าจอเดียวกับค่า ไม่ใช่อยู่ในหัวคนที่พิมพ์มันเข้าไป
ui.Label("ตารางซ้าย = ค่าที่จดมือ", x=536, y=200, color=COL_DIM, value=14)
ui.Label("ไม่ใช่ค่าที่วัดสดตอนนี้", x=536, y=222, color=COL_DIM, value=14)

# มาตรวัดเวลา: เลข ms ลอย ๆ ไม่บอกว่านานไหม เทียบกับเพดาน 85 วินาทีแล้วบอกทันที
# ui.Scale คือไม้บรรทัด ไม่มีเข็มและไม่รับ .value() ตัวที่ขยับคือ ui.Bar ที่วางทับ
ui.Label("เวลาต่อเฉลี่ย เทียบเพดาน", x=536, y=254, color=COL_DIM, value=14)
lbl_wait = ui.Label("- วินาที", x=536, y=276, color=COL_TEXT, value=20)
bar_wait = ui.Bar(x=536, y=312, w=148, h=12, color=COL_OK,
                  min=0, max=WAIT_CEILING_MS, value=0)
sc_wait = ui.Scale(x=536, y=328, w=148, h=44, color=COL_TEXT,
                   min=0, max=WAIT_CEILING_MS // 1000)
# ไม้บรรทัดสั้น ๆ ที่มีตัวเลขหกตัวจะทับกันจนอ่านไม่ออก - เอาแค่สามพอ
sc_wait.ticks(11, 5)
ui.poll()

# --- ท่าที่ 4: ไล่พิมพ์ทีละแถว ---
# unpack สี่ช่องใส่สี่ตัวแปรในคราวเดียว ถ้าเขียน row[0] row[1] คนอ่านจะไม่รู้ว่าช่องไหนคืออะไร
# ถ้าทีมไหนเผลอพิมพ์แถวที่มีสามช่อง บรรทัด for นี้จะ error ทันที - และนั่นเป็นเรื่องดี
for name, cond, hit, ms in TRIALS:
    # เลือกแท็กสีตามผล เขียวเมื่อต่อติด แดงเมื่อไม่ติด - ตาอ่านสีได้ก่อนตัวอักษร
    mark = "<span class=ok>ต่อติด</span>" if hit else "<span class=error>ไม่ติด</span>"

    # แถวที่ยาวที่สุดในตัวอย่างนี้กินราว 91 ไบต์ ยังห่างจากเพดาน 127 ไบต์ต่อครั้ง
    # ถ้าทีมจดเงื่อนไขยาวกว่านี้ ให้ย่อในตัวแปร cond ไม่ใช่ไปย่อตอนพิมพ์
    lcd.print(name, "|", cond, "|", mark, "|", ms, "ms")

    # แถวเดียวกันลงตารางบนจอด้วย ลิ้นชักตอบว่า "ที่ผ่านมาเกิดอะไร"
    # ตารางตอบว่า "สรุปแล้วผลเป็นยังไง" - คนละคำถาม จึงต้องมีทั้งคู่
    # ช่องผลเขียนเป็นคำ ไม่ใช่ระบายสีอย่างเดียว ภาพขาวดำก็ยังอ่านออก
    tbl.add_row(name, cond, "ต่อติด" if hit else "ไม่ติด", str(ms))
    ui.poll()

    # หน่วงให้แถวไล่ขึ้นทีละบรรทัด ดูทันว่ากำลังพิมพ์ถึงแถวไหน
    time.sleep_ms(400)

# --- ท่าที่ 5: สรุปผลรวมของการทดลอง ---
# ตารางดิบตอบว่า "เกิดอะไรขึ้นบ้าง" บรรทัดสรุปตอบว่า "แล้วมันแปลว่าอะไร"
# ลูปนี้ใช้ row[2] row[3] แทนการ unpack เพราะรอบนี้เราสนใจแค่สองช่อง
hits = 0
total_ms = 0
for row in TRIALS:
    if row[2]:
        hits += 1
    total_ms += row[3]

# // หารแบบปัดเศษทิ้ง - ความละเอียดของผลลัพธ์ไม่ควรเกินความละเอียดของเครื่องมือวัด
# ข้อจำกัดที่ต้องรู้: ถ้าสามแถวเป็นการทดลองคนละแบบกัน เอามาเฉลี่ยรวมแล้วเลขที่ได้
# ไม่ได้อธิบายแถวไหนเลย - เลขสรุปจากของที่เทียบกันไม่ได้ ดูน่าเชื่อถือเกินจริง
# ค่าเฉลี่ยจากสามครั้งยังไม่นับว่าเป็นการวัด ให้จดต่ำสุดกับสูงสุดคู่ไปด้วยเสมอ
# เพราะช่วงของค่าบอกเรื่องที่ค่าเฉลี่ยเดี่ยว ๆ กลบไว้หมด และเวลาที่จดลงใบงาน
# ต้องเป็นเวลาที่คนยืนรอจริง ไม่ใช่แค่ช่วงที่โปรแกรมนับได้
avg_ms = total_ms // len(TRIALS)
lcd.print("สรุป: ต่อติด", hits, "จาก", len(TRIALS), "ครั้ง")
lcd.print("เวลาที่ใช้ต่อ เฉลี่ย", avg_ms, "ms")

# มาตรวัดขยับครั้งเดียวหลังคำนวณเสร็จ ไม่ใช่ขยับตามทุกแถวระหว่างลูป
# ตัวเลขที่กระพริบเร็วกว่าวินาทีละครั้ง คนอ่านไม่ทัน และไม่มีใครได้ประโยชน์จากมัน
bar_wait.value(avg_ms)
lbl_wait.text(str(avg_ms // 1000) + " วินาที")
ui.poll()

# --- ท่าที่ 6: ต่อ WiFi แล้วรายงาน IP ---
# พิมพ์คำเตือนก่อนเรียก ไม่ใช่หลัง เพราะ wifi.connect() บล็อกทั้งบรรทัด
# และถ้ารหัสผิด มันใช้เวลานานถึงราว 85 วินาทีกว่าจะยอมแพ้ ถ้าพิมพ์ทีหลัง
# คนดูจะเห็นจอค้างเปล่า ๆ แล้วสรุปเองว่าบอร์ดแฮงก์
lcd.print("<span class=muted>กำลังต่อ WiFi รอได้ถึง 85 วินาที</span>")

# รับสองอาร์กิวเมนต์ตามตำแหน่งเท่านั้น (ssid, password) และคืน True/False
# มันไม่ยกข้อยกเว้น เราจึงต้องเช็กค่าที่คืนมาเอง ไม่มีใครเตือนเรา
ok = wifi.connect(WIFI_SSID, WIFI_PASS)

if ok:
    lcd.print("<span class=ok>WiFi OK - IP " + wifi.ip() + "</span>")
    # ไฟสลับกันสองดวง ดวงที่ดับจะหรี่ลง ไม่ใช่หายไป คนดูจึงยังเห็นว่ามีดวงนั้นอยู่
    led_up.value(1)
    led_down.value(0)
    lbl_ip.text("IP: " + wifi.ip())
else:
    # มี else เสมอ - โปรแกรมที่รายงานเฉพาะตอนสำเร็จ จะเงียบสนิทตอนล้มเหลว
    # ซึ่งเป็นจังหวะที่คนใช้ต้องการข้อมูลมากที่สุด
    lcd.print("<span class=muted>ต่อไม่สำเร็จ ตรวจ SSID และรหัสผ่าน</span>")
    led_up.value(0)
    led_down.value(1)
    lbl_ip.text("IP: ต่อไม่สำเร็จ")
ui.poll()

print("จบการบันทึกผล - ถ้าจอเงียบ เช็กว่าเข้าเมนู Playground หรือยัง")
