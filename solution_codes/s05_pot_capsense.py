# สร้างนอกลูป เพราะฟิลเตอร์ต้องจำค่าเดิมข้ามรอบ ถ้าเผลอสร้างในลูป
# ทุกรอบจะได้ตัวใหม่ที่ความจำว่างเปล่า ค่าที่ออกมาจะเท่ากับค่าดิบเป๊ะ ๆ
# แล้วเราจะสรุปผิดว่า "ฟิลเตอร์ไม่ทำงาน" - alpha เป็น keyword-only ห้ามเขียน dsp.EMA(0.2)
