# ทำไมเป็น 0.2 ไม่ใช่ 0.5: examples/s05/06_ema_time_constant.py แปลง alpha ให้เป็นเวลาจริง
# ด้วย tau = dt * (1-alpha)/alpha ที่คาบ 200 ms ของไฟล์นี้ alpha 0.2 คือ tau ราว 0.8 วินาที
# ซึ่งเป็นความหน่วงที่มือคนยังรู้สึกว่าเข็มตามทัน เลือกจากตัวเลขนั้น ไม่ใช่จากความรู้สึก
# และถ้าสัญญาณของทีมมีค่าหลุดโด่ง ๆ เป็นครั้งคราว examples/s05/07_median_beats_mean.py
# แสดงว่าทำไมงานแบบนั้น median ชนะค่าเฉลี่ยขาดลอย - ค่าที่หลุดไปนอนริมแถว ไม่มีสิทธิ์ถูกหยิบ
