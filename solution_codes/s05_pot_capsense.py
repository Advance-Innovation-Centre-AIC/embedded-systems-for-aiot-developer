# --- ท่าที่ 5: ลูปหลักและจังหวะที่ปลอดภัย ---
while True:
    fresh = True
    try:
        # สามบรรทัดนี้คือการถามคอร์จอสามรอบ ไม่ใช่รอบเดียว ถ้าอยากได้ทุกค่า
        # ในจังหวะเดียวกันเป๊ะ ให้ใช้ sensors.snapshot() ซึ่งได้ทั้งชุดในการถามครั้งเดียว
        raw = sensors.pot.read()          # 0 - 65535   จำนวนเต็ม ค่าดิบจาก ADC
        # โวลต์ทั้งสองบอร์ดไม่ได้วัดมาตรง ๆ แต่คำนวณจากเปอร์เซ็นต์คูณแรงดันอ้างอิง 3.3 V
        # และค่าอ้างอิงตัวนั้นยังไม่มีใครเอามิเตอร์ไปจิ้มขาลูกบิดยืนยันบนบอร์ดไหนเลย
        # (Eva Kit ต่อที่ P15[1] ส่วน Dev Kit คือ VR1 บนฐาน QWA309) จึงใช้ดูแนวโน้มได้
        # แต่อย่าเพิ่งเอาไปเถียงกับมัลติมิเตอร์
        # เหตุผลที่ต้องระวังคำว่า "โวลต์" ขนาดนี้ examples/s05/05_adc_counts_to_volts.py อธิบายไว้ครบ
        # เลขจาก ADC ไม่ใช่แรงดัน มันคือ "จำนวนขั้น" การจะเรียกว่าโวลต์ได้ต้องรู้แรงดันเต็มสเกล
        # กับจำนวนบิตก่อนเสมอ ที่นี่เรารู้ไม่ครบ บรรทัดนี้จึงเป็นค่าประมาณ ไม่ใช่ค่าวัด
        volts = sensors.pot.voltage()     # 0.0 - 3.3   คำนวณจากเปอร์เซ็นต์ ไม่ใช่ค่าวัด
        pct = sensors.pot.percent()       # 0.0 - 100.0 แปลงเป็นเปอร์เซ็นต์ให้แล้ว
        # ไฟล์นี้เอาค่าจาก slider() ขึ้นจอตรง ๆ ได้ เพราะจอไม่ได้ไปสั่งอะไรต่อ
        # แต่วันที่เอาค่านี้ไปสั่งของจริง จะต้องรู้เพิ่มอีกเรื่อง - examples/s05/01_capsense_dimmer.py
        # แสดงว่าค่าสุดท้ายจะค้างอยู่ตอนปล่อยนิ้ว ไม่ได้กลับเป็นศูนย์ ต้องดูว่าค่าหยุดเปลี่ยนกี่รอบแล้ว
        # จึงจะสรุปว่านิ้วออก และ examples/s05/02_capsense_menu_wet_hand.py ต่อยอดเป็นเมนูที่ตอบกลับ
        # ด้วยจอ ไฟ และเสียง เพราะแผ่นสัมผัสไม่มีแรงต้านให้นิ้วรู้สึกเหมือนปุ่มกล
        slider = sensors.capsense.slider()    # 0 - 100 อยู่แล้ว ไม่ต้องแปลงหน่วย
        b0, b1 = sensors.capsense.buttons()   # คืน tuple สองช่อง แกะพร้อมกันได้เลย
    except OSError:
        # อ่านพลาดหนึ่งรอบไม่ควรทำให้จอดับทั้งหน้า ใช้ค่าเดิมไปก่อน
        # แต่ต้องบอกให้คนดูรู้ว่าตัวเลขบนจอตอนนี้ไม่ใช่ค่าปัจจุบันแล้ว
        fresh = False
        b0, b1 = 0, 0

    # ครอบขอบเขตก่อนส่งเข้า widget: ถ้าไดรเวอร์คืนค่าหลุดช่วงมา จอยังแสดงผลได้
    # แทนที่จะพังทั้งหน้า - ค่าที่มาจากภายนอกโปรแกรมเราควรถูกตรวจขอบเขตก่อนใช้เสมอ
    pot_bar.value(int(max(0, min(100, pct))))
    touch_bar.value(max(0, min(100, slider)))

    ema_pct = ema.update(pct)         # ป้อนค่าใหม่ ได้ค่าที่กรองแล้วกลับมาทันที

    # แถบกับไฟขยับได้ทุกรอบ เพราะตาคนอ่าน "ตำแหน่ง" ได้โดยไม่ต้องหยุดอ่าน
    # หนึ่งดวงติดเท่านั้น แผงที่ติดพร้อมกันหลายดวงคือแผงที่อ่านไม่ออก
    over = ema_pct >= th
    led_ok.value(0 if over else 1)
    led_bad.value(1 if over else 0)
    led_b0.value(1 if b0 else 0)
    led_b1.value(1 if b1 else 0)

    # --- ปุ่มเพิ่ม/ลดเกณฑ์: คนละปุ่มกันคนละทิศ ไม่ใช่ปุ่มเดียวสลับ ---
    for ev in ui.poll():
        if ev.get("type") != "clicked":
            continue
        if ev.get("handle") == btn_up.id():
            th = min(TH_MAX, th + TH_STEP)
            sp_th.value(th)
        elif ev.get("handle") == btn_dn.id():
            th = max(TH_MIN, th - TH_STEP)
            sp_th.value(th)

    # ตัวเลขที่คนต้องอ่าน เขียนใหม่ไม่เกินวินาทีละครั้ง และอยู่ตำแหน่งเดิมเสมอ
    # ตัวเลขที่วิ่งห้าครั้งต่อวินาทีคือตัวเลขที่อ่านไม่ทัน และคนจะเลิกอ่านมันไปเลย
    sec = time.ticks_ms() // 1000
    if sec != last_sec:
        last_sec = sec
        lbl_pct.text("{:.1f} %".format(pct))
        lbl_raw.text("ค่าดิบ {}".format(raw))
        lbl_volt.text("โวลต์ {:.3f} V".format(volts))
        # พิมพ์ทศนิยมสองตำแหน่งทั้งคู่โดยตั้งใจ ถ้าปัดเหลือจำนวนเต็ม
        # ความสั่นจะถูกซ่อนไปเอง แล้วบทเรียนทั้งคาบก็หายไปด้วย
        raw_line.text("ดิบ    {:.2f} %".format(pct))
        ema_line.text("กรอง  {:.2f} %".format(ema_pct))
        # ตั้งสีก่อนแล้วค่อยเขียนข้อความ สองบรรทัดนี้เป็นคำสั่งคนละครั้งข้ามคอร์
        # ถ้าเขียนข้อความก่อน จะมีเสี้ยววินาทีที่ข้อความใหม่ยังใส่สีของสถานะเก่าอยู่
        if not fresh:
            lbl_health.color(COL_WARN)
            health = "ค่าค้าง - เลขคือค่าล่าสุด"
        elif over:
            lbl_health.color(COL_BAD)
            health = "เกินเกณฑ์ {} %".format(th)
        else:
            lbl_health.color(COL_DIM)
            health = "ปกติ ต่ำกว่า {} %".format(th)

    # --- ชีพจรของช่องทางข้ามคอร์: ส่งบรรทัดสถานะซ้ำทุกรอบโดยตั้งใจ ---
    # ฝั่งจอมีตัวจับเวลาสองจังหวะ โหมดเร็ว 5 ms กับโหมดปกติ 200 ms และมันจะอยู่
    # โหมดเร็วต่อไปอีก 500 ms ทุกครั้งที่ได้รับคำสั่ง "เขียนข้อความ" หรือ "ย้าย/ย่อ/เปลี่ยนสี"
    # แต่ .value() ของแถบกับไฟ "ไม่" ปลุกโหมดนั้น ลูปที่อัปเดตเฉพาะแถบกับไฟจึงเงียบเกิน
    # ครึ่งวินาที แล้วจอจะถอยไปโหมดช้า ภาพกระตุกทั้งที่โค้ดไม่ได้เปลี่ยนสักบรรทัด
    # ข้อความที่ส่งไปนี้เท่าเดิมเกือบทุกรอบ และเฟิร์มแวร์ไม่วาดซ้ำถ้าข้อความไม่เปลี่ยน
    # เราจึงจ่ายแค่ค่าส่งข้ามคอร์ ไม่ได้จ่ายค่าวาดใหม่
    lbl_health.text(health)

    # ทำไม 200 ms ไม่ใช่ 20 ms - ลูปที่เร็วเกินจะยิงคำสั่งวาดข้ามคอร์ถี่กว่าที่ CM55 วาดทัน
    # เฟรมส่วนเกินถูกทิ้งเงียบ ๆ ไม่มี error ให้เห็น ผลคือจอกระตุกทั้งที่โค้ดดูถูกทุกบรรทัด
    time.sleep_ms(200)
