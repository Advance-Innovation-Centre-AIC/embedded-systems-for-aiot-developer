# s01_hello_lcd.py - ข้อความแรกของทีม ขึ้นจอ Eva Kit
# วิธีรัน: 1) บนจอบอร์ด แตะการ์ด Playground บนหน้า Home ก่อน (สำคัญมาก)
#          2) แก้ชื่อทีมและรายชื่อสมาชิกในโค้ดให้เป็นของทีมเราก่อน
#          3) เปิดไฟล์นี้ใน BENTO IDE กด "Program to Device" แล้วอ่านผลบนจอบอร์ด
#
# คาบนี้เราคุยกับจอผ่านโมดูล lcd: ข้อความถูกพิมพ์จากคอร์ CM33 (ฝั่งที่รัน Python)
# แล้ววิ่งข้ามกล่องจดหมาย IPC ไปให้คอร์ CM55 วาดลงจอ
# เห็นข้อความบนจอเมื่อไร แปลว่าเราคุยครบทั้งสองสมองของบอร์ดแล้ว
#
# ดูที่จอ: ท่าที่ 1-4 ส่งบรรทัดเข้าลิ้นชัก Console ที่ต้องกดเปิดเองก่อนจะเห็น
#         ท่าที่ 5 วางป้ายประจำทีมลงหน้า Playground ตรง ๆ ซึ่งค้างอยู่หลังโปรแกรมจบ
#         ปลายการ์ดล่างคือมาตรวัดไบต์ บอกว่าบรรทัดปิดท้ายกินไปเท่าไรจากเพดาน 127

import lcd
import time
import ui

# ---------- ข้อมูลของทีม (แก้สามบรรทัดนี้ให้เป็นของทีมเราก่อนรัน) ----------
TEAM_NAME = "BentoBuilders"                      # ชื่อทีม (ไทยหรืออังกฤษก็ได้)
MEMBERS = ["สมชาย", "สมหญิง", "สมศรี"]              # รายชื่อสมาชิก 2-3 คน
MOTTO = "เล่นของจริงก่อน แล้วค่อยแกะ"                 # คำขวัญทีมสั้น ๆ

# --- ท่าที่ 1: ล้างจอให้สะอาด แล้วปักหัวเรื่อง ---
# ทำไมต้อง clear ก่อน: จอ Playground อาจมีของจากโปรแกรมก่อนหน้าค้างอยู่
# เริ่มจากสถานะที่รู้แน่ (known state) เสมอ - นิสัยของงาน embedded จริง
# ที่ไฟล์นี้เลือกท่า "ล้างแล้วพิมพ์ไล่ลงมา" ไม่ใช่เพราะมันดีกว่า แต่เพราะรอบนี้พิมพ์ครั้งเดียวจบ
# examples/s01/05_clear_and_refresh.py วางท่านี้เทียบกับท่าอัปเดตค่าเดิมซ้ำที่เดิม
# และบอกจุดตัดไว้ชัด: ค่าที่เปลี่ยนถี่กว่าราว 5 ครั้งต่อวินาที ท่านี้จะกลายเป็นจอกระพริบ
lcd.clear()

# lcd.console() เขียนข้อความลงพื้นที่ console บนจอ - แท็ก <h2> ทำให้เป็นหัวเรื่องใหญ่
# แท็กต้องเปิด-ปิดครบคู่ ไม่งั้นผลบนจอจะเพี้ยน
lcd.console("<h2>AIoT in Action - คาบ 1</h2>")

# <span class=muted> คือตัวหนังสือสีจาง เหมาะกับข้อความประกอบที่ไม่ใช่พระเอก
lcd.console("<span class=muted>ทดสอบจอครั้งแรกของทีม " + TEAM_NAME + "</span>")

# --- ท่าที่ 2: ประโยคทักทายจากทีม ---
# lcd.print() รับหลายอาร์กิวเมนต์แบบเดียวกับ print() ปกติ
# มันคั่นแต่ละค่าด้วยช่องว่างให้เอง (sep=' ') เราไม่ต้องต่อสตริงเอง
lcd.print("สวัสดีจากทีม", TEAM_NAME)
lcd.print("คำขวัญของเรา:", MOTTO)

# print() ธรรมดาขึ้นที่คอนโซลของ BENTO IDE ฝั่งคอม ไม่ใช่จอบอร์ด
# มีไว้เทียบให้เห็นว่า "ปลายทาง" ของสองคำสั่งนี้คนละที่กัน
# ถ้าตอนทำเองสับสนว่าบรรทัดไหนไปไหน examples/s01/01_first_line.py ยิงข้อความออกทั้งสามทาง
# ในไฟล์เดียว แล้วบอกตำแหน่งของแต่ละทางบนจอ จะได้เลิกเดาว่าโค้ดพังหรือแค่มองผิดที่
print("ส่งข้อความทักทายขึ้นจอบอร์ดแล้ว ดูที่จอ ไม่ใช่ที่หน้าคอม")

# --- ท่าที่ 3: แนะนำสมาชิกทีละคนด้วยลูป ---
# ทำไมใช้ลูป: รายชื่ออยู่ใน list เพิ่มหรือลดสมาชิกได้โดยไม่ต้องแตะตัวลูปเลย
# ข้อมูลเป็นตัวขับการแสดงผล ไม่ใช่ copy บรรทัดซ้ำ ๆ ตามจำนวนคน
for i in range(len(MEMBERS)):
    # i นับจาก 0 ตามธรรมเนียม Python - บวก 1 ตอนแสดงผลให้คนอ่านเข้าใจง่าย
    lcd.print("สมาชิกคนที่", i + 1, ":", MEMBERS[i])
    # หน่วง 800 ms ให้ชื่อขึ้นทีละคน คนดูอ่านทัน - ถ้าไม่หน่วง ทุกชื่อจะโผล่พรึ่บเดียว
    time.sleep_ms(800)

# --- ท่าที่ 4: ปิดท้ายด้วยสถานะสีเขียว ---
# <span class=ok> คือสีเขียว "งานสำเร็จ" - จบโปรแกรมด้วยการบอกผลชัดเจนทุกครั้ง
# ทำไมต้องเป็น ok ไม่ใช่สีที่ชอบ: examples/s01/02_markup_tags.py อธิบายว่าห้าคลาสนี้คือ
# ห้าระดับความสำคัญ ไม่ใช่จานสี คนอ่านหน้างานกวาดตาหาสีแดงก่อนเสมอ ถ้าเราแจกสีตามใจ ระดับก็หมดความหมาย
# ระวังความยาวรวมต่อการเรียกหนึ่งครั้ง: อย่าเกิน 127 ไบต์ (ไทยตัวละ 3 ไบต์ = ราว 42 ตัวอักษร) เกินแล้วถูกตัดเงียบ ให้แบ่งพิมพ์
# แยกเป็นสองครั้งโดยตั้งใจ: รวมกันแล้วเกิน 127 ไบต์ ระบบจะตัดทิ้งเงียบ ๆ
# และที่ร้ายกว่านั้นคือ \n ท้ายบรรทัดหายไปด้วย บรรทัดถัดไปจะมาต่อท้ายกันเละ
# ตัวเลข 127 นี้ examples/s01/03_byte_limit.py วัดให้ดูสด ๆ ทีละก้อน จะได้ไม่ต้องเชื่อเพราะมีคนบอก
# และถ้าไม่อยากแบ่งบรรทัดด้วยมือไปตลอด examples/s01/06_safe_print.py ยกกฎนี้ไปไว้ในฟังก์ชัน
# ด้วยเหตุผลข้อเดียว: ความรู้ที่ต้องอาศัยวินัยของคนทุกครั้ง จะพังในวันที่คนเหนื่อย
TAIL = "ทีม " + TEAM_NAME + " พร้อมลุยคาบต่อไป"
lcd.print("<span class=ok>ขึ้นจอสำเร็จ</span>")
lcd.print("<span class=ok>" + TAIL + "</span>")

# --- ท่าที่ 5: ป้ายประจำทีมบนหน้าจอ - ของที่ lcd ทำแทนไม่ได้ ---
# สี่ท่าที่ผ่านมาทุกบรรทัดไปเข้าคิวในลิ้นชัก Console ซึ่งต้องกดเปิดเองถึงจะเห็น
# ป้ายที่คนเดินผ่านโต๊ะต้องอ่านได้ทันทีจึงเป็นงานของโมดูล ui ไม่ใช่ของ lcd
# ui.screen() ล้างหน้า Playground ให้ว่าง แล้วหน่วงให้ CM55 ล้างเสร็จก่อนวางของ
ui.screen()
time.sleep_ms(200)

COL_TEXT, COL_DIM = 0xFFFFFF, 0xA0B4CC
COL_CARD, COL_OK, COL_RUN = 0x142240, 0x00E676, 0x4FC3F7
BYTE_LIMIT = 127

# ui.Panel คือพื้นหลังของการ์ด ของอื่นวางทับได้ - min คือสีขอบ max คือความมน value คือความหนาขอบ
ui.Panel(x=16, y=6, w=760, h=372, color=COL_CARD, min=COL_DIM, max=12, value=1)
ui.Label("ป้ายประจำทีม", x=32, y=14, color=COL_DIM, value=18)
ui.Label(TEAM_NAME, x=32, y=40, color=COL_TEXT, value=28)
ui.Label(MOTTO, x=32, y=84, color=COL_DIM, value=18)

# ui.Table จัดคอลัมน์ให้เอง ถ้าเรียง ui.Label เองต้องนับพิกเซลทุกแถว และพอชื่อยาว
# ไม่เท่ากัน คอลัมน์ที่สองจะเยื้องกันจนอ่านไม่ออก - ตารางจริงแก้ปัญหานี้ให้ตั้งแต่แรก
# แถวหนึ่งสูงราว 62 พิกเซล ตารางหัวหนึ่งแถวบวกสมาชิกสามคนจึงต้องการความสูง 250
tbl = ui.Table(x=32, y=114, w=340, h=252, cols=2)
tbl.col_width(0, 100)
tbl.col_width(1, 230)
tbl.add_row("ลำดับ", "ชื่อสมาชิก")

# ไฟสองดวงแทนการเขียนสถานะด้วยสีตัวอักษร ไฟมีทั้งรูปทรงและความสว่าง
# ถ่ายรูปจอเป็นขาวดำแล้วยังแยกออกว่าดวงไหนติด ส่วนตัวหนังสือสีเขียวกับสีเทาแยกไม่ออก
ui.Label("สถานะการเขียนตาราง", x=400, y=114, color=COL_DIM, value=16)
led_run = ui.Led(x=406, y=142, w=34, h=34, color=COL_RUN, value=1)
ui.Label("กำลังเขียน", x=452, y=148, color=COL_DIM, value=18)
led_done = ui.Led(x=406, y=186, w=34, h=34, color=COL_OK, value=0)
ui.Label("เขียนครบแล้ว", x=452, y=192, color=COL_DIM, value=18)

# ลูปนี้เดินรายชื่อชุดเดิมกับท่าที่ 3 แต่ปลายทางคนละที่ - นั่นคือประเด็นทั้งหมดของคาบนี้
# ท่าที่ 3 พิมพ์เข้าลิ้นชัก ท่านี้เขียนลงตารางบนจอ ข้อมูลชุดเดียวไปได้สองที่พร้อมกัน
for i in range(len(MEMBERS)):
    tbl.add_row(str(i + 1), MEMBERS[i])
    ui.poll()
    time.sleep_ms(500)

# value(0) ทำให้ไฟ "หรี่" ไม่ใช่ "หาย" โดยตั้งใจ - ดวงที่หายไปตอนดับ ทำให้คนดู
# แยกไม่ออกว่าดับจริงหรือจอเสีย ส่วนดวงที่หรี่อยู่ยังยืนยันว่าจอยังวาดอยู่
led_run.value(0)
led_done.value(1)

# --- มาตรวัดไบต์: ตัวเลขลอย ๆ ไม่บอกว่าใกล้เพดานแค่ไหน มาตรวัดบอก ---
# ภาษาไทยตัวละ 3 ไบต์ บรรทัดที่ดูสั้นบนจอคอมจึงกินโควตาเร็วกว่าที่ตาประเมิน
used = len(TAIL.encode())
ui.Label("ความยาวบรรทัดปิดท้าย จากเพดาน 127", x=400, y=240, color=COL_DIM, value=16)
ui.Bar(x=406, y=270, w=330, h=14, color=COL_OK, min=0, max=BYTE_LIMIT, value=used)
ui.Scale(x=406, y=288, w=330, h=44, color=COL_TEXT, min=0, max=BYTE_LIMIT)
ui.Label(str(used) + " ไบต์", x=406, y=336, color=COL_TEXT, value=20)
ui.poll()

# ปิดท้ายฝั่งคอมด้วย เผื่อทีมไหนจอมีปัญหา จะได้รู้ว่าโค้ดรันจบจริง
print("โปรแกรมจบแล้ว ถ้าจอไม่ขึ้นข้อความ เช็กว่าเข้าเมนู Playground หรือยัง")
