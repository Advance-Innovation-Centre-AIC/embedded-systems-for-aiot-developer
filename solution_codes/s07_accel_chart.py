# s07_accel_chart.py - กราฟความเร่งสามแกนแบบสด + ตารางสรุปสามแกน
# วิธีรัน: 1) บนจอบอร์ด แตะการ์ด Playground ค้างไว้ แล้ววางบอร์ดให้ขยับได้อิสระ
#          2) กด Program to Device แล้วโยกบอร์ดเบา ๆ ดูสามเส้นแยกกันชัดเจน
#          3) กด "หยุดบันทึก" ค้างภาพไว้อ่านตาราง แล้วกด "เริ่มบันทึก" ให้กราฟเดินต่อ
#
# Chart รับได้สูงสุด 4 เส้น เก็บได้เส้นละ 50 จุด และ set_next() รับเฉพาะจำนวนเต็ม
# ตัวเลข loop ms บนจอไม่ใช่ของประดับ มันคือหลักฐานว่าคาบที่เราตั้งไว้เกิดขึ้นจริงหรือไม่
#
# ดูที่จอ: ซ้ายคือกราฟสามเส้น ขวาคือตารางต่ำสุด-สูงสุด-ล่าสุดของทั้งสามแกน
#         แถบล่างคือไฟบอกว่ากำลังบันทึกอยู่ไหม คาบลูปจริง และปุ่มเริ่มกับปุ่มหยุดที่แยกกัน
# กับดัก : กราฟบอก "รูปร่างตามเวลา" แต่ตอบไม่ได้ว่าค่าสูงสุดที่ผ่านมาคือเท่าไร
#         เพราะจุดที่เก่ากว่า 50 จุดถูกเขี่ยออกไปแล้ว ตารางจึงไม่ใช่ของซ้ำซ้อนกับกราฟ
#         มันตอบคนละคำถามกัน และ ui.Led สั่ง .value(0) แล้ว "หรี่" ไม่ใช่ "หาย"
#         โดยตั้งใจ ไฟที่หายไปตอนดับ ทำให้คนดูแยกไม่ออกว่าดับจริงหรือจอเสีย

import ui
ui.screen()
import time
import sensors

COL_TEXT, COL_DIM = 0xFFFFFF, 0xA0B4CC
COL_CARD = 0x142240
COL_AX = 0xFF5252      # X แดง
COL_AY = 0x00E676      # Y เขียว
COL_AZ = 0x448AFF      # Z น้ำเงิน
COL_RUN = 0x4FC3F7
# 200 ms คือ 5 ตัวอย่างต่อวินาที เลือกให้พอดีกับสองอย่าง คือมือคนที่โยกบอร์ดได้ไม่เร็วกว่านี้มาก
# และ CM55 ที่ต้องวาดทัน ราคาที่จ่ายคือการสั่นเร็ว ๆ ทั้งหมดหายไปจากกราฟนี้ ไม่ใช่แค่เบาลง
# examples/s07/03_aliasing_nyquist.py แสดงราคานั้นให้เห็นเป็นภาพ คือคลื่นจริงกับคลื่นที่เครื่อง
# คิดว่าเห็น วางทับกันจนถึงจุดที่มันแยกจากกัน และกฎคือ fs > 2*f ไม่ใช่ fs >= 2*f
PERIOD_MS = 200        # คาบการสุ่มที่เราเลือก

# --- ท่าที่ 1: เตรียมเซนเซอร์และหน้าจอให้พร้อม ---
# Eva Kit ไม่มี sensors.init() ให้เรียก IMU อยู่บนบัสที่คอร์จอ (CM55) ถือไว้คนเดียว
# ฝั่ง Python ขอค่าที่คอร์จออ่านเก็บไว้ให้ทุก 200 ms จึงเรียก motion() ได้เลย
# ถ้าเผลอเรียก sensors.init() จะได้ OSError ทันที ไม่ใช่ค้าง
#
# แต่หลังรีเซ็ต คอร์จอเริ่มตอบเรื่องเซนเซอร์ราว 13 วินาที การอ่านครั้งแรก
# จึงนิ่งได้ถึง 16 วินาที ครั้งถัดไปเร็วปกติ อุ่นเครื่องหนึ่งครั้งตรงนี้
# ให้การรอไปเกิดก่อนสร้างกราฟ ไม่ใช่ระหว่างที่กราฟควรจะเดินแล้ว
try:
    sensors.bmi270.motion()
except OSError:
    print("คอร์จอยังไม่ตอบรอบแรก จะลองใหม่ในลูป")

ui.clear()
time.sleep_ms(200)

ui.Label("กราฟความเร่งสามแกน หน่วย m/s2", x=16, y=6, color=COL_TEXT, value=24)

# --- ท่าที่ 2: กราฟหนึ่งใบ สามเส้น และตารางสรุปข้าง ๆ ---
# min/max คือขอบแกน Y ตั้ง -20..20 เพราะแรงโน้มถ่วงอยู่ที่ 9.81 มีที่เหลือให้โยกได้อีกเท่าตัว
# เส้นแรกคือ series 0 ที่มากับตัว Chart เอง (สีจาก color=) ไม่ต้อง add_series ให้มัน
chart = ui.Chart(x=12, y=38, w=330, h=280, min=-20, max=20, color=COL_AX)
s_ay = chart.add_series(COL_AY)      # คืนค่าเป็น "หมายเลข series" ต้องเก็บไว้ใช้ตอน set_next
s_az = chart.add_series(COL_AZ)

# ตารางแทนการเรียง Label หลายบรรทัดให้ดูเหมือนตาราง: ui.Table จัดคอลัมน์ให้เอง
# ไม่ต้องนับพิกเซลทีละแถว และพอค่าติดลบเข้ามา ความยาวข้อความเปลี่ยน คอลัมน์ก็ยังตรง
#
# ความกว้างคอลัมน์ต้องตั้งให้กว้างพอสำหรับข้อความที่ยาวที่สุดในคอลัมน์นั้น
# ถ้าแคบไป ข้อความจะขึ้นบรรทัดใหม่ แล้วความสูงของ "ทุกแถว" จะเด้งเป็นสองเท่าทันที
# ตารางหัวหนึ่งแถวบวกสามแกนจึงต้องการความสูง 280 พอดี
# value= ของ ui.Table คือขนาดฟอนต์ในช่อง ถ้าไม่บอกจะได้ 20 ซึ่งกว้างกว่าที่คิด
tbl = ui.Table(x=352, y=38, w=436, h=280, cols=4, value=16)
tbl.col_width(0, 100)
tbl.col_width(1, 108)
tbl.col_width(2, 108)
tbl.col_width(3, 108)
tbl.add_row("แกน", "ต่ำสุด", "สูงสุด", "ล่าสุด")
tbl.add_row("X", "-", "-", "-")
tbl.add_row("Y", "-", "-", "-")
tbl.add_row("Z", "-", "-", "-")

# --- ท่าที่ 3: ไฟบอกสถานะ และปุ่มเริ่มกับปุ่มหยุดที่แยกกันคนละปุ่ม ---
# ปุ่มเดียวที่สลับไปมาบอกไม่ได้ว่าตอนนี้อยู่สถานะไหน คนกดจึงต้องเดา และเดาผิดได้เสมอ
# แผงจริงจึงแยกปุ่มเริ่มกับปุ่มหยุดออกจากกัน แล้วให้ไฟเป็นคนบอกสถานะปัจจุบัน
ui.Panel(x=12, y=326, w=676, h=62, color=COL_CARD, min=COL_DIM, max=12, value=1)
led_rec = ui.Led(x=24, y=340, w=26, h=26, color=COL_RUN, value=1)
lbl_rec = ui.Label("กำลังบันทึก", x=58, y=342, color=COL_TEXT, value=16)
rec_msg = "กำลังบันทึก"       # ข้อความสถานะล่าสุด เปลี่ยนเฉพาะตอนกดปุ่ม
lbl_dt = ui.Label("คาบลูป -- ms", x=196, y=342, color=COL_DIM, value=16)
btn_start = ui.Button("เริ่มบันทึก", x=380, y=332, w=140, h=50,
                      color=0x1B5E20, value=16)
btn_stop = ui.Button("หยุดบันทึก", x=530, y=332, w=140, h=50,
                     color=0x37474F, value=16)
start_id = btn_start.id()
stop_id = btn_stop.id()
ui.poll()

running = True
last_ms = time.ticks_ms()
dt = PERIOD_MS
last_sec = -1                    # วินาทีที่เพิ่งเขียนตัวเลขลงจอ
ax, ay, az = 0.0, 0.0, 9.81      # ค่าตั้งต้น เผื่อรอบแรกยังอ่านไม่ได้
# ต่ำสุด สูงสุด และค่าล่าสุดของสามแกน เก็บเป็นลิสต์เรียงตาม X Y Z
# ตั้งต้นด้วย None แล้วเติมค่าจริงในรอบแรก ดีกว่าตั้งด้วยเลขมหาศาลที่คนอ่านโค้ดต้องมาเดา
lo = [None, None, None]
hi = [None, None, None]


def note(i, v):
    """จำค่าต่ำสุดกับสูงสุดของแกนหนึ่ง - กราฟจำให้ไม่ได้เพราะจุดเก่าถูกเขี่ยทิ้ง"""
    if lo[i] is None or v < lo[i]:
        lo[i] = v
    if hi[i] is None or v > hi[i]:
        hi[i] = v


def cell(v):
    return "-" if v is None else "{:+.2f}".format(v)


while True:
    # --- ท่าที่ 4: อ่านหกแกนจาก snapshot ชุดเดียว แล้วป้อนสามเส้น ---
    if running:
        # motion() คืนหกแกนที่มาจากการอ่านครั้งเดียวกันของคอร์จอ จึงเป็นชุดที่สอดคล้องกัน
        # ต่างจากเรียก acceleration() แล้ว gyroscope() ซึ่งเป็นคนละจังหวะ
        # อ่านพลาดหนึ่งรอบไม่ควรทำให้กราฟดับทั้งหน้า ใช้ค่าเดิมไปก่อนแล้วลองใหม่รอบหน้า
        try:
            ax, ay, az, gx, gy, gz = sensors.bmi270.motion()
        except OSError:
            pass

        # int() จำเป็น: ส่ง float เข้าไปตรง ๆ จะได้ TypeError ทันที
        # ถ้าอยากได้ความละเอียดกว่านี้ ให้คูณ 100 แล้วขยาย min/max เป็น -2000..2000
        # ท่าคูณก่อนป้อนนั้นใช้จริงอยู่ใน examples/s07/01_imu_vibration_monitor.py
        # ซึ่งคูณค่า RMS ขึ้นพันเท่าก่อนเข้ากราฟ เพราะค่าที่มันวัดเล็กกว่าหนึ่งขั้นของกราฟทั้งชุด
        # ไฟล์นี้ไม่ต้องทำ เพราะความเร่งเป็นหน่วยที่ใหญ่พออยู่แล้ว - นั่นคือความต่างของสองงาน
        chart.set_next(0, int(ax))
        chart.set_next(s_ay, int(ay))
        chart.set_next(s_az, int(az))
        # ตารางเก็บของที่กราฟเก็บไม่ได้: ค่าสุดขีดที่ผ่านไปแล้วเกิน 50 จุด
        note(0, ax)
        note(1, ay)
        note(2, az)

    # --- ท่าที่ 5: วัดคาบลูปจริงแล้วรายงาน ---
    # ticks_diff() จัดการเรื่องตัวนับวนกลับให้เอง อย่าลบกันตรง ๆ ด้วย -
    now = time.ticks_ms()
    dt = time.ticks_diff(now, last_ms)
    last_ms = now

    # poll ทุกรอบไม่ว่าจะหยุดบันทึกอยู่หรือไม่ ถ้ากั้น poll ไว้ใน if running ปุ่มจะกดไม่ได้ตลอดกาล
    # กฎข้อนี้เขียนไว้เป็นตัวหนังสือแล้วที่ examples/s07/01_imu_vibration_monitor.py
    # "หยุดกราฟคือหยุดวาด ไม่ใช่หยุดทำงาน" - ปุ่มหยุดที่ฆ่าทางกลับของตัวเอง เป็นบั๊กที่เจอบ่อยที่สุด
    # ในหน้าที่มีปุ่มหยุด และมันดูเหมือนจอค้าง ทั้งที่โปรแกรมยังวิ่งอยู่ครบทุกบรรทัด
    for ev in ui.poll():
        h = ev.get('handle')
        if h == start_id:
            running = True
            # เริ่มรอบใหม่ = ล้างค่าสุดขีดของรอบเก่าทิ้ง ไม่งั้นตารางจะปนสองรอบเข้าด้วยกัน
            lo = [None, None, None]
            hi = [None, None, None]
            led_rec.value(1)
            lbl_rec.color(COL_TEXT)
            rec_msg = "กำลังบันทึก"
        elif h == stop_id:
            running = False
            # ไฟที่ดับจะ "หรี่" ไม่ใช่หายไป ดวงที่หายไปทำให้คนดูแยกไม่ออกว่าดับหรือจอเสีย
            led_rec.value(0)
            lbl_rec.color(COL_DIM)
            rec_msg = "หยุดแล้ว ตัวเลขคือค่าล่าสุด"


    # --- ชีพจรของช่องทางข้ามคอร์: ส่งบรรทัดสถานะซ้ำทุกรอบโดยตั้งใจ ---
    # ฝั่งจอมีตัวจับเวลาสองจังหวะ โหมดเร็ว 5 ms กับโหมดปกติ 200 ms และมันจะอยู่
    # โหมดเร็วต่อไปอีก 500 ms ทุกครั้งที่ได้รับคำสั่ง "เขียนข้อความ" หรือ "ย้าย/ย่อ/เปลี่ยนสี"
    # แต่ set_next() ของกราฟกับ .value() ของไฟ "ไม่" ปลุกโหมดนั้น ลูปที่ป้อนแต่กราฟ
    # จึงเงียบเกินครึ่งวินาที แล้วจอถอยไปโหมดช้า เส้นกระตุกทั้งที่โค้ดไม่ได้เปลี่ยน
    # ข้อความที่ส่งไปนี้เท่าเดิมเกือบทุกรอบ และเฟิร์มแวร์ไม่วาดซ้ำถ้าข้อความไม่เปลี่ยน
    # เราจึงจ่ายแค่ค่าส่งข้ามคอร์ ไม่ได้จ่ายค่าวาดใหม่
    lbl_rec.text(rec_msg)

    # ตัวเลขที่คนต้องอ่าน เขียนใหม่ไม่เกินวินาทีละครั้ง และอยู่ตำแหน่งเดิมเสมอ
    # เส้นกราฟยังเดินห้าครั้งต่อวินาทีตามเดิม เพราะตาคนอ่าน "รูปร่าง" ได้โดยไม่ต้องหยุดอ่าน
    # ส่วนตัวเลขสามตำแหน่งทศนิยมที่วิ่งเท่ากันนั้น อ่านไม่ทัน แล้วคนจะเลิกอ่านมันไปเลย
    sec = time.ticks_ms() // 1000
    if sec != last_sec:
        last_sec = sec
        # .cell(แถว, คอลัมน์, ข้อความ) เขียนทับช่องเดิม ไม่ได้เพิ่มแถวใหม่
        # แถว 0 คือหัวตาราง แกน X Y Z จึงเป็นแถว 1 2 3
        for i, v in enumerate((ax, ay, az)):
            tbl.cell(i + 1, 1, cell(lo[i]))
            tbl.cell(i + 1, 2, cell(hi[i]))
            tbl.cell(i + 1, 3, "{:+.2f}".format(v))
        # อัปเดต Label ในลูปเสมอ - การส่งงานเข้า IPC สม่ำเสมอคือสิ่งที่ทำให้ช่องทาง
        # ข้ามคอร์อยู่ในโหมดเร็ว ถ้าเงียบไปหลายรอบมันจะถอยไปโหมดช้า และค่า dt ที่เห็น
        # จะกระโดดขึ้นทันทีทั้งที่ PERIOD_MS ไม่ได้เปลี่ยน
        lbl_dt.text("คาบลูป {} ms".format(dt))

    # หน่วงเท่าเดิมเสมอ ไม่ว่าจะหยุดบันทึกหรือไม่ ถ้าตอนหยุดปล่อยลูปวิ่งฟรี
    # CM55 จะโดนยิงคำสั่ง poll ถี่ยิบโดยไม่ได้อะไรกลับมาเลย
    time.sleep_ms(PERIOD_MS)
