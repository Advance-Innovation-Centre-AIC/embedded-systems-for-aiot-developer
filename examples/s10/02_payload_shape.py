# 02_payload_shape.py - รูปร่างของ payload ตัดสินว่าฝั่งรับทำงานง่ายหรือยาก
#
# Why : บอร์ดหนึ่งตัวส่งทุก 5 วินาที = 17,280 ใบต่อวัน ทุกไบต์ที่เกินจำเป็นใน
#        หนึ่งใบถูกคูณด้วยหมื่นทุกวัน และคนที่มาอ่านโค้ดอีกหกเดือนคือคนที่ต้อง
#        เดาว่า a กับ b คืออะไร ขนาดกับความอ่านออกจึงต้องชั่งพร้อมกัน
# What: payload ที่ดีคือเล็ก คงที่ มีหน่วย และมีตัวตนของอุปกรณ์ "คงที่" แปลว่า
#        ทุกใบมีคีย์ชุดเดิม ไม่ใช่บางรอบมีบางรอบไม่มี
#
# ดูที่จอ: แท่งสามแท่งยาวไม่เท่ากัน แท่งบนสุดยาวที่สุดทั้งที่ให้ข้อมูลน้อยกว่า
#          แท่งล่างสุด และเลขใหญ่บอกว่าใบที่ใช้จริงกินกี่ไบต์
# กับดัก : ส่งตัวเลขเป็นสตริง เช่น "25.5" ฝั่ง dashboard จะขึ้นค่าให้อ่านได้
#          แต่วาดกราฟไม่ได้ เพราะมันไม่ใช่ตัวเลขในสายตาของโปรแกรมฝั่งนั้น

import ui
import lcd
import json
import time

DEVICE_ID = "eva-team03"

COL_TEXT, COL_DIM = 0xFFFFFF, 0xA0B4CC
COL_CARD = 0x142240
COL_TRACK = 0x27364F         # สีรางของ ui.Bar - ตัวแท่งที่วิ่งเป็นสีของธีมเสมอ
COL_OK, COL_WARN, COL_BAD = 0x00E676, 0xFFA726, 0xFF5252

# ค่าที่จะส่ง วันนี้ยังไม่ต้องมาจากของจริง ใช้ตัวนับกับนาฬิกาไปก่อน
# ประเด็นของไฟล์นี้คือรูปร่างของข้อความ ไม่ใช่ที่มาของตัวเลข
count = 7
uptime_ms = time.ticks_ms()

# แบบที่หนึ่ง: หลวมเกินไป
# ทศนิยมสิบสี่ตำแหน่งไม่ได้บอกอะไรเพิ่ม นอกจากกินแบนด์วิดท์ทั้งสองฝั่ง
# ชื่อคีย์ยาวเกินจำเป็น และไม่มีตัวตนของอุปกรณ์อยู่ในข้อความเลย
loose = {"temperature_value_in_celsius": 25.123456789012345,
         "the_counter": count}

# แบบที่สอง: แน่นเกินไปจนคนอ่านไม่ออก
# ประหยัดไบต์ได้จริง แต่หกเดือนถัดมาไม่มีใครรู้ว่า a กับ b คืออะไร
too_tight = {"a": 25.1, "b": count}

# แบบที่สาม: พอดี - ชื่อสั้นแต่ยังเดาออก ปัดทศนิยม มีหน่วย มีตัวตน มีเวลา
good = {"id": DEVICE_ID,
        "count": count,
        "uptime_s": uptime_ms // 1000,
        "unit": "s"}

SHAPES = (("หลวมเกินไป", loose, COL_BAD),
          ("แน่นเกินไป", too_tight, COL_WARN),
          ("พอดี", good, COL_OK))

# len() ของสตริง ASCII เท่ากับจำนวนไบต์ที่จะวิ่งบนสาย ใช้เทียบขนาดได้ตรง ๆ
texts = [json.dumps(obj) for _, obj, _ in SHAPES]
sizes = [len(t) for t in texts]
widest = max(sizes)     # แท่งที่ยาวที่สุดเป็นตัวตั้งของสเกล อีกสองแท่งเทียบกับมัน

ui.screen()
time.sleep_ms(200)

ui.Label("payload สามแบบ วัดเป็นไบต์", x=20, y=12, color=COL_TEXT, value=24)

# การ์ดซ้าย: สามแท่ง สเกลเดียวกัน ความยาวคือจำนวนไบต์ล้วน ๆ
ui.Panel(x=20, y=52, w=440, h=180, color=COL_CARD, min=COL_DIM, max=12, value=1)
row_y = 64
for i in range(3):
    name, _, col = SHAPES[i]
    ui.Label("{}  {} bytes".format(name, sizes[i]), x=36, y=row_y,
             color=col, value=16)
    # color ของ ui.Bar คือสี "ราง" ไม่ใช่สีแท่ง ตัวแท่งที่วิ่งเป็นสีของธีมตายตัว
    # ความหมายจึงอยู่ที่ความยาว ส่วนสีของหัวข้อข้างบนเป็นตัวบอกว่าแบบไหนดีไม่ดี
    ui.Bar(x=36, y=row_y + 22, w=404, h=18, min=0, max=widest, value=sizes[i],
           color=COL_TRACK)
    row_y += 54

# การ์ดขวา: ใบที่จะใช้จริงกินกี่ไบต์ Seg7 รับ "ข้อความ" เท่านั้น
# seg.value(62) เงียบสนิทไม่ขึ้นอะไรเลย ต้อง seg.text("62")
ui.Panel(x=475, y=52, w=195, h=180, color=COL_CARD, min=COL_OK, max=12, value=1)
ui.Label("ใบพอดี กินกี่ไบต์", x=490, y=76, color=COL_DIM, value=16)
seg = ui.Seg7(text=str(sizes[2]), x=490, y=116, w=165, h=76, color=COL_OK)
# หน่วยวางใต้ตัวเลข ไม่ใช่ทับบนมัน Seg7 สูง 76 จึงจบที่ y=192
ui.Label("bytes", x=490, y=198, color=COL_DIM, value=16)

# ตัวเลขต้องเป็นตัวเลข ไม่ใช่สตริง สองบรรทัดนี้ต่างกันแค่เครื่องหมายคำพูดคู่เดียว
ui.Label('ตัวเลข  {"v": 25.5}    ฝั่งรับวาดกราฟได้', x=20, y=252,
         color=COL_OK, value=18)
ui.Label('สตริง   {"v": "25.5"}  ฝั่งรับวาดกราฟไม่ได้', x=20, y=284,
         color=COL_BAD, value=18)
# แยกสองป้ายให้อยู่ในเพดาน 126 ไบต์ของ ui.Label - ไทยหนึ่งตัวกิน 3 ไบต์
ui.Label("สั้นแต่ยังเดาออก", x=20, y=330, color=COL_DIM, value=18)
ui.Label("มีหน่วย มีตัวตน มีเวลา", x=200, y=330, color=COL_DIM, value=18)
ui.poll()

# lcd เก็บ JSON ตัวเต็มไว้ให้อ่านทีละบรรทัด จอเก็บการเปรียบเทียบ
lcd.clear()
lcd.console("<h2>คาบ 10 - รูปร่างของ payload</h2>")
for i in range(3):
    lcd.print("{} {} bytes".format(SHAPES[i][0], sizes[i]))
    lcd.print("  ", texts[i])

lcd.print("ส่งเป็นตัวเลข", json.dumps({"v": 25.5}))
# หมายเหตุ: lcd.print ตีความ markup ข้อความที่ขึ้นต้นด้วย < จะถูกกลืนหายไปทั้งก้อน
lcd.print("ส่งเป็นสตริง", json.dumps({"v": "25.5"}), "(วาดกราฟไม่ได้)")

# ห่อไว้ใต้คีย์ "data" เมื่อฝั่งแพลตฟอร์มต้องการแยกส่วนข้อมูลออกจากส่วนหัว
# คาบ 11 ใช้รูปนี้ ดังนั้นออกแบบให้เข้ากันตั้งแต่วันนี้จะได้ไม่ต้องรื้อ
wrapped = {"data": good}
lcd.print("รูปที่แพลตฟอร์มคาดหวัง")
lcd.print("  ", json.dumps(wrapped))

# แกะกลับด้วย json.loads() แล้วต้องได้ของเดิมทุกช่อง
# ถ้าแกะแล้วได้ไม่ครบ แปลว่าตอนประกอบมีของที่ JSON แทนไม่ได้ปนอยู่
back = json.loads(json.dumps(wrapped))
lcd.print("แกะกลับได้ id =", back["data"]["id"])
lcd.print("count =", back["data"]["count"], "ชนิด", type(back["data"]["count"]))
