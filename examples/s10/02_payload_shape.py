# 02_payload_shape.py - รูปร่างของ payload ตัดสินว่าฝั่งรับทำงานง่ายหรือยาก
#
# Why : บอร์ดหนึ่งตัวส่งทุก 5 วินาที = 17,280 ใบต่อวัน ทุกไบต์ที่เกินจำเป็นใน
#        หนึ่งใบถูกคูณด้วยหมื่นทุกวัน และคนที่มาอ่านโค้ดอีกหกเดือนคือคนที่ต้อง
#        เดาว่า a กับ b คืออะไร ขนาดกับความอ่านออกจึงต้องชั่งพร้อมกัน
# What: payload ที่ดีคือเล็ก คงที่ มีหน่วย และมีตัวตนของอุปกรณ์ "คงที่" แปลว่า
#        ทุกใบมีคีย์ชุดเดิม ไม่ใช่บางรอบมีบางรอบไม่มี
#
# ดูที่จอ: แท่งสามแท่งยาวไม่เท่ากัน แท่งบนสุดยาวที่สุดทั้งที่ให้ข้อมูลน้อยกว่า
#          แท่งล่างสุด และเลขใหญ่บอกว่าใบที่ใช้จริงกินกี่ไบต์
# กับดัก : ส่งตัวเลขเป็นสตริง เช่น "25.5" ฝั่ง dashboard จะขึ้นค่าให้อ่านได้
#          แต่วาดกราฟไม่ได้ เพราะมันไม่ใช่ตัวเลขในสายตาของโปรแกรมฝั่งนั้น

import ui
import lcd
import json
import time

DEVICE_ID = "eva-team03"

# จานสีของหลักสูตร - บทบาทละหนึ่งค่า ตาม SPEC §S7.13
COL_TEXT, COL_DIM = 0xE8EAED, 0x9AA3AF
COL_CARD = 0x171B22
COL_ACCENT = 0x4A9EFF
COL_OK, COL_WARN, COL_BAD = 0x30A46C, 0xF5A623, 0xE5484D
# รางของ ui.Bar เป็น "พื้น" ไม่ใช่สถานะ จึงใช้สีพื้นการ์ดตัวเดียวกัน
COL_TRACK = COL_CARD         # สีรางของ ui.Bar - ตัวแท่งที่วิ่งเป็นสีของธีมเสมอ

# ค่าที่จะส่ง วันนี้ยังไม่ต้องมาจากของจริง ใช้ตัวนับกับนาฬิกาไปก่อน
# ประเด็นของไฟล์นี้คือรูปร่างของข้อความ ไม่ใช่ที่มาของตัวเลข
count = 7
uptime_ms = time.ticks_ms()

# แบบที่หนึ่ง: หลวมเกินไป
# ทศนิยมสิบสี่ตำแหน่งไม่ได้บอกอะไรเพิ่ม นอกจากกินแบนด์วิดท์ทั้งสองฝั่ง
# ชื่อคีย์ยาวเกินจำเป็น และไม่มีตัวตนของอุปกรณ์อยู่ในข้อความเลย
loose = {"temperature_value_in_celsius": 25.123456789012345,
         "the_counter": count}

# แบบที่สอง: แน่นเกินไปจนคนอ่านไม่ออก
# ประหยัดไบต์ได้จริง แต่หกเดือนถัดมาไม่มีใครรู้ว่า a กับ b คืออะไร
too_tight = {"a": 25.1, "b": count}

# แบบที่สาม: พอดี - ชื่อสั้นแต่ยังเดาออก ปัดทศนิยม มีหน่วย มีตัวตน มีเวลา
good = {"id": DEVICE_ID,
        "count": count,
        "uptime_s": uptime_ms // 1000,
        "unit": "s"}

SHAPES = (("หลวมเกินไป", loose, COL_BAD),
          ("แน่นเกินไป", too_tight, COL_WARN),
          ("พอดี", good, COL_OK))

# len() ของสตริง ASCII เท่ากับจำนวนไบต์ที่จะวิ่งบนสาย ใช้เทียบขนาดได้ตรง ๆ
texts = [json.dumps(obj) for _, obj, _ in SHAPES]
sizes = [len(t) for t in texts]
widest = max(sizes)     # แท่งที่ยาวที่สุดเป็นตัวตั้งของสเกล อีกสองแท่งเทียบกับมัน

ui.screen()
time.sleep_ms(200)

# ผังจอ: หัวเรื่องหนึ่งบรรทัด การ์ดคู่ซ้าย/ขวาแถวเดียว แล้วสามบรรทัดสรุปล่างสุด
# การ์ดคู่สูงเท่ากันทั้งสองใบ (56 ถึง 280) ขอบบนกับขอบล่างจึงตรงกันพอดี
ui.Label("payload สามแบบ วัดเป็นไบต์", x=24, y=8, color=COL_TEXT, value=28)

# การ์ดซ้าย: สามแท่ง สเกลเดียวกัน ความยาวคือจำนวนไบต์ล้วน ๆ
# หนึ่งกลุ่มสูง 72 (ป้าย 27 + ช่องไฟ + แท่ง 24) สามกลุ่มจึงลงตัวในการ์ดสูง 224
ui.Panel(x=24, y=56, w=488, h=224, color=COL_CARD, min=COL_CARD, max=12,
         value=1)
row_y = 72
for i in range(3):
    name, _, col = SHAPES[i]
    ui.Label("{}  {} bytes".format(name, sizes[i]), x=40, y=row_y,
             color=col, value=20)
    # color ของ ui.Bar คือสี "ราง" ไม่ใช่สีแท่ง ตัวแท่งที่วิ่งเป็นสีของธีมตายตัว
    # ความหมายจึงอยู่ที่ความยาว ส่วนสีของหัวข้อข้างบนเป็นตัวบอกว่าแบบไหนดีไม่ดี
    ui.Bar(x=40, y=row_y + 32, w=456, h=24, min=0, max=widest, value=sizes[i],
           color=COL_TRACK)
    row_y += 72

# การ์ดขวา: ใบที่จะใช้จริงกินกี่ไบต์ Seg7 รับ "ข้อความ" เท่านั้น
# seg.value(62) ขึ้น 62 ได้ แต่ที่นี่ใช้ text() เพราะคุมรูปแบบเอง
# เลขใหญ่ใช้สีเน้น ไม่ใช่สีเขียว - เขียวในจอนี้ถูกจองไว้ให้แถวที่แปลว่า "พอดี"
# ถ้าทาเลขใหญ่เป็นเขียวด้วย ตาจะอ่านว่ามีสองอย่างที่หมายถึงสิ่งเดียวกัน
ui.Panel(x=528, y=56, w=240, h=224, color=COL_CARD, min=COL_CARD, max=12,
         value=1)
ui.Label("ใบพอดี กินกี่ไบต์", x=544, y=72, color=COL_DIM, value=20)
seg = ui.Seg7(text=str(sizes[2]), x=544, y=112, w=208, h=88, color=COL_ACCENT)
# หน่วยวางใต้ตัวเลข ไม่ใช่ทับบนมัน Seg7 สูง 88 จึงจบที่ y=200
ui.Label("bytes", x=544, y=216, color=COL_DIM, value=20)

# ตัวเลขต้องเป็นตัวเลข ไม่ใช่สตริง สองบรรทัดนี้ต่างกันแค่เครื่องหมายคำพูดคู่เดียว
# บรรทัดที่ y=328 ลงไปเลยเส้น 340 จึงต้องสั้นพอให้จบก่อน x=690
ui.Label('ตัวเลข  {"v": 25.5}    ฝั่งรับวาดกราฟได้', x=24, y=296,
         color=COL_OK, value=20)
ui.Label('สตริง   {"v": "25.5"}  ฝั่งรับวาดกราฟไม่ได้', x=24, y=328,
         color=COL_BAD, value=20)
ui.Label("พอดี = สั้น เดาออก มีหน่วย มีตัวตน", x=24, y=360, color=COL_DIM,
         value=20)
ui.poll()

# lcd เก็บ JSON ตัวเต็มไว้ให้อ่านทีละบรรทัด จอเก็บการเปรียบเทียบ
lcd.clear()
lcd.console("<h2>คาบ 10 - รูปร่างของ payload</h2>")
for i in range(3):
    lcd.print("{} {} bytes".format(SHAPES[i][0], sizes[i]))
    lcd.print("  ", texts[i])

lcd.print("ส่งเป็นตัวเลข", json.dumps({"v": 25.5}))
# หมายเหตุ: lcd.print ตีความ markup ข้อความที่ขึ้นต้นด้วย < จะถูกกลืนหายไปทั้งก้อน
lcd.print("ส่งเป็นสตริง", json.dumps({"v": "25.5"}), "(วาดกราฟไม่ได้)")

# แพลตฟอร์มคาดหวัง "ของแบน" ไม่ต้องห่ออะไรทั้งนั้น
#
# ฝั่งแพลตฟอร์มมี bridge คอยรับ มันอ่าน device_id จาก topic แล้วเอา payload
# ทั้งก้อนของเราไปใส่ใต้คีย์ data ให้เอง เราจึงส่งคีย์ของเราตรง ๆ ได้เลย
#
# ถ้าเราห่อเองด้วย {"data": ...} bridge จะห่อซ้ำอีกชั้นแล้วรีดให้แบนด้วย _
# ชื่อวัดจึงกลายเป็น data_temperature แทน temperature
# วัดจริงบนบอร์ด 2026-09-11 ส่งสองแบบห่างกันสี่วินาที แล้วอ่านจากฐานข้อมูล:
#     ส่ง {"tstflat": 111.0}          -> เก็บเป็น tstflat
#     ส่ง {"data": {"tstenv": 222.0}} -> เก็บเป็น data_tstenv
flat = good
lcd.print("รูปที่แพลตฟอร์มคาดหวัง")
lcd.print("  ", json.dumps(flat))

# ทำไมชื่อคีย์ถึงสำคัญกว่าที่คิด
# แพลตฟอร์มเดาหน่วยจากชื่อคีย์ตรง ๆ temperature ได้ C, accel_x ได้ m/s2
# พอชื่อเพี้ยนไปเป็น data_accel_x มันหาไม่เจอ หน่วยเลยว่าง กราฟยังขึ้นแต่ไม่มีหน่วย
# และไม่มีอะไรฟ้องสักอย่าง นี่คือกับดักที่เงียบที่สุดในคาบนี้
lcd.print("ตั้งชื่อคีย์ให้ตรง ได้หน่วยฟรี")

# แกะกลับด้วย json.loads() แล้วต้องได้ของเดิมทุกช่อง
# ถ้าแกะแล้วได้ไม่ครบ แปลว่าตอนประกอบมีของที่ JSON แทนไม่ได้ปนอยู่
back = json.loads(json.dumps(flat))
lcd.print("แกะกลับได้ id =", back["id"])
lcd.print("count =", back["count"], "ชนิด", type(back["count"]))
