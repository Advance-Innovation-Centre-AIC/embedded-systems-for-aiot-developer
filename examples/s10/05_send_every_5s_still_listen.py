# 05_send_every_5s_still_listen.py - ส่งทุก 5 วินาที แต่ยังรับคำสั่งได้ทุก 100 ms
#
# ไฟล์นี้ไม่ต้องแก้อะไรก่อนกด Run - ไม่ต่อ WiFi ไม่ต่อ broker
# มันสอนเรื่องการนับเวลาอย่างเดียว ของจริงอยู่ในสองไฟล์ที่บอกไว้ท้ายหัวเรื่องนี้
#
# Why : ทีมที่อยากส่งข้อมูลทุกห้าวินาที เขียน time.sleep(5) เป็นคำตอบแรกเสมอ
#        แล้ววันสาธิตก็พบว่ากดปุ่มสั่งงานจากคอมพิวเตอร์แล้วบอร์ดไม่ตอบ
#        บางครั้งตอบ บางครั้งเงียบ เพราะตลอดห้าวินาทีนั้นโปรแกรมไม่ได้ทำอะไรเลย
#        แม้แต่จะดูว่ามีใครสั่งอะไรมาหรือเปล่า
# What: "ทุกห้าวินาที" เป็นคำถามว่าถึงเวลาหรือยัง ไม่ใช่คำสั่งให้หยุดทำงานห้าวินาที
#        เก็บเวลาที่ทำครั้งล่าสุดไว้ แล้วถามด้วย ticks_diff ทุกรอบว่าครบหรือยัง
#        ลูปจึงเดินเร็วได้ตามใจ ในขณะที่งานยังเกิดตามจังหวะที่นัดไว้
#
# นาฬิกาสองเรือน คือทั้งเรื่องของไฟล์นี้
#        เรือนซ้ายเดินทุก 100 ms เรือนขวาเดินทุก 5000 ms
#        ทั้งสองเรือนอยู่ในลูป while เดียวกัน ไม่มี sleep ยาวที่ไหนเลย
#        ถ้าเปลี่ยน LOOP_MS เป็น 5000 แล้วลบการนับเวลาทิ้ง เรือนซ้ายกับเรือนขวา
#        จะเดินเท่ากัน และปุ่มจะกดไม่ติดเก้าครั้งจากสิบ - ลองดูได้ มันคือบทเรียน
#
# ของจริงอยู่ที่ไหน
#        ส่ง MQTT จริง - examples/s10/03_connect_and_publish.py
#        รับคำสั่งจาก MQTT จริง - examples/s10/04_subscribe_command.py
#        ไฟล์นี้ตัดเรื่องเครือข่ายออกหมด เพื่อให้เหลือเรื่องเดียวคือการนับเวลา
#        และเพื่อให้รันได้ทันทีแม้วันที่ broker ของห้องยังไม่ขึ้น
#
# ดูที่จอ: เลขซ้ายวิ่งเร็วมาก เลขขวาขยับทีละหนึ่งทุกห้าวินาที ความต่างของสองเลข
#          นี้คือเนื้อหาทั้งหมดของไฟล์ และแท่งกลางคือเวลาที่ผ่านไปตั้งแต่ใบล่าสุด
# กับดัก : ticks_diff จัดการเรื่องตัวนับเวลาวนกลับเป็นศูนย์ให้แล้ว
#          ถ้าเขียน now - t_last ตรง ๆ วันที่ตัวนับวน โปรแกรมจะเงียบไปเฉย ๆ นานมาก
#          โดยไม่มี error ให้เห็น

import gpio
import lcd
import ui
import time

SEND_EVERY_MS = 5000     # จังหวะการส่ง
LOOP_MS = 100            # จังหวะของลูป ต้องสั้นกว่ามาก
ROUNDS = 600             # 600 รอบ x 100 ms = ราวหนึ่งนาที

# จานสีของหลักสูตร - บทบาทละหนึ่งค่า ตาม SPEC §S7.13
COL_TEXT, COL_DIM = 0xE8EAED, 0x9AA3AF
COL_CARD = 0x171B22          # และใช้เป็นสีรางของ ui.Bar ด้วย แท่งที่วิ่งเป็นสีธีม
COL_OK, COL_INFO = 0x30A46C, 0x4A9EFF

btn = gpio.button(0)         # SW1 - ใช้แทนคำสั่งที่วิ่งเข้ามาระหว่างรอ

ui.screen()
time.sleep_ms(200)

# หัวเรื่องเต็มยาว 110 ไบต์ ยังอยู่ใต้เพดาน 126 ของตัวสร้าง Label จึงเป็นใบเดียว
# ครึ่งหลังคือครึ่งที่สำคัญกว่า ห้ามตัดทิ้งเพื่อให้สั้นลง
#
# ผังจอเป็นสองการ์ดวางซ้อนกันเป็นแถบ ขอบนอก 24 ระยะระหว่างการ์ด 16 ระยะใน 16
# ก่อนแก้ Seg7 สูง 88 เริ่มที่ y=96 จึงยาวถึง 184 ล้นก้นการ์ดใบบน (จบที่ 152)
# ไปโผล่ในเขตการ์ดใบล่างที่สร้างทีหลัง แล้วถูกใบล่างทาทับหายไปทั้งสองตัว
# ตอนนี้การ์ดใบบนสูงพอให้ Seg7 อยู่ในตัวเอง และใบล่างจบที่ y=320 พ้นปุ่ม Console
ui.Label("ส่งทุก 5 วินาที แต่ยังรับคำสั่งได้ทุก 100 ms", x=24, y=8,
         color=COL_TEXT, value=24)
ui.Panel(x=24, y=48, w=744, h=128, color=COL_CARD, min=COL_DIM, max=12, value=1)
ui.Label("รอบลูป (ทุก 100 ms)", x=40, y=64, color=COL_DIM, value=20)
# h ของ Seg7 คือขนาดกล่อง ไม่ใช่ขนาดตัวเลข ตัวเลขถูกตรึงที่ 28 px ตาม §S7.13
# กล่อง 88 จึงเหลือที่ว่างในตัวเองสามสิบกว่าพิกเซล ซึ่งอ่านออกมาเหมือนของวาดไม่ขึ้น
seg_loops = ui.Seg7(text="0", x=40, y=96, w=232, h=64, color=COL_INFO)
ui.Label("ส่งแล้ว (ทุก 5 วินาที)", x=400, y=64, color=COL_DIM, value=20)
seg_sent = ui.Seg7(text="0", x=400, y=96, w=232, h=64, color=COL_OK)

ui.Panel(x=24, y=192, w=744, h=128, color=COL_CARD, min=COL_DIM, max=12, value=1)
ui.Label("เวลาที่ผ่านไปตั้งแต่ใบล่าสุด", x=40, y=208, color=COL_DIM, value=20)
bar = ui.Bar(x=40, y=244, w=712, h=24, min=0, max=SEND_EVERY_MS, value=0,
             color=COL_CARD)
l_recv = ui.Label("กด SW1 ระหว่างรอ - รับได้: 0 ครั้ง", x=40, y=280,
                  color=COL_TEXT, value=20)
note = ui.Label("ลูปทุก 100 ms  ส่งทุก 5000 ms  ไม่มี sleep ยาว", x=24, y=336,
                color=COL_DIM, value=20)
ui.poll()

lcd.clear()
lcd.console("<h2>คาบ 10 - นาฬิกาสองเรือนในลูปเดียว</h2>")
lcd.print("ลูปทุก", LOOP_MS, "ms | ส่งทุก", SEND_EVERY_MS, "ms")
lcd.print("กด SW1 ระหว่างรอ แล้วดูว่าบอร์ดรู้ตัวทันทีหรือไม่")

loops = 0
sent = 0
received = 0
prev_btn = btn.value()

# t_last เก็บเวลาที่ส่งครั้งล่าสุด แล้ววัดระยะจากมันด้วย ticks_diff ทุกรอบ
# ห้ามใช้วิธีหลับยาวเท่าคาบ เพราะคาบคือ "เมื่อไรถึงจะส่ง" ไม่ใช่ "หยุดทำงานนานเท่าไร"
t_last = time.ticks_ms()

for _ in range(ROUNDS):
    loops += 1
    now = time.ticks_ms()
    waited = time.ticks_diff(now, t_last)

    if waited >= SEND_EVERY_MS:
        # ตรงนี้คือจุดที่ของจริงจะเรียก mqtt.publish()
        # ตัวอย่างที่ส่งจริงอยู่ที่ examples/s10/03_connect_and_publish.py
        sent += 1
        seg_sent.text(str(sent))     # Seg7 รับข้อความ ไม่ใช่ตัวเลข
        lcd.print("ถึงกำหนดใบที่", sent, "| ลูปไปแล้ว", loops, "รอบ")
        t_last = now
        waited = 0

    # ระหว่างรอครบห้าวินาที เรายังอ่านปุ่มอยู่ทุกรอบ
    # ปุ่มตัวนี้ทำหน้าที่แทนข้อความขาเข้าจาก broker - ถ้าลูปหลับ มันก็หายไปเงียบ ๆ
    v = btn.value()
    if v == 0 and prev_btn == 1:     # ขอบขาลง - ปุ่มบอร์ดนี้ 0 คือกด
        received += 1
        l_recv.color(COL_INFO)
        l_recv.text("กด SW1 ระหว่างรอ - รับได้: " + str(received) + " ครั้ง")
        lcd.print("รับคำสั่งระหว่างรอบที่", loops, "- ครั้งที่", received)
    prev_btn = v

    # เลขซ้ายกับแท่งขยับทุกรอบ เลขขวาขยับทุกห้าวินาที ความต่างนั้นต้องเห็นด้วยตา
    seg_loops.text(str(loops))
    bar.value(waited)
    ui.poll()

    time.sleep_ms(LOOP_MS)

note.text("จบ - ลูป " + str(loops) + " รอบ ส่ง " + str(sent) + " ใบ")
ui.poll()
lcd.print("จบ - ลูป", loops, "รอบ | ถึงกำหนดส่ง", sent, "ใบ | รับ", received)
print("ลูปเดินไป", loops, "รอบ แต่ถึงกำหนดส่งแค่", sent, "ครั้ง")
print("อัตราส่วนนี้คือ SEND_EVERY_MS / LOOP_MS - ลองแก้สองค่านั้นแล้วรันซ้ำ")
