# msgbox.py - ui.MsgBox ตัวเดียว
#
# ทำอะไร  : กล่องข้อความสำหรับถามยืนยัน text= บรรทัดแรกคือหัวเรื่อง บรรทัดที่เหลือ
#           คือเนื้อความ value=1 เพิ่มปุ่มกากบาทปิดที่มุมขวาบน
#           ปุ่มท้ายกล่องเติมด้วย .add_button(ข้อความ)
# ดูที่จอ : กล่องกลางจอ มีหัวเรื่องไทย เนื้อความไทยสองบรรทัด และปุ่มสองปุ่มด้านล่าง
#
# แบบไหนคือพัง:
#   - กากบาทปิดเป็นกล่องสี่เหลี่ยม = ฟอนต์ไทยของหัวเรื่องไปทับฟอนต์สัญลักษณ์
#   - หัวเรื่องกับเนื้อความติดกันเป็นบรรทัดเดียว = การตัดบรรทัดแรกไม่ทำงาน
#   - กล่องไปโผล่กลางจอแทนที่จะอยู่ตามพิกัด = การจัดตำแหน่งของ lv_msgbox
#     ไม่ได้ถูกดึงกลับมาที่มุมซ้ายบน
#
# กับดักที่ต้องรู้: ปุ่มท้ายกล่อง "ไม่ส่ง event" กลับมา จึงใช้รับคำตอบไม่ได้
#   กล่องนี้ใช้ "บอก" ได้ แต่ถ้าต้องรับคำตอบ ให้วาง ui.Button จริงไว้ข้างนอก
#
# รันจบเองใน 20 วินาที ไม่ต้องต่อเน็ต ไม่ต้องมีเซนเซอร์

import time
import ui

COL_TEXT = 0xE8EAED
COL_DIM = 0x9AA3AF
COL_ACCENT = 0x4A9EFF

ui.screen()
time.sleep_ms(200)

ui.Label("ui.MsgBox", x=24, y=16, color=COL_TEXT, value=28)

# ข้อความทั้งก้อนรวมหัวเรื่องกับเนื้อความมีเพดานเดียวกับ Label คือ 126 ไบต์
# ยาวกว่านั้นจะถูกตัดกลางคันเงียบ ๆ และประตู check_label_bytes.py ไม่ได้ตรวจ
# ตัวสร้างของ MsgBox ให้ - นับเองก่อนเขียนยาว
mb = ui.MsgBox(text="ยืนยันคำสั่ง\nสั่งปั๊มเดิน 30 วินาที",
               x=24, y=72, w=440, h=240, color=COL_TEXT, value=1)
mb.add_button("ยืนยัน")
mb.add_button("ยกเลิก")

# ปุ่มจริงสองใบ วางไว้ข้างนอกกล่อง เพราะปุ่มในกล่องไม่ส่ง event
btn_ok = ui.Button("ยืนยัน", x=496, y=72, w=272, h=88, color=COL_ACCENT,
                   value=24)
btn_no = ui.Button("ยกเลิก", x=496, y=192, w=272, h=88, color=COL_DIM,
                   value=24)

ui.Label("ปุ่มในกล่องเป็นของประดับ", x=24, y=344, color=COL_DIM, value=20)

for _ in range(100):
    for ev in ui.poll():
        if ev["handle"] == btn_ok.id():
            print("กดยืนยันจากปุ่มจริง")
        elif ev["handle"] == btn_no.id():
            print("กดยกเลิกจากปุ่มจริง")
        else:
            print("event จากที่อื่น handle", ev["handle"], ev["type"])
    time.sleep_ms(200)

print("ui.MsgBox: บรรทัดแรก=หัวเรื่อง, value=1 เพิ่มกากบาท, ปุ่มท้ายกล่องไม่ส่ง event")
