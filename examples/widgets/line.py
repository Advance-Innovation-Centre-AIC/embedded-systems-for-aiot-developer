# line.py - ui.Line ตัวเดียว
#
# ทำอะไร  : เส้นหลายท่อนที่ลากผ่านจุดที่เราให้ เติมจุดด้วย .add_point(x, y)
#           value= คือความหนาเส้น color= คือสีเส้น
# ดูที่จอ : เส้นหักหกท่อนคล้ายกราฟ วาดอยู่ในกรอบการ์ด
#
# แบบไหนคือพัง:
#   - ไม่มีเส้นเลย = .add_point() ไปไม่ถึง หรือให้จุดไม่ครบสองจุด
#   - เส้นบางจนแทบไม่เห็น = value= ไม่ทำงาน ค่าปริยายคือ 2 พิกเซล
#   - เส้นไปโผล่มุมซ้ายบนของจอ = พิกัดของจุดถูกตีความผิดระบบ
#
# กับดักที่ต้องรู้: พิกัดของจุดนับจาก "มุมซ้ายบนของ widget เอง" ไม่ใช่ของจอ
#   เส้นนี้อยู่ที่ x=24 y=96 จุด (0,0) ของมันจึงอยู่ที่ (24,96) บนจอ
#   และจุดเดินทางข้าม IPC เป็นข้อความ "x y" เพราะพิกัดจอไม่พอใส่ในช่องขนาดไบต์
#
# รันจบเองใน 20 วินาที ไม่ต้องต่อเน็ต ไม่ต้องมีเซนเซอร์

import time
import ui

COL_TEXT = 0xE8EAED
COL_DIM = 0x9AA3AF
COL_CARD = 0x171B22
COL_ACCENT = 0x4A9EFF

# จุดในระบบพิกัดของเส้นเอง กว้าง 696 สูง 200
POINTS = ((0, 160), (120, 120), (240, 152), (360, 40), (480, 88),
          (600, 24), (696, 72))

ui.screen()
time.sleep_ms(200)

ui.Label("ui.Line", x=24, y=16, color=COL_TEXT, value=28)

ui.Panel(x=24, y=72, w=744, h=248, color=COL_CARD, max=8)

ln = ui.Line(x=48, y=96, w=696, h=200, color=COL_ACCENT, value=6)
for px, py in POINTS:
    ln.add_point(px, py)

ui.Label("เจ็ดจุด หกท่อน หนาหกพิกเซล", x=24, y=344, color=COL_DIM, value=20)

for _ in range(100):
    ui.poll()
    time.sleep_ms(200)

print("ui.Line: .add_point(x, y) นับจากมุมซ้ายบนของเส้นเอง, value=ความหนา")
