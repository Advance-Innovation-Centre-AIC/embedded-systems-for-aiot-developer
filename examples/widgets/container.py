# container.py - กล่อง (Container) ตัวเดียว
#
# ทำอะไร  : กล่องคือชนิดที่ 32 ในตารางของเฟิร์มแวร์ และเป็นชนิดเดียวที่สร้างตรง ๆ
#           ไม่ได้ - ไม่มี ui.Container() ให้เรียก มันเกิดทางเดียวคือถูกคืนมาจาก
#           .add_tab() .add_tile() .content() .add_page() .section() .row()
#           หน้าที่ของมันคือเป็น "ที่" ให้ widget อื่นไปอยู่ ผ่าน parent=
#           แล้วพิกัด x= y= ของลูก จะนับจากมุมซ้ายบนของกล่องใบนั้น ไม่ใช่ของจอ
# ดูที่จอ : ป้ายสี่ใบเขียนข้อความเดียวกันว่า x=24 y=56 แต่ไปโผล่คนละที่ทั้งสี่ใบ
#           ใบที่ 1 บนจอ ใบที่ 2 ในการ์ด ใบที่ 3 ในหน้าของแท็บ ใบที่ 4 ในตัว
#           หน้าต่าง และบรรทัดล่างบอกแฮนเดิลที่กล่องแต่ละใบกินไป
#
# แบบไหนคือพัง:
#   - ป้ายทั้งสี่ใบซ้อนกันอยู่มุมเดียว = parent= ไม่ถึงปลายทาง ทุกใบเลยเป็นลูกของจอ
#   - ป้ายในกล่องหายไปเลย = พิกัดของลูกเกินขอบกล่อง ลูกถูกตัด ไม่ได้ล้นออกมาบนจอ
#   - โปรแกรมค้างตอนสร้าง = แฮนเดิลเต็ม 64 ซึ่งกล่องกินใบละหนึ่งเท่า widget ปกติ
#
# กับดักที่ต้องรู้:
#   - กล่องเป็น "ที่" ไม่ใช่ "ของที่ตอบได้" - ui_widget_mgr.c ไม่มี case ของ
#     ชนิดกล่องทั้งใน set_text และ set_value ส่วน get_value ตกที่ default คืน 0
#     สั่งเปลี่ยนข้อความหรือค่าให้กล่อง จึงเงียบสนิท ไม่มี error ให้จับ
#   - parent= ไม่ได้รับเฉพาะกล่อง มันรับ widget อะไรก็ได้ เพราะ CM55 แปลง
#     แฮนเดิลเป็น object แล้วส่งให้ LVGL ตรง ๆ - ป้ายที่มี parent=Panel จึงย้าย
#     ไปอยู่ในระบบพิกัดของการ์ดใบนั้นทันที
#   - ด่าน check_overlap.py ข้ามทุกตัวที่มี parent= เพราะมันอยู่คนละระบบพิกัด
#     หน้าจอที่ใช้กล่อง จึงต้องเปิดภาพดูด้วยตาเสมอ เครื่องมือตรวจให้ไม่ได้
#
# รันจบเองใน 20 วินาที ไม่ต้องต่อเน็ต ไม่ต้องมีเซนเซอร์

import time
import ui

COL_TEXT = 0xE8EAED
COL_DIM = 0x9AA3AF
COL_CARD = 0x171B22
COL_ACCENT = 0x4A9EFF

# ข้อความเดียวกันเป๊ะทุกใบ ความต่างบนจอจึงมาจากระบบพิกัดล้วน ๆ
SAME = "x=24 y=56"

ui.screen()
time.sleep_ms(200)

ui.Label("กล่อง (Container)", x=24, y=16, color=COL_TEXT, value=28)

# ใบที่ 1 - ไม่มี parent= คือลูกของจอ
ui.Label(SAME, x=24, y=56, color=COL_DIM, value=24)

# ใบที่ 2 - พ่อเป็น Panel ธรรมดา ไม่ใช่กล่องที่คอนเทนเนอร์คืนมา แต่ใช้ได้
card = ui.Panel(x=24, y=96, w=232, h=224, color=COL_CARD, max=8)
ui.Label(SAME, x=24, y=56, color=COL_ACCENT, value=24, parent=card)

# ใบที่ 3 - พ่อเป็นหน้าของแท็บ ซึ่งเป็นกล่องของจริง
tabs = ui.Tabview(x=280, y=96, w=232, h=224, color=COL_CARD, value=88)
page = tabs.add_tab("แท็บ")
ui.Label(SAME, x=24, y=56, color=COL_ACCENT, value=24, parent=page)

# ใบที่ 4 - พ่อเป็นตัวหน้าต่าง ซึ่งก็เป็นกล่องเหมือนกัน
wn = ui.Win(text="หน้าต่าง", x=536, y=96, w=232, h=224, color=COL_CARD)
body = wn.content()
ui.Label(SAME, x=24, y=56, color=COL_ACCENT, value=24, parent=body)

# สั่งสองอย่างนี้กับกล่อง แล้วจอไม่ขยับสักพิกเซล
page.text("ชื่อใหม่ที่ไม่มีวันขึ้นจอ")
page.value(1)

note = "การ์ด id " + str(card.id()) + " หน้าแท็บ id " + str(page.id())
ui.Label(note, x=24, y=344, color=COL_DIM, value=20)
ui.Label("ถามค่าจากกล่องได้ " + str(page.value()), x=440, y=344,
         color=COL_DIM, value=20)

events = 0
for _ in range(100):
    for _ev in ui.poll():
        events += 1
    time.sleep_ms(200)

# ต้องเป็นศูนย์ - register_object() ผูกไว้แค่ LV_EVENT_DELETE เพื่อคืนแฮนเดิล
print("Container: event ที่ได้รับตลอดการรัน =", events, "(ควรเป็น 0)")
print("parent= เปลี่ยนระบบพิกัดของลูก และกล่องกินแฮนเดิลใบละหนึ่ง")
