# table.py - ui.Table ตัวเดียว
#
# ทำอะไร  : ตารางสองคอลัมน์ สี่แถว เติมทีละช่องด้วย .cell(แถว, คอลัมน์, ข้อความ)
#           min= คือจำนวนคอลัมน์ max= คือจำนวนแถว value= คือขนาดตัวอักษรในช่อง
# ดูที่จอ : ตารางเต็มความกว้าง หัวตารางเป็นภาษาไทย คอลัมน์ซ้ายกว้างกว่าขวา
#
# แบบไหนคือพัง:
#   - ช่องว่างเปล่าทั้งตาราง = .cell() ไปไม่ถึง CM55
#   - ภาษาไทยเป็นกล่องสี่เหลี่ยม = ฟอนต์ไทยไม่ได้ถูกตั้งที่ LV_PART_ITEMS
#     (ตารางวาดช่องจากส่วน ITEMS ไม่ใช่ MAIN ตั้งฟอนต์ที่ MAIN อย่างเดียวไม่พอ)
#   - คอลัมน์กว้างเท่ากันหมด = .col_width() ไม่ทำงาน
#
# รันจบเองใน 20 วินาที ไม่ต้องต่อเน็ต ไม่ต้องมีเซนเซอร์

import time
import ui

COL_TEXT = 0xE8EAED
COL_DIM = 0x9AA3AF

ui.screen()
time.sleep_ms(200)

ui.Label("ui.Table", x=24, y=16, color=COL_TEXT, value=28)

# ความสูงต้องพอกับจำนวนแถวจริง - แถวหนึ่งกินราว 68 พิกเซลที่ตัวอักษรขนาด 24
# ตั้งเตี้ยกว่านั้นแล้วแถวสุดท้ายจะถูกตัดครึ่ง โดยไม่มีคำเตือน
# h=288 ไม่ใช่ 272 - สี่แถวที่ฟอนต์ 24 สูงรวมเกิน 272 อยู่นิดเดียว แล้ว Table
# จะขึ้นแถบเลื่อนกับตัดขอบแถวสุดท้าย เผื่อไว้หนึ่งช่องกริดจึงพอดี
tb = ui.Table(x=24, y=72, w=520, h=288, color=COL_TEXT, min=2, max=4, value=24)
# 312+192 = 504 ไม่ใช่ 520 เต็ม - ตารางมีขอบในของมันเอง ตั้งรวมเท่าความกว้าง
# พอดีเป๊ะแล้วจะล้นออกไปนิดเดียว แล้วขึ้นแถบเลื่อนแนวนอนคาไว้ใต้ตาราง
tb.col_width(0, 312)
tb.col_width(1, 192)

tb.add_row("รายการ", "ค่าที่อ่านได้")
tb.add_row("อุณหภูมิ", "25.4 องศา")
tb.add_row("ความชื้น", "55 เปอร์เซ็นต์")
tb.add_row("แรงดันไฟ", "3.28 โวลต์")

ui.Label("สองคอลัมน์ สี่แถว", x=576, y=96, color=COL_DIM, value=20)
ui.Label("เติมทีละช่อง", x=576, y=136, color=COL_DIM, value=20)
ui.Label("คอลัมน์กว้างต่างกัน", x=576, y=176, color=COL_DIM, value=20)

for _ in range(100):
    ui.poll()
    time.sleep_ms(200)

print("ui.Table: min=คอลัมน์ max=แถว value=ขนาดตัวอักษรในช่อง")
