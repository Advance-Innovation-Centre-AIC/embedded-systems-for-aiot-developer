# keyboard.py - ui.Keyboard ตัวเดียว
#
# ทำอะไร  : แป้นพิมพ์เต็มบนจอ ผูกกับ ui.Textarea หนึ่งช่องด้วย .bind(ช่อง)
#           แล้วทุกปุ่มที่แตะจะไปโผล่ในช่องนั้นเอง โดยเราไม่ต้องเขียนโค้ดรับ
# ดูที่จอ : ช่องข้อความด้านบน แป้นพิมพ์สี่แถวด้านล่าง แตะแล้วตัวอักษรขึ้นในช่อง
#           มีขีดกะพริบบอกตำแหน่งที่กำลังพิมพ์ และปุ่มที่กดจะเข้มขึ้นชั่วขณะ
#           ตัวอย่างนี้เปิดมาที่ผังไทย (เกษมณี) ครบทุกตัวอักษรเหมือนแป้นจริง
#           ปุ่ม ENG แถวล่าง - แตะแล้วสลับไปอังกฤษ แล้วปุ่มนั้นจะเขียน TH
#           ปุ่ม ⌃ ซ้ายล่าง - ระนาบที่สอง เลขไทยและพยัญชนะที่เหลือ
#
# แบบไหนคือพัง:
#   - แป้นพิมพ์ไปโผล่กลางล่างของจอแทนที่จะอยู่ตามพิกัด = การจัดตำแหน่งของ
#     lv_keyboard ไม่ได้ถูกดึงกลับมาที่มุมซ้ายบน (วัดได้: ขอ (20,100) ได้ (110,310))
#   - แตะปุ่มแล้วช่องข้อความไม่ขึ้นอะไร = .bind() ไปไม่ถึง หรือแฮนเดิลที่ผูกไม่ใช่
#     Textarea - CM55 ปฏิเสธเงียบ ๆ ทั้งสองกรณี
#   - ไม่มีแป้นพิมพ์เลย = สร้างไม่สำเร็จ
#   - ปุ่มพิเศษเป็นกล่องสี่เหลี่ยม = ฟอนต์ไทยขนาด 20px ไม่มีไอคอนของ LVGL อยู่
#     ปกติมันถูกรวมเข้าไปแล้วโดย thai_text/tools/regen.sh ถ้าเห็นกล่องเปล่า
#     แปลว่าฟอนต์ถูก regen ใหม่โดยไม่ได้ใส่ช่วง 0xF00C ขึ้นไป
#   - พิมพ์คำไทยแล้วหาตัวอักษรไม่เจอ = ผังขาดตัว ตรวจด้วย
#     BENTO-TESAIoT-libraries/tools/check_thai_keymap.py ซึ่งเทียบผังกับ
#     พยัญชนะ 44 ตัวและสระ/วรรณยุกต์ทั้งหมด ทั้งฝั่งเฟิร์มแวร์และ emulator
#
# กับดักที่ต้องรู้ ก่อนเอาไปวางแผนใช้งาน:
#   Keyboard "ไม่ส่ง event" และไลบรารีนี้ "ยังไม่มีคำสั่งอ่านข้อความกลับ"
#   (ตาราง IPC_CMD_UI_* มี SET_TEXT แต่ไม่มี GET_TEXT ส่วน GET_VALUE คืน 0
#   เมื่อถูกถามด้วย Textarea) แปลว่าสิ่งที่พิมพ์ คนอ่านได้ โปรแกรมยังอ่านไม่ได้
#   ถ้าต้องรับตัวอักษรจากนิ้วไปใช้ต่อ ให้ดู buttonmatrix.py ในโฟลเดอร์นี้
#
# รันจบเองใน 24 วินาที ไม่ต้องต่อเน็ต ไม่ต้องมีเซนเซอร์

import time
import ui

COL_TEXT = 0xE8EAED
COL_DIM = 0x9AA3AF

ui.screen()
time.sleep_ms(200)

ui.Label("ui.Keyboard", x=24, y=16, color=COL_TEXT, value=28)

ta = ui.Textarea(text="พิมพ์ต่อท้ายได้เลย", x=24, y=64, w=664, h=88,
                 color=COL_TEXT)

# แป้นพิมพ์ต้องสร้างหลังช่อง เพราะ .bind() ส่งแฮนเดิลของช่องข้ามไปให้ CM55
# value=1 คือเปิดมาที่ผังไทย ส่วน 0 คือผังอังกฤษ สลับตอนรันด้วย .value(1) หรือ (0)
kb = ui.Keyboard(x=24, y=168, w=664, h=176, color=COL_TEXT, value=1)
kb.bind(ta)

events = 0
for _ in range(60):
    for _ev in ui.poll():
        events += 1
    time.sleep_ms(400)

# ตัวเลขนี้ต้องเป็นศูนย์ ต่อให้แตะแป้นพิมพ์รัว ๆ ตลอดยี่สิบสี่วินาที
# ถ้าไม่ใช่ศูนย์ แปลว่าไลบรารีเพิ่ม event ให้แป้นพิมพ์แล้ว - เป็นข่าวดี
print("ui.Keyboard: event ที่ได้รับตลอดการรัน =", events, "(ควรเป็น 0)")
print("ผูกช่องได้ วาดได้ แต่ยังส่งสิ่งที่พิมพ์กลับ MicroPython ไม่ได้")
