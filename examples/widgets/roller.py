# roller.py - ui.Roller ตัวเดียว
#
# ทำอะไร  : วงล้อเลือกที่กางตัวเลือกให้เห็นหลายบรรทัดพร้อมกัน แล้วเลื่อนด้วยนิ้ว
#           เติมทีละบรรทัดด้วย .add_option() อ่านบรรทัดที่เลือกด้วย .value()
# ดูที่จอ : วงล้อไทยห้าตัวเลือก บรรทัดที่เลือกอยู่เป็นแถบสีเน้น
#           อีกสิบวินาทีต่อมาโปรแกรมสั่งเลื่อนเอง ให้เห็นว่าแถบสีขยับตาม
#
# แบบไหนคือพัง:
#   - "บรรทัดที่ไม่ได้เลือก" เป็นตัวอักษร แต่ "บรรทัดที่เลือก" เป็นกล่องสี่เหลี่ยม
#     = ฟอนต์ไทยถูกตั้งที่ LV_PART_MAIN แต่ไม่ได้ตั้งที่ LV_PART_SELECTED
#     นี่คืออาการที่เจอบ่อยที่สุดของ widget ตัวนี้ ดูที่แถบสีเสมอ
#   - วงล้อว่างเปล่า = .add_option() ไปไม่ถึง CM55
#   - สั่ง .value(3) แล้วแถบสีไม่ขยับ = การตั้งบรรทัดที่เลือกไม่ทำงาน
#
# กับดักที่ต้องรู้: value= ตอนสร้างทำสองหน้าที่พร้อมกัน คือบรรทัดที่เลือก
#   และขนาดฟอนต์ไทย จึงไม่ตั้งไว้ในไฟล์นี้ - ใช้ .value(n) ทีหลังแทน
#   และตัวเลือกทั้งหมดรวมกันยาวได้ไม่เกิน 320 ไบต์ เกินแล้วหายเงียบ ๆ
#
# รันจบเองใน 24 วินาที ไม่ต้องต่อเน็ต ไม่ต้องมีเซนเซอร์

import time
import ui

COL_TEXT = 0xE8EAED
COL_DIM = 0x9AA3AF

CHOICES = ("ปกติ", "เฝ้าระวัง", "หยุดฉุกเฉิน", "ล้างค่า", "ปิดเครื่อง")

ui.screen()
time.sleep_ms(200)

ui.Label("ui.Roller", x=24, y=16, color=COL_TEXT, value=28)

ro = ui.Roller(x=24, y=72, w=320, h=248, color=COL_TEXT)
for choice in CHOICES:
    ro.add_option(choice)

note = ui.Label("ตอนนี้เลือก " + CHOICES[0], x=384, y=112, color=COL_TEXT,
                value=24)
ui.Label("ดูที่แถบสี กล่อง = ฟอนต์ไทยหาย", x=384, y=160, color=COL_DIM,
         value=20)
ui.Label("ปัดนิ้วก็ได้ สั่งจากโปรแกรมก็ได้", x=24, y=344, color=COL_DIM,
         value=20)

for i in range(60):
    # ทุกสองวินาทีสั่งเลื่อนเอง เพื่อให้ไฟล์นี้พิสูจน์ตัวเองได้โดยไม่ต้องมีนิ้ว
    if i % 5 == 0:
        pick = (i // 5) % len(CHOICES)
        ro.value(pick)
        note.text("ตอนนี้เลือก " + CHOICES[pick])

    for ev in ui.poll():
        if ev["handle"] == ro.id() and ev["type"] == "value_changed":
            print("บรรทัดที่เลือกคือ", ev["value"])
    time.sleep_ms(400)

print("ui.Roller: .add_option() เติม, .value(n) เลือก, event คือ value_changed พร้อมลำดับ")
