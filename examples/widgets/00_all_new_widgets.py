# 00_all_new_widgets.py - widget ใหม่สี่ตัวบนหน้าจอเดียว สำหรับตรวจบนบอร์ดจริง
#
# ไฟล์นี้ทำอะไร: สร้าง Table, Roller, Led, Spinbox พร้อมกันในจอเดียว
#                พร้อมข้อความไทย แล้วปล่อยค้างไว้ให้ตรวจด้วยตา
#                ตัวที่เหลือแยกเป็นไฟล์ละตัวในโฟลเดอร์นี้ - เปิดทีละไฟล์
#
# ดูที่จอ: ทุกตัวต้องเห็นครบทั้งตัว ไม่ใช่โผล่มาครึ่งเดียว
#          และข้อความไทยต้องเป็นตัวอักษร ไม่ใช่กล่องสี่เหลี่ยม
#
# แบบไหนคือพัง:
#   - ที่ว่างเปล่า           = widget ตัวนั้นสร้างไม่สำเร็จ
#   - กล่องสี่เหลี่ยมแทนตัวอักษร = ฟอนต์ไทยไปไม่ถึง widget ตัวนั้น
#   - ตารางเห็นแถวเดียว      = ตั้งความสูงไว้ไม่พอกับจำนวนแถว
#   - วงล้อโดนตัดกลางคำ      = ความสูงวงล้อไม่พอกับจำนวนตัวเลือกที่ขอให้เห็น
#   - ไฟดวงขวาหายไปเลย       = Led สั่งดับแล้วหายแทนที่จะหรี่ (ผิด)
#
# เรื่องพื้นที่: จอกว้าง 800 แต่พื้นที่วาดจริงสูงแค่ 398 เพราะแถบหัวกินไป
#   และมุมขวาล่างเป็นปุ่มคอนโซล ห้ามวางของทับ - ที่นี่จึงหยุดที่ x=664
#   ครั้งแรกที่เขียนไฟล์นี้ ใส่กรอบกับป้ายชื่อครบทุกตัวจนไม่เหลือที่ให้ของข้างใน
#   ป้ายชื่อจึงย้ายมารวมเป็นบรรทัดเดียวข้างบน แล้วยกที่ที่เหลือให้ widget ทั้งหมด
#   และ Scale ถูกยกออกไปทั้งตัว - ตารางสามแถวกับวงล้อสามตัวเลือกกินไป 224
#   เหลือ 134 ซึ่งไม่พอทั้งไม้บรรทัดและไฟสถานะ ยัดทั้งสามแล้วโดนตัดทุกอัน
#   Scale ดูได้ที่ scale.py ในโฟลเดอร์นี้ และที่ examples/s04/09
#
# ไฟล์นี้ไม่ต้องต่อเน็ต ไม่ต้องมีเซนเซอร์ รันจบเองใน 20 วินาที

import lcd
import time
import ui

# ระบบออกแบบตาม SPEC.md S7.13 - เฟิร์มแวร์มีฟอนต์ 5 ขนาดและปัดขึ้น
# ใช้ได้จริงคือ 28 / 24 / 20 ส่วน 14 กับ 16 ต่ำกว่ามาตรฐานการอ่าน
F_TITLE, F_BODY = 24, 20

COL_TEXT = 0xE8EAED
COL_DIM = 0x9AA3AF
COL_ACCENT = 0x4A9EFF
COL_WARN = 0xF5A623
COL_BAD = 0xE5484D
COL_OK = 0x30A46C

ui.screen()
time.sleep_ms(200)

lcd.clear()
lcd.console("<h2>ตรวจ widget ใหม่</h2>")

# ห้ามใช้ "·" ในข้อความที่ขึ้นจอ - ฟอนต์ไทยไม่มีตัวนี้ และตัวเลือกฟอนต์
# เห็นไบต์ที่ไม่ใช่ ASCII ก็สลับไปฟอนต์ไทยทั้งบรรทัด จุดจึงกลายเป็นกล่องเปล่า
# บรรทัดนี้เคยเขียนด้วย "·" แล้วขึ้นจอเป็นสี่เหลี่ยมสี่ใบ เห็นตอนเปิดภาพดู
ui.Label("Table / Roller / Led / Spinbox", x=24, y=4,
         color=COL_TEXT, value=F_TITLE)

# --- แถวบน: ตาราง และ วงล้อเลือก -----------------------------------------
# แถวหนึ่งสูงราว 72 ที่ฟอนต์ 20 สามแถวจึงต้องการ 224 ไม่ใช่ 192
# ลองมาแล้วทั้ง 160 และ 192 - แถวสุดท้ายโดนตัดครึ่งเงียบ ๆ ทั้งสองครั้ง
# วงล้อก็ตัวเลขเดียวกัน สามตัวเลือกต้องการ 224 ไม่งั้นตัวล่างโดนตัด
tb = ui.Table(x=24, y=40, w=440, h=224, color=COL_TEXT, min=2, max=3,
              value=F_BODY)
tb.col_width(0, 232)
tb.col_width(1, 192)
tb.add_row("เซนเซอร์", "ค่าที่อ่านได้")
tb.add_row("อุณหภูมิ", "25.4 องศา")
tb.add_row("ความชื้น", "55 เปอร์เซ็นต์")

ro = ui.Roller(x=488, y=40, w=264, h=224, color=COL_TEXT, value=F_BODY)
ro.add_option("ปกติ")
ro.add_option("เฝ้าระวัง")
ro.add_option("หยุดฉุกเฉิน")

# --- แถวล่าง: ไฟสถานะ และ ช่องกรอกตัวเลข ---------------------------------
# ดวงที่สี่สั่ง value=0 ไว้ - ต้องหรี่ ไม่ใช่หายไปจากจอ
ui.Led(x=24, y=288, w=64, h=64, color=COL_OK, value=1)
ui.Led(x=112, y=288, w=64, h=64, color=COL_WARN, value=1)
ui.Led(x=200, y=288, w=64, h=64, color=COL_BAD, value=1)
ui.Led(x=288, y=288, w=64, h=64, color=COL_OK, value=0)

# สูง 88 ไม่ใช่ 64 - ปุ่มบวกลบของ Spinbox คือเป้าสัมผัส ต้องได้ 10 มม.
ui.Spinbox(x=488, y=280, w=176, h=88, color=COL_OK, min=0, max=9999,
           value=2375)

ui.poll()

lcd.print("ตรวจด้วยตา: ทุกตัวเห็นครบทั้งตัวไหม")
lcd.print("และข้อความไทยเป็นตัวอักษร ไม่ใช่กล่องสี่เหลี่ยม")

# ค้างไว้ให้ดู แล้วจบเอง ไม่ต้องกดอะไร
for _ in range(100):
    ui.poll()
    time.sleep_ms(200)

lcd.print("<span class=ok>จบการตรวจ</span>")
print("ถ้าทุกตัวเห็นครบและอ่านภาษาไทยออก แปลว่า widget ใหม่ใช้ได้ทั้งชุด")
