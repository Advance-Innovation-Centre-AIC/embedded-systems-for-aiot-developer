# scale.py - ui.Scale ตัวเดียว
#
# ทำอะไร  : ไม้บรรทัดมีขีดและตัวเลขกำกับ min= max= คือพิสัย
#           .ticks(ขีดทั้งหมด, ทุกกี่ขีดจึงเป็นขีดใหญ่) กำหนดความถี่ของขีด
# ดูที่จอ : ไม้บรรทัด 0 ถึง 100 มีตัวเลขกำกับทุก 20 และมีแถบค่าวางอยู่เหนือมัน
#           แถบเลื่อนไปมา ส่วนไม้บรรทัดอยู่นิ่ง
#
# แบบไหนคือพัง:
#   - ไม่มีตัวเลขกำกับ = ขีดใหญ่ไม่ถูกตั้ง หรือ .ticks() ไปไม่ถึง
#   - ไม้บรรทัดขยับตามค่า = ผิด มันต้องอยู่นิ่ง ตัวที่ขยับคือ ui.Bar ข้างบน
#   - ไม่มีขีดเลย = สร้างไม่สำเร็จ
#
# กับดักที่ต้องรู้: ui.Scale "ไม่มีเข็ม" และ "ไม่รับ .value()" มันคือไม้บรรทัด
#   ไม่ใช่หน้าปัด สิ่งที่ขยับคือของที่เราวางทับลงไปเอง
#
# รันจบเองใน 24 วินาที ไม่ต้องต่อเน็ต ไม่ต้องมีเซนเซอร์

import time
import ui

COL_TEXT = 0xE8EAED
COL_DIM = 0x9AA3AF
COL_ACCENT = 0x4A9EFF

ui.screen()
time.sleep_ms(200)

ui.Label("ui.Scale", x=24, y=16, color=COL_TEXT, value=28)

# แถบค่าอยู่ "เหนือ" ไม้บรรทัด เพราะไม้บรรทัดไม่มีเข็มให้
bar = ui.Bar(x=24, y=96, w=744, h=24, color=COL_ACCENT, min=0, max=100,
             value=0)
sc = ui.Scale(x=24, y=128, w=744, h=64, color=COL_TEXT, min=0, max=100)
sc.ticks(51, 10)          # 51 ขีดบนพิสัย 0-100 คือทุก 2 หน่วย ขีดใหญ่ทุก 10 ขีด

val = ui.Label("ค่า 0 จาก 100", x=24, y=224, color=COL_TEXT, value=24)
ui.Label("ไม้บรรทัดนิ่ง แถบคือตัวที่ขยับ", x=24, y=272, color=COL_DIM,
         value=20)
ui.Label("เรียก sc.value(50) แล้วไม่มีอะไรเกิด", x=24, y=344,
         color=COL_DIM, value=20)

for i in range(60):
    v = i * 100 // 59
    bar.value(v)
    if i % 5 == 0:
        val.text("ค่า " + str(v) + " จาก 100")
    ui.poll()
    time.sleep_ms(400)

# พิสูจน์ข้อสุดท้ายด้วยตัวมันเอง - สั่งแล้วดูว่าไม้บรรทัดนิ่งเหมือนเดิม
sc.value(50)
val.text("สั่ง sc.value(50) แล้ว - ไม้บรรทัดนิ่ง")

print("ui.Scale: ไม้บรรทัด ไม่มีเข็ม ไม่รับ .value() - ตัวที่ขยับคือ ui.Bar")
