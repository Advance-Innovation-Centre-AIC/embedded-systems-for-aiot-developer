# 05_clear_and_refresh.py - อัปเดตซ้ำที่เดิม ต่างจากไล่พิมพ์ลงมา
#
# Why : ค่าที่เปลี่ยนตลอดเวลา เช่นเวลาที่เหลือหรืออุณหภูมิ ถ้าไล่พิมพ์ลงมาเรื่อย ๆ
#       คนดูต้องไล่หาเองว่าบรรทัดไหนคือค่าล่าสุด พอค่าเปลี่ยนวินาทีละครั้ง
#       จอจะเต็มไปด้วยประวัติ แล้วสิ่งที่เขาอยากรู้จริง ๆ คือแค่ตัวเลขตัวเดียว
# What: มีสองท่าคนละแบบ ท่าลิ้นชักคือ lcd.clear() แล้ววาดใหม่ทั้งหน้าทุกรอบ
#       ท่า widget คือสร้างครั้งเดียวแล้วเรียก .text() หรือ .value() ทับค่าเดิม
#       ท่าหลังถูกกว่ามาก เพราะส่งข้ามไปแค่ค่าใหม่ ไม่ได้ส่งทั้งหน้า
#
# ดูที่จอ: ตัวเลขใหญ่นับถอยหลัง 5 4 3 2 1 0 อยู่ที่เดิม ไม่เลื่อน พร้อมวงแหวน
#          ที่ค่อย ๆ ปิดลง เหลือสองวินาทีสุดท้ายทั้งคู่เปลี่ยนเป็นสีเหลือง
# กับดัก : ล้างจอถี่กว่าราว 5 ครั้งต่อวินาที ตาจะเห็นเป็นจอกระพริบ อ่านค่าไม่ทัน
#          ส่วน widget อัปเดตถี่ได้ เพราะมันเปลี่ยนเฉพาะจุดที่ค่าเปลี่ยนจริง

import lcd
import time
import ui

TOTAL = 5           # นับถอยหลังกี่วินาที
TICK_MS = 1000      # อัปเดตทุกกี่มิลลิวินาที

COL_TEXT, COL_DIM = 0xE8EAED, 0x9AA3AF
COL_CARD = 0x171B22
COL_OK, COL_WARN = 0x30A46C, 0xF5A623

ui.screen()
time.sleep_ms(200)

ui.Label("นับถอยหลัง", x=20, y=12, color=COL_TEXT, value=24)
ui.Panel(x=20, y=52, w=652, h=200, color=COL_CARD, min=COL_DIM, max=12, value=1)

# สร้างครั้งเดียวตรงนี้ นอกลูป ทั้งสามตัวจะถูกเขียนทับค่าใหม่ในลูปข้างล่าง
# ถ้าย้ายสามบรรทัดนี้เข้าไปในลูป จะได้ widget ใหม่ทุกวินาที และชนโควตา 32 ตัว
seg = ui.Seg7(text=str(TOTAL), x=60, y=92, w=152, h=112, color=COL_OK)
arc = ui.Arc(x=280, y=80, w=132, h=132, min=0, max=TOTAL, value=TOTAL,
             color=COL_OK)
# ข้อความในการ์ดต้องสั้นพอที่จะไม่ล้นขอบขวาของ Panel (ขอบอยู่ที่ x=670)
note = ui.Label("อยู่ที่เดิมทุกวินาที", x=440, y=120,
                color=COL_DIM, value=20)

# ห้ามสร้าง Label ด้วยข้อความว่าง LVGL จะเติมคำว่า "Label" ให้เอง
# แล้วคำนั้นจะค้างบนจอจนกว่าจะมีการเขียนทับครั้งแรก
elapsed_lbl = ui.Label("ยังไม่เริ่มจับเวลา", x=20, y=272, color=COL_DIM,
                       value=20)

# ticks_ms() คือนาฬิกาที่นับตั้งแต่บอร์ดบูต ไม่ใช่เวลาจริงบนปฏิทิน
t0 = time.ticks_ms()

for left in range(TOTAL, -1, -1):
    # --- ท่าที่ 1: widget เขียนทับค่าเดิม ไม่มีการล้างอะไรทั้งสิ้น ---
    seg.text(str(left))
    arc.value(left)

    if left <= 2:
        # เปลี่ยนสีตอนเหลือน้อย ตาจับสีได้ก่อนอ่านตัวเลขเสมอ
        seg.color(COL_WARN)
        arc.color(COL_WARN)

    # --- ท่าที่ 2: ลิ้นชักต้องล้างแล้ววาดใหม่ทั้งหน้า ---
    # ถ้าไม่ล้าง เลข 5 4 3 2 1 จะกองซ้อนกันจนอ่านไม่ออกว่าอันไหนล่าสุด
    lcd.clear()
    lcd.console("<h2>นับถอยหลัง</h2>")

    if left == 0:
        lcd.print("<span class=ok>หมดเวลา</span>")
    elif left <= 2:
        lcd.print("<span class=warn>เหลืออีก", left, "วินาที</span>")
    else:
        lcd.print("เหลืออีก", left, "วินาที")

    # เวลาที่ผ่านไปจริง ไม่เท่ากับ TICK_MS คูณจำนวนรอบเป๊ะ ๆ
    # เพราะการวาดจอเองก็กินเวลา นาฬิกาของลูปจึงเดินช้ากว่านาฬิกาจริงเสมอ
    elapsed = time.ticks_diff(time.ticks_ms(), t0)
    elapsed_lbl.text("ผ่านไปแล้ว " + str(elapsed) + " ms")
    lcd.print("<span class=muted>ผ่านไปแล้ว", elapsed, "ms</span>")

    ui.poll()
    time.sleep_ms(TICK_MS)

# หน้าสุดท้ายไม่ล้าง ปล่อยให้ค้างไว้ให้คนอ่านทัน
# โปรแกรมที่ล้างจอเป็นสิ่งสุดท้ายก่อนจบ จะทิ้งจอว่างให้คนงงว่าเกิดอะไรขึ้น
total = time.ticks_diff(time.ticks_ms(), t0)
seg.text("0")
note.text("จบแล้ว ค่าค้างไว้ให้อ่าน")
elapsed_lbl.text("รวมทั้งหมด " + str(total) + " ms - ตั้งใจไว้ " +
                 str(TOTAL * TICK_MS) + " ms")
lcd.print("<span class=muted>รวมทั้งหมด", total, "ms</span>")
ui.poll()

# ----- ตาคุณ แก้แล้วรันใหม่ -----
# ตั้ง TICK_MS = 150 แล้วขยาย TOTAL เป็น 20 รันดูแล้วตอบว่าท่าไหนอ่านออก
# ท่าไหนกลายเป็นจอกระพริบ ระหว่างตัวเลขบน Seg7 กับบรรทัดในลิ้นชัก
# ใบ้: ท่าหนึ่งวาดใหม่ทั้งหน้าทุกรอบ อีกท่าเปลี่ยนเฉพาะจุดที่ค่าเปลี่ยนจริง
