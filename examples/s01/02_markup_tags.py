# 02_markup_tags.py - ทำให้บรรทัดที่ต้องรีบอ่าน เด่นออกมาจากบรรทัดอื่น
#
# ไฟล์นี้สอน: ห้าคลาสของ span คือห้าระดับความสำคัญ ไม่ใช่ห้าสีให้เลือกตามชอบ
# ดูที่จอ   : ป้ายบนหน้า Playground บอกว่ากำลังพิมพ์ชุดไหน ตัวรายงานอยู่ใน
#             ลิ้นชัก Console เปิดลิ้นชักแล้วเทียบสามชุดจากบนลงล่าง
# กับดัก    : ชื่อคลาสที่พิมพ์ผิด เช่น class=okay ไม่มี error ให้จับสักตัว
#             บรรทัดนั้นแค่ออกมาเป็นสีปกติ เจอบรรทัดที่ไม่มีสี ให้สงสัยชื่อคลาสก่อน

import lcd
import time
import ui

# จานสีของหลักสูตร - บทบาทละหนึ่งค่า
COL_TEXT = 0xE8EAED      # ข้อความหลัก
COL_ACCENT = 0x4A9EFF    # ค่าที่กำลังเปลี่ยน

# เนื้อความชุดเดียว เก็บระดับแยกจากข้อความ เพราะเดี๋ยวจะพิมพ์ชุดเดิมแบบไม่ติดระดับ
# เรียงจากเรื่องที่ไม่ต้องสนใจ ไปหาเรื่องที่ต้องลุกจากเก้าอี้
REPORT = [
    ("muted", "รุ่นเฟิร์มแวร์ 1.7.0"),
    ("info", "เริ่มรอบตรวจใหม่"),
    ("ok", "ต่อเน็ตสำเร็จ"),
    ("warn", "แบตเตอรี่เหลือ <b>12%</b>"),
    ("error", "อ่านเซนเซอร์ไม่ได้"),
]

ui.screen()
time.sleep_ms(200)

# หัวเรื่องอยู่แถวบนสุด เนื้อหาเริ่มที่ y=56 - จอนี้มีของอยู่สองบรรทัดก็จริง
# แต่จังหวะแนวตั้งต้องเป็นชุดเดียวกับจออื่นทั้งคาบ ไม่งั้นตาต้องหาใหม่ทุกไฟล์
ui.Label("ห้าระดับความสำคัญ", x=24, y=8, color=COL_TEXT, value=24)

# ป้ายนี้เปลี่ยนข้อความสามครั้งระหว่างรัน จึงใช้สีเน้น ไม่ใช่สีเขียว
# เขียวในหลักสูตรนี้แปลว่า "ปกติ" อย่างเดียว เอามาบอกว่า "กำลังทำอยู่" ไม่ได้
say = ui.Label("ชุดที่ 1 - ติดระดับครบทุกบรรทัด", x=24, y=56,
               color=COL_ACCENT, value=20)

# เคาะหนึ่งครั้งหลังสร้างป้ายเสร็จ ป้ายจะขึ้นจอทันทีแทนที่จะรอราวสองวินาที
ui.poll()

lcd.clear()

# <h2> ใช้ครั้งเดียวต่อชุดก็พอ ถ้าทุกบรรทัดตัวใหญ่หมด ก็ไม่มีบรรทัดไหนเด่น
lcd.console("<h2>ชุดที่ 1 ติดระดับครบ</h2>")

for cls, text in REPORT:
    # แท็กเปิดกับแท็กปิดต้องอยู่ในการเรียกครั้งเดียวกันเสมอ
    # ฝั่งจอแกะแท็กทีละบรรทัด จบบรรทัดแล้วสถานะเริ่มใหม่หมด
    # เปิด <b> ค้างไว้ในบรรทัดนี้ บรรทัดหน้าก็ไม่ได้ตัวหนาต่อให้
    lcd.print("<span class=" + cls + ">" + text + "</span>")

time.sleep_ms(1500)

# ชุดที่ 2 - เนื้อความเดิมเป๊ะ ๆ ต่างกันที่ไม่ได้ติดระดับไว้เลย
say.text("ชุดที่ 2 - เนื้อความเดิม แต่ไม่ติดระดับ")
ui.poll()
lcd.console("<h2>ชุดที่ 2 ไม่ติดระดับ</h2>")
for cls, text in REPORT:
    lcd.print(text)

time.sleep_ms(1500)

# ชุดที่ 3 - ข่าวดีที่ทาสีแดง สีไม่ได้ผิดในตัวมันเอง
# ที่ผิดคือความหมายที่คนอ่านได้รับก่อนอ่านตัวหนังสือ
say.text("ชุดที่ 3 - ข่าวดีที่ติดระดับผิด")
ui.poll()
lcd.console("<h2>ชุดที่ 3 ติดระดับผิด</h2>")
lcd.print("<span class=error>ต่อเน็ตสำเร็จ</span>")
lcd.print("<span class=muted>คนอ่านตกใจก่อนได้อ่านเนื้อความ</span>")

say.text("พิมพ์ครบ 3 ชุดแล้ว เปิดลิ้นชัก Console เทียบดู")
ui.poll()

# ----- ตาคุณ แก้แล้วรันใหม่ -----
# ใน REPORT มีบรรทัดหนึ่งที่ติดระดับไว้ผิด ลองหาว่าบรรทัดไหน แล้วแก้ให้ตรงความหมาย
# จากนั้นเพิ่มอีกหนึ่งบรรทัดเป็นข่าวของทีมคุณเอง พร้อมเลือกระดับให้มันด้วย
# ใบ้: ถามว่าบรรทัดนี้ทำให้คนที่เดินผ่านมาต้องลุกจากเก้าอี้ไหม ถ้าไม่ ก็ไม่ใช่ error
