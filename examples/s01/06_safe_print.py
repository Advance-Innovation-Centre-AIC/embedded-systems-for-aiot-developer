# 06_safe_print.py - ฟังก์ชันช่วยพิมพ์ที่ไม่มีวันโดนตัดเงียบ
#
# Why : รู้เพดาน 127 ไบต์แล้วก็จริง แต่ถ้าต้องนั่งนับไบต์ด้วยมือทุกบรรทัด
#       สักวันจะลืมสักบรรทัด แล้วรายงานจะขาดครึ่งโดยไม่มี error ให้จับ
#       ความรู้ที่ต้องใช้วินัยของคนทุกครั้ง คือความรู้ที่จะพังในวันที่คนเหนื่อย
# What: ย้ายกฎนั้นเข้าไปอยู่ในฟังก์ชันเดียว แล้วเรียกฟังก์ชันนั้นแทน lcd.print()
#       ตั้งแต่นั้นเพดานก็ไม่ใช่เรื่องที่คนต้องจำอีกต่อไป โค้ดจำแทนให้แล้ว
#
# ดูที่จอ: ตัวเลขจำนวนก้อนเพิ่มขึ้นทีละก้อน แถบไบต์ของก้อนล่าสุดขยับตาม
#          และไม่มีก้อนไหนเลยที่แถบไปชนขีดแดง ส่วนตัวข้อความอยู่ในลิ้นชัก
# กับดัก : ฟังก์ชันนี้ตัดที่ตัวอักษร ไม่ใช่ตัดที่คำ และมันไม่รู้จักแท็ก
#          ห้ามส่งข้อความที่มีแท็กเข้ามา เพราะแท็กอาจถูกตัดครึ่งกลางคัน

import lcd
import time
import ui

# 127 คือเพดานจริง เผื่อไว้ 7 ไบต์เป็นระยะปลอดภัย เผื่อ lcd เติมอะไรต่อท้าย
LIMIT = 127
SAFE_BYTES = 120

COL_TEXT, COL_DIM = 0xE8EAED, 0x9AA3AF
COL_CARD = 0x171B22
COL_OK, COL_INFO = 0x30A46C, 0x4A9EFF

ui.screen()
time.sleep_ms(200)

ui.Label("พิมพ์ยาวเท่าไรก็ไม่หาย", x=20, y=12, color=COL_TEXT, value=24)
ui.Panel(x=20, y=52, w=652, h=172, color=COL_CARD, min=COL_DIM, max=12, value=1)

ui.Label("ก้อนที่ปล่อยไปแล้ว", x=40, y=68, color=COL_DIM, value=16)
seg = ui.Seg7(text="0", x=40, y=92, w=112, h=60, color=COL_OK)

ui.Label("ขนาดก้อนล่าสุด (ไบต์)", x=248, y=68, color=COL_DIM, value=16)
bar = ui.Bar(x=212, y=100, w=420, h=28, min=0, max=LIMIT, value=0)
size_lbl = ui.Label("0 / 120 ไบต์ - เพดานจริง 127", x=212, y=136,
                    color=COL_INFO, value=16)

piece = ui.Label("ยังไม่ได้ปล่อยก้อนไหน", x=40, y=172, color=COL_TEXT, value=20)
# ห้ามสร้าง Label ด้วยข้อความว่าง LVGL จะเติมคำว่า "Label" ให้เอง
# แล้วคำนั้นจะค้างบนจอจนกว่าจะมีการเขียนทับครั้งแรก
status = ui.Label("ยังไม่ได้วัดอะไร", x=20, y=240, color=COL_DIM, value=20)


def safe_print(text):
    """พิมพ์ข้อความยาวเท่าไรก็ได้ โดยแบ่งเป็นหลายบรรทัดให้อัตโนมัติ"""
    sent = 0

    def flush(chunk):
        # ทุกก้อนที่ปล่อยออกไป รายงานขนาดมันบนจอทันที คนดูจะได้เห็นด้วยตา
        # ว่าไม่มีก้อนไหนเลยที่เกินเพดาน ไม่ต้องเชื่อคำอธิบายอย่างเดียว
        n = len(chunk.encode())
        lcd.print(chunk)
        bar.value(n)
        size_lbl.text(str(n) + " / " + str(SAFE_BYTES) + " ไบต์ - เพดานจริง 127")
        piece.text(chunk[:24] + "...")
        ui.poll()
        time.sleep_ms(400)

    # เริ่มจากกรณีง่ายก่อน สั้นพออยู่แล้วก็ส่งไปเลย ไม่ต้องทำงานเพิ่ม
    if len(text.encode()) <= SAFE_BYTES:
        flush(text)
        return 1

    chunk = ""          # ก้อนที่กำลังสะสม
    used = 0            # ความยาวเป็นไบต์ของก้อนนั้น

    for ch in text:
        # ถามความยาวของตัวอักษรตัวนี้เป็นไบต์ ไทยได้ 3 อังกฤษได้ 1
        size = len(ch.encode())

        # เช็ก "ก่อนใส่" ไม่ใช่ "หลังใส่" ไม่งั้นก้อนที่ส่งไปจะเกินเพดานไปแล้ว
        if used + size > SAFE_BYTES:
            flush(chunk)
            sent = sent + 1
            seg.text(str(sent))
            chunk = ""
            used = 0

        chunk = chunk + ch
        used = used + size

    # ตัวที่ค้างอยู่ในก้อนสุดท้ายต้องส่งด้วย ลืมบรรทัดนี้แล้วท้ายประโยคจะหายไป
    if chunk != "":
        flush(chunk)
        sent = sent + 1
        seg.text(str(sent))

    return sent


lcd.clear()
lcd.console("<h2>พิมพ์ยาวเท่าไรก็ไม่หาย</h2>")

story = ("บอร์ด Eva Kit มีคอร์สองก้อนทำงานพร้อมกัน "
         "ก้อนแรกรัน Python ที่เราเขียน อีกก้อนวาดจอกับรันโมเดล "
         "สองก้อนคุยกันผ่านกล่องจดหมายที่เรียกว่า IPC "
         "เวลาเราสั่ง lcd.print ข้อความจึงต้องเดินทางข้ามไปอีกก้อนก่อนถึงจะขึ้นจอ")

# วัดก่อน แล้วบอกคนอ่านว่ากำลังจะเจออะไร
total = len(story.encode())
status.text("ข้อความยาว " + str(total) + " ไบต์ - เกินเพดาน " +
            str(total // LIMIT) + " เท่า")
lcd.print("ข้อความยาว", total, "ไบต์")

pieces = safe_print(story)

status.text("แบ่งเป็น " + str(pieces) + " ก้อน - ไม่มีตัวอักษรไหนหายไปเลย")
piece.text("ครบทุกตัว อ่านได้ในลิ้นชัก Console")
lcd.print("<span class=ok>ครบทุกตัว ไม่มีหาย</span>")
ui.poll()

# ตัวข้อความดิบยาวเกินกว่าจะอ่านบนจอ 4.3 นิ้ว จึงส่งไปคอนโซลฝั่งคอมแทน
print("ความยาวจริงเป็นไบต์:", total, "| แบ่งได้", pieces, "ก้อน")

