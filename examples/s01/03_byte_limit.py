# 03_byte_limit.py - ข้อความยาวเกิน 127 ไบต์ จะถูกตัดหายเงียบ ๆ
#
# ไฟล์นี้สอน: จอนับไบต์ ไม่ได้นับตัวอักษร ไทยหนึ่งตัวกิน 3 ไบต์
# ดูที่จอ   : ตัวเลขไบต์ของก้อนที่กำลังวัด เปลี่ยนทุกวินาที
#             เขียวคือส่งได้ครบ แดงคือเกินเพดาน ข้อความจริงไปรอในลิ้นชัก Console
# กับดัก    : การตัดเกิดขึ้นเงียบ ๆ ไม่มี error ให้จับ และ \n ท้ายบรรทัดหายไปด้วย
#             บรรทัดถัดไปจึงมาต่อท้ายกันเละโดยที่เราไม่รู้ตัว

import lcd
import time
import ui

LIMIT = 127
CHUNK = 40          # แบ่งเองทีละกี่ตัวอักษร (ไทย 40 ตัว = 120 ไบต์)
SHOW_MS = 900       # ค้างแต่ละก้อนไว้บนจอนานเท่าไร ให้อ่านทัน

# จานสีของหลักสูตร - บทบาทละหนึ่งค่า
# เขียวกับแดงที่นี่เป็นคำตัดสินจริง ๆ ว่าก้อนนี้ส่งครบหรือโดนตัด ไม่ใช่สีตกแต่ง
COL_TEXT, COL_DIM = 0xE8EAED, 0x9AA3AF
COL_CARD = 0x171B22
COL_OK, COL_BAD = 0x30A46C, 0xE5484D

# ยาว 66 ตัวอักษร แต่กินถึง 198 ไบต์ - ตั้งใจให้เกินเพดาน
LONG_LINE = "บอร์ดนี้มีสมองสองก้อนคือคอร์สามสามกับคอร์ห้าห้าทำงานคนละหน้าที่กัน"

# แท็กเปล่า ๆ ก็กินไบต์ไปแล้วก่อนที่เราจะพิมพ์อะไรลงไปสักตัว
TAG = "<span class=muted></span>"

ITEMS = [
    ("hello - อังกฤษ 5 ตัว", "hello"),
    ("สวัสดี - ไทย 6 ตัว", "สวัสดี"),
    ("แท็ก span เปล่า ๆ", TAG),
    ("ประโยคยาว ส่งทั้งก้อน", LONG_LINE),
]

# ตัดที่ตัวอักษร ไม่ใช่ตัดที่ไบต์ เพราะการตัดกลางไบต์ของตัวอักษรหนึ่งตัว
# จะได้ข้อมูลที่ถอดรหัสไม่ออก แล้วจอจะแสดงเป็นขยะ
for start in range(0, len(LONG_LINE), CHUNK):
    part = LONG_LINE[start:start + CHUNK]
    ITEMS.append(("แบ่งเอง ก้อนที่ " + str(start // CHUNK + 1), part))

ui.screen()
time.sleep_ms(200)

ui.Label("นับไบต์ก่อนพิมพ์", x=24, y=8, color=COL_TEXT, value=28)

# การ์ดใบเดียวถือทั้งตัวเลขและคำอธิบาย ตัวเลขอยู่ซ้าย เรื่องเล่าอยู่ขวา
# ตาคนอ่านซ้ายไปขวา จึงเจอ "เท่าไร" ก่อน แล้วค่อยเจอ "ของอะไร"
ui.Panel(x=24, y=56, w=744, h=224, color=COL_CARD, min=COL_CARD, max=12,
         value=1)

# ตัวเลขลอย ๆ ไม่มีความหมาย ป้ายหน่วยข้างบนคือสิ่งที่ทำให้มันอ่านได้
ui.Label("ขนาดเป็นไบต์", x=40, y=88, color=COL_DIM, value=20)

# Seg7 รับ "ข้อความ" เท่านั้น seg.value(198) เงียบสนิทและไม่มีอะไรเกิดขึ้น
# ขนาดตัวเลขของ Seg7 ตายตัวที่ 28 px ส่วน w กับ h คุมแค่กล่องที่มันนั่งอยู่
seg = ui.Seg7(text="0", x=40, y=128, w=208, h=96, color=COL_OK)

what = ui.Label("กำลังจะเริ่มวัด", x=288, y=88, color=COL_TEXT, value=24)
status = ui.Label("ยังไม่ได้วัดก้อนไหน", x=288, y=152, color=COL_DIM, value=20)

# แถบล่างสุดบอกเพดานไว้ตลอดเวลา คนที่เดินมาดูกลางทางจะได้ไม่ต้องเดาว่าเทียบกับอะไร
ui.Label("เพดานจริง 127 ไบต์ต่อหนึ่งครั้ง", x=24, y=352, color=COL_DIM,
         value=20)

lcd.clear()
lcd.console("<h2>นับไบต์ก่อนพิมพ์</h2>")

for name, text in ITEMS:
    # len() ของสตริงนับตัวอักษร ส่วน len() ของ bytes นับไบต์ สองค่านี้ต่างกัน
    nbytes = len(text.encode())

    what.text(name + " - " + str(len(text)) + " ตัวอักษร")
    seg.text(str(nbytes))

    if nbytes > LIMIT:
        seg.color(COL_BAD)
        status.text(str(nbytes) + " ไบต์ เกินเพดาน ส่วนที่เกินหายเงียบ ๆ")
    else:
        seg.color(COL_OK)
        status.text(str(nbytes) + " ไบต์ ส่งได้ครบทุกตัว")

    # ส่งข้อความจริงลงลิ้นชัก จะได้เห็นกับตาว่าจอตัดตรงไหน
    lcd.print("<span class=muted>" + name + "</span>")
    lcd.print(text)

    ui.poll()
    time.sleep_ms(SHOW_MS)

# ก้อนที่ 4 คือประโยคเต็มที่โดนตัด ก้อนที่ 5-6 คือประโยคเดียวกันที่แบ่งเอง
what.text("วัดครบทุกก้อนแล้ว")
status.text("เทียบก้อนที่ 4 กับก้อนที่ 5-6 ในลิ้นชัก")
lcd.print("<span class=ok>วัดครบแล้ว - แบ่งก่อนส่ง จึงได้ครบ</span>")
ui.poll()

# ----- ตาคุณ แก้แล้วรันใหม่ -----
# ใส่ชื่อสมาชิกในทีมเป็นภาษาไทยลงใน ITEMS อีกหนึ่งแถว แล้วทำนายก่อนรันว่า
# ตัวเลขไบต์จะขึ้นเป็นเท่าไร และจะเป็นสีเขียวหรือสีแดง จากนั้นรันเทียบกับที่ทำนาย
# ใบ้: นับตัวอักษรไทยก่อน แล้วคูณสาม ช่องว่างกับตัวเลขนับหนึ่งไบต์
