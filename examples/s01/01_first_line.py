# 01_first_line.py - บรรทัดแรกที่ขึ้นจอบอร์ด
#
# ไฟล์นี้สอน: ข้อความหนึ่งบรรทัดไปได้สามปลายทาง และแต่ละทางอยู่คนละที่
# ดูที่จอ   : ป้ายหนึ่งใบบนหน้า Playground เห็นทันที
#             ส่วนสองบรรทัดของ lcd รออยู่ในลิ้นชัก Console มุมขวาล่าง
# กับดัก    : ถ้าไม่ได้แตะการ์ด Playground บนหน้า Home ก่อน จอจะเงียบสนิท
#             ทั้งที่โค้ดรันจบแล้ว หลายทีมสรุปว่าโค้ดพัง ทั้งที่แค่ยืนผิดหน้า

import lcd
import time
import ui

# จานสีของหลักสูตร - บทบาทละหนึ่งค่า
COL_TEXT = 0xE8EAED      # ข้อความหลัก
COL_ACCENT = 0x4A9EFF    # ค่าที่กำลังเปลี่ยน

# ล้าง widget เดิมทิ้ง แล้วหน่วงให้คอร์ CM55 ล้างจอเสร็จก่อน
ui.screen()
time.sleep_ms(200)

# หัวเรื่องหนึ่งบรรทัดบนสุด แล้วเนื้อหาเริ่มที่ y=56 เป็นจังหวะเดียวกันทุกจอในคาบนี้
ui.Label("บรรทัดแรกที่ขึ้นจอบอร์ด", x=24, y=8, color=COL_TEXT, value=28)

# ปลายทางที่ 1 - ป้ายบนหน้า Playground เห็นได้โดยไม่ต้องกดอะไร
# ทาสีเน้นเพราะมันคือป้ายที่ข้อความจะเปลี่ยนระหว่างรัน ไม่ใช่เพราะอยากให้สวย
say = ui.Label("กำลังพิมพ์ลงลิ้นชัก Console...", x=24, y=56,
               color=COL_ACCENT, value=24)

# สร้างป้ายแล้วต้องเคาะ ui.poll() หนึ่งครั้ง ป้ายถึงจะโผล่ทันที
# ถ้าไม่เคาะ ป้ายก็ยังมาอยู่ดี แต่ช้าไปราวสองวินาที ซึ่งนานพอที่คนดูจะสรุปว่าโค้ดพัง
ui.poll()

# ปลายทางที่ 2 - ลิ้นชัก Console ล้างก่อน จะได้แยกออกว่าบรรทัดไหนของรอบนี้
lcd.clear()
lcd.print("สวัสดี บอร์ด PSoC Edge")
lcd.print("หนึ่งบวกหนึ่งได้", 1 + 1)      # ตัวเลขส่งได้เลย ไม่ต้องแปลงก่อน

# ปลายทางที่ 3 - print() ธรรมดาไม่ได้อยู่บนบอร์ด มันขึ้นที่คอนโซลฝั่งคอม
print("บรรทัดนี้อยู่บนคอม ไม่ได้อยู่บนจอบอร์ด")

time.sleep_ms(1000)

# แก้ข้อความบนป้ายเดิม ไม่ใช่วางป้ายใหม่ทับ
# ป้ายหนึ่งใบที่เปลี่ยนค่าได้ อ่านง่ายกว่าป้ายสิบใบที่กองทับกัน
say.text("พิมพ์ 2 บรรทัดแล้ว - เปิดลิ้นชัก Console เพื่ออ่าน")
ui.poll()
lcd.print("<span class=ok>จบแล้ว</span>")

# ----- ตาคุณ แก้แล้วรันใหม่ -----
# เพิ่มชื่อทีมของคุณเข้าไปในทั้งสามปลายทาง คือป้ายบนจอ บรรทัดในลิ้นชัก
# และ print() ฝั่งคอม แล้วตอบว่าต้องเปิดดูที่ไหนบ้างถึงจะเห็นครบทั้งสามที่
# ใบ้: ปลายทางที่สามไม่ได้อยู่บนบอร์ดเลย ต้องมองที่หน้าจอคอมของตัวเอง
