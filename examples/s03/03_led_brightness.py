# 03_led_brightness.py - หรี่ไฟค้างไว้ให้นานพอที่ตาจะเทียบสองระดับได้
#
# Why : ทีมหนึ่งสั่งหรี่ไฟทีละระดับแล้วเงยหน้าไปมองหลอด ไม่เห็นความต่างสักระดับ
#       จึงสรุปกันว่าหลอดเสีย ที่จริงคำสั่งทำงานถูกทุกครั้ง แต่บนดวงที่ทีมนั้นใช้
#       มันจบเร็วเกินกว่าที่ตาจะทัน สิ่งที่ขาดไม่ใช่ค่าที่ถูก แต่คือเวลาที่นานพอ
# What: led.brightness(pct) เลือกทางตามขาของหลอด ดวงที่มีเส้น PWM ของฮาร์ดแวร์
#       (ดวง RGB ของทั้งสองบอร์ด) ค้างระดับไว้ได้จนกว่าจะสั่งใหม่ ดวงที่ไม่มีเส้นนั้น
#       ได้พัลส์ราว 12 ms แล้วจบด้วยหลอดดับ ท่าที่ค้างได้แน่ทุกดวงคือ
#       led.hold(pct, ms) ซึ่งย้ำพัลส์เดิมซ้ำจนครบเวลาที่สั่ง แล้วจบด้วยหลอดดับเสมอ
#       (ที่มา: modgpio.c ตาราง s_led_pwm_routes คือดวงที่มี PWM, gpio_led_hold คือ hold)
#
# ดูที่จอ: ตัวเลขบอกเปอร์เซ็นต์ที่กำลังสั่งค้างอยู่ตอนนั้น ให้มองหลอดจริง
#          สลับไปมาระหว่าง 10 กับ 90 สองระดับนี้ต่างกันจนเห็นได้ด้วยตาเปล่า
# กับดัก : duty() คืนเปอร์เซ็นต์ครั้งล่าสุดที่เราสั่ง ไม่ได้ไปวัดจากหลอดจริง
#          พอ hold() จบ หลอดดับแล้ว แต่ duty() ยังคืนเลขเดิมอยู่ดี
#          ตัวเลขบนจอจึงไม่ใช่หลักฐานว่าหลอดกำลังสว่างอยู่
#          และ toggle() ไม่ได้ไปแก้ตัวเลขนั้นเลย ท่าที่ 3 ข้างล่างพิสูจน์ให้ดู
# หมายเหตุ: brightness(0) กับ brightness(100) เป็นทางลัด สั่งขาตรง ๆ แล้วค้างไว้ทุกดวง
#          ไม่ได้จบด้วยหลอดดับเหมือนค่ากลาง 1-99 บนดวงที่ไม่มี PWM - hold() ก็แบ่งเป็นสองทางเดียวกัน

import gpio
import lcd
import time
import ui

LOW, HIGH = 10, 90      # สองระดับที่เอามาเทียบกัน ห่างกันพอให้ตาแยกออก
HOLD_MS = 700           # ค้างแต่ละระดับนานเท่าไร
ROUNDS = 3              # สลับสองระดับกี่รอบ

COL_TEXT, COL_DIM = 0xE8EAED, 0x9AA3AF
COL_OK, COL_WARN, COL_INFO = 0x30A46C, 0xF5A623, 0x4A9EFF

# เลือกดวงจากชื่อที่ board_info() รายงาน ไม่ใช่จากเลขที่จำมา
# ดวง RGB มองเห็นแน่บนบอร์ดที่ประกอบแล้ว และมีเส้น PWM ของฮาร์ดแวร์ทั้งสองบอร์ด
# ถ้าบอร์ดไม่มีดวงชื่อ RGB_ ก็ใช้ดวงแรก - เลขดัชนีอาจถูกจัดใหม่ในรุ่นหน้า
# หมายเหตุ Eva Kit: ดวงที่ชื่อ RGB_RED บนบอร์ดนั้นคือหลอดสีน้ำเงินจริง ๆ (ชื่อในตาราง
#   เฟิร์มแวร์ไม่ตรงกับสี - กับดักที่คาบ 3 พูดถึง) ไฟล์นี้ต้องการแค่ "ดวงที่มองเห็น" ไม่ได้ต้องการสี
LED = 0
for i, name in enumerate(gpio.board_info()["led_names"]):
    if name.startswith("RGB_"):
        LED = i
        break

led = gpio.led(LED)
led.off()

ui.screen()
time.sleep_ms(200)

ui.Label("หรี่ไฟให้ค้างนานพอจะมองเห็น", x=20, y=12, color=COL_TEXT, value=24)
seg = ui.Seg7(text="0", x=20, y=60, w=152, h=64, color=COL_WARN)
ui.Label("% ที่สั่งค้างอยู่", x=192, y=84, color=COL_DIM, value=20)
what = ui.Label("กำลังจะเริ่ม", x=20, y=144, color=COL_INFO, value=20)
back = ui.Label("ยังไม่ได้อ่าน duty()", x=20, y=184, color=COL_DIM, value=20)
note = ui.Label("มองหลอด " + led.name() + " บนบอร์ด ไม่ใช่มองแต่จอ", x=20,
                y=232, color=COL_DIM, value=20)

lcd.clear()
lcd.console("<h2>หรี่ไฟให้ค้างนานพอจะมองเห็น</h2>")

# ท่าที่ 1 - สั่งครั้งเดียว เงยหน้าขึ้นมอง บอร์ดตอบด้วยหลอด ไม่ใช่ด้วยข้อความ
# ดวงที่มีเส้น PWM จะค้างที่ 40 ให้เห็น ดวงที่ไม่มีจะวูบแล้วดับก่อนตาจะทัน
# เขียนป้ายก่อนสั่งเสมอ เพราะบรรทัดที่สั่งอาจบล็อกไว้จนกว่าจะทำงานเสร็จ
# ป้ายที่เขียนทีหลังคำสั่งที่บล็อก จะขึ้นจอตอนที่ของจริงจบไปแล้ว
what.text("brightness(40) ครั้งเดียว - มองหลอด ค้างหรือวูบ")
seg.text("40")
ui.poll()

led.brightness(40)

back.text("duty() = " + str(led.duty()) + " - ตัวเลขไม่บอกว่าค้างหรือดับ")
lcd.print("brightness(40) ดวง", led.name(), "- ค้างไหม ดูที่หลอด")
time.sleep_ms(1500)

# กลับสู่สถานะที่รู้แน่ก่อนท่าถัดไป: off() คืนขาจากเส้น PWM ให้เป็น GPIO ธรรมดา
# hold() บิตแบงก์ที่ขา GPIO ถ้าขายังต่ออยู่กับ PWM ของท่าที่ 1 มันจะไม่เห็นผลเลย
led.off()

# ท่าที่ 2 - สั่งค้าง สลับสองระดับ ระดับละ HOLD_MS
for k in range(ROUNDS):
    for pct in (LOW, HIGH):
        seg.text(str(pct))
        what.text("hold(" + str(pct) + ", " + str(HOLD_MS) + ") กำลังค้างอยู่")
        ui.poll()

        # จับเวลาจริงคร่อมคำสั่งไว้ เพื่อพิสูจน์เองว่ามันค้างครบตามที่สั่ง
        t0 = time.ticks_ms()
        led.hold(pct, HOLD_MS)
        used = time.ticks_diff(time.ticks_ms(), t0)

        back.text("duty() = " + str(led.duty()) + " ใช้เวลาจริง " +
                  str(used) + " ms")
        lcd.print("hold(", pct, ",", HOLD_MS, ") ใช้เวลา", used, "ms")

        # hold() จบด้วยหลอดดับเสมอ ช่วงสั้น ๆ ตรงนี้จึงเป็นช่วงที่หลอดดับจริง
        # ระดับหนึ่งจะเห็นได้เฉพาะระหว่างที่ hold ของมันเองยังทำงานอยู่เท่านั้น
        ui.poll()
        time.sleep_ms(150)

# ท่าที่ 3 - duty() ตอบ "สั่งอะไรไปล่าสุด" ไม่ใช่ "หลอดเป็นอย่างไรตอนนี้"
# on() off() และ value(n) เขียนตัวเลขนี้ให้ตรงกับขาเสมอ แต่ toggle() ไม่แตะมันเลย
# จึงเป็นจุดเดียวที่ duty() กับหลอดจริงจะไม่ตรงกัน และไม่มี error ให้จับ
what.text("ท่าที่ 3 - on() แล้ว toggle() ดูตัวเลขของ duty()")
ui.poll()

led.on()
d_on = led.duty()               # 100 ตามที่ on() เขียนไว้
time.sleep_ms(600)

led.toggle()                    # หลอดดับแล้ว แต่ตัวเลขของ duty ไม่ได้ขยับตาม
d_after = led.duty()

back.text("on() duty=" + str(d_on) + "  toggle() duty=" + str(d_after))
lcd.print("toggle() ดับหลอด แต่ duty() ยังตอบ", d_after)
lcd.print("<span class=muted>duty() = สิ่งที่สั่ง ไม่ใช่สิ่งที่วัด</span>")
ui.poll()
time.sleep_ms(1200)

led.off()
what.text("จบแล้ว - เทียบ 10 กับ 90 ที่เพิ่งเห็นเมื่อกี้")

# ค่าที่ส่งห่างกันเก้าเท่า แต่ตาไม่ได้เห็นว่าสว่างต่างกันเก้าเท่า
# ตาคนไม่ตอบสนองเป็นเส้นตรง 50% จึงไม่ได้แปลว่าสว่างครึ่งหนึ่งของ 100%
note.text("ส่งห่างกัน 9 เท่า ตาไม่ได้เห็นต่างกัน 9 เท่า")
lcd.print("<span class=ok>ระดับจะเห็นได้ ต่อเมื่อสั่งค้างไว้</span>")
ui.poll()
