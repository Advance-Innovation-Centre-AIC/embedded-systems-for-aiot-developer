# 04_magnet_presence.py - ตรวจว่ามีแม่เหล็กอยู่ใกล้หรือไม่
# ชุดตัวอย่างประจำคาบ 08
#
# Why : ฝากล่องที่รู้ว่าถูกเปิด แปรงสีฟันไฟฟ้าที่รู้ว่าวางบนแท่นชาร์จ และมิเตอร์น้ำ
#       ที่นับรอบใบพัดจากแม่เหล็กเม็ดเดียวบนใบ ทั้งหมดถามคำถามเดียว "ตอนนี้มี
#       แม่เหล็กอยู่ใกล้ไหม" โดยไม่ต้องแตะกัน แต่สนามพื้นหลังของแต่ละห้องไม่เท่ากัน
#       เกณฑ์ที่ฝังตายตัวมาจากห้องหนึ่ง จึงพังทันทีเมื่อย้ายไปอีกห้อง
# What: ตัวตรวจจับที่ใช้ได้จริงวัดเทียบเส้นฐานที่เก็บเองตอนเริ่ม และคิดเกณฑ์จาก
#       ความผันผวนของห้องนั้นเอง ไม่ใช่จากตัวเลขที่เดามา เกณฑ์จึงย้ายห้องไปกับบอร์ด
#
# ดูที่จอ: เส้นแดงคือเกณฑ์ เส้นฟ้าคือค่าเบี่ยงตอนนี้ เอาแม่เหล็กเข้าใกล้แล้วดูเส้นฟ้า
#          พุ่งข้ามเส้นแดง ป้ายล่างเปลี่ยนเป็น "พบแม่เหล็ก" พร้อมกับตอนที่เส้นตัดกัน
# กับดัก : ห้ามฝังตัวเลขเกณฑ์ตายตัวลงโค้ด ค่าที่ใช้ได้ในห้องเรียนจะพังทันทีเมื่อย้าย
#          ไปวางบนโต๊ะเหล็กหรือใกล้จอคอมพิวเตอร์
#
# [หน่วยยังไม่ยืนยัน] sensors.bmm350.magnetic() คืนตัวเลขที่คอมเมนต์ในไดรเวอร์
#   เรียกว่า uT แต่ภาพจากบอร์ดวัดขนาดรวมสามแกนได้ราว 1532 ขณะที่สนามแม่เหล็กโลก
#   อยู่ที่ 25-65 uT ตัวเลขกับหน่วยจริงพร้อมกันไม่ได้ ยังไม่ตัดสินว่าอันไหนผิด
#   ไฟล์นี้จึงเลิกเขียน uT ทุกจุด และวัดเป็น "เบี่ยงจากเส้นฐานที่เก็บเอง" แทน
#   ซึ่งไม่ต้องรู้หน่วยก็ใช้งานได้ - นั่นคือเหตุผลที่ไฟล์นี้ยังเชื่อถือได้อยู่

import lcd
import math
import sensors
import time
import ui

SAMPLES = 20       # จำนวนตัวอย่างที่ใช้หาเส้นฐาน
THRESH_K = 6.0     # ต้องเบี่ยงเกินกี่เท่าของความผันผวนพื้นหลัง ถึงนับว่าเจอ
FLOOR_DEV = 8.0    # พื้นล่างของเกณฑ์ กันกรณีห้องนิ่งจนความผันผวนเกือบศูนย์


def magnitude():
    mx, my, mz = sensors.bmm350.magnetic()
    return math.sqrt(mx * mx + my * my + mz * mz)


ui.screen()
ui.Label("ตัวตรวจจับแม่เหล็ก", x=12, y=8, value=24)
ui.Label("ฟ้า = เบี่ยงจากเส้นฐาน", x=496, y=44, value=16, color=0x4A9EFF)
ui.Label("แดง = เกณฑ์ที่คำนวณได้", x=496, y=68, value=16, color=0xE5484D)
ui.Label("เบี่ยงตอนนี้ (หน่วยบอร์ด)", x=496, y=100, value=16)
seg = ui.Seg7(x=496, y=124, w=180, h=44)
ui.Label("เทียบเกณฑ์ (100% = ถึงเกณฑ์)", x=484, y=180, value=16)
bar = ui.Bar(x=496, y=216, w=180, h=16, min=0, max=100)

ui.Panel(x=12, y=268, w=472, h=68)
st = ui.Label("กำลังเก็บเส้นฐาน", x=24, y=276, value=24)
sub = ui.Label("อย่าขยับบอร์ด", x=24, y=304, value=20)
ui.poll()

lcd.clear()
lcd.console("<h2>ตัวตรวจจับแม่เหล็ก</h2>")
lcd.print("กำลังเก็บเส้นฐาน อย่าขยับบอร์ด...")

# เก็บทั้งค่าเฉลี่ยและความผันผวน เพราะเกณฑ์ต้องมาจากเสียงรบกวนจริงของห้องนี้
vals = []
for i in range(SAMPLES):
    vals.append(magnitude())
    bar.value(int((i + 1) * 100 / SAMPLES))
    ui.poll()
    time.sleep_ms(60)

mean = sum(vals) / len(vals)
spread = sum(abs(v - mean) for v in vals) / len(vals)
thresh = max(FLOOR_DEV, spread * THRESH_K)

lcd.print("เส้นฐาน", int(mean), "| ผันผวน", round(spread, 1))
lcd.print("เกณฑ์ที่คำนวณได้:", int(thresh), "(หน่วยบอร์ด)")

# แกน Y ต้องเผื่อเหนือเกณฑ์ ไม่งั้นตอนพบแม่เหล็กเส้นจะชนขอบบนจนอ่านไม่ออก
ch = ui.Chart(x=12, y=44, w=472, h=212, min=0, max=max(20, int(thresh * 2.5)))
s_dev = 0
s_thr = ch.add_series(0xFF5555)
st.text("ยังไม่พบแม่เหล็ก")
st.color(0x9AA0A6)
sub.text("เส้นฐาน %d | เกณฑ์ %d" % (int(mean), int(thresh)))
ui.poll()

present = False
for _ in range(600):
    dev = abs(magnitude() - mean)
    now = dev >= thresh

    ch.set_next(s_dev, int(dev))
    ch.set_next(s_thr, int(thresh))      # เส้นแนวนอน = เกณฑ์ ให้ตาเทียบได้ทันที
    seg.text(str(int(dev)))
    bar.value(int(min(100.0, dev / thresh * 100.0)))

    # รายงานเฉพาะตอนสถานะเปลี่ยน ไม่ใช่ทุกรอบ
    if now != present:
        present = now
        if present:
            st.text("พบแม่เหล็ก")
            st.color(0x55DD55)
            lcd.print("<span class=ok>พบแม่เหล็ก - เบี่ยง " +
                      str(int(dev)) + "</span>")
        else:
            st.text("ยังไม่พบแม่เหล็ก")
            st.color(0x9AA0A6)
            lcd.print("<span class=muted>แม่เหล็กออกไปแล้ว</span>")

    ui.poll()
    time.sleep_ms(80)

lcd.print("เกณฑ์นี้คิดจากห้องนี้ ย้ายห้องแล้วรันใหม่")
print("เกณฑ์คำนวณจากห้องนี้ ไม่ใช่ตัวเลขที่เดามา ย้ายห้องแล้วรันใหม่ได้เลย")
