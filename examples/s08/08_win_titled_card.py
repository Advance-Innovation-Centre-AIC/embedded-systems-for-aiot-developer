# 08_win_titled_card.py - การ์ดที่มีชื่อกำกับมาในตัว และหัวเรื่องที่แก้ไม่ได้
# ชุดตัวอย่างประจำคาบ 08
#
# Why : dashboard ของคาบนี้คือการ์ดสี่ใบ และทุกใบต้องมีชื่อกำกับ ไม่งั้นคนที่
#       เพิ่งเดินมาถึงหน้าจอไม่รู้ว่าตัวเลขที่เห็นคือค่าอะไร วิธีที่เราใช้มา
#       ตลอดคือ ui.Panel หนึ่งใบบวก ui.Label หนึ่งใบเป็นหัวเรื่อง ซึ่งแปลว่า
#       ตำแหน่งของหัวเรื่องเป็นความรับผิดชอบของเรา และมันเลื่อนไม่ตรงกันทุกครั้ง
#       ที่การ์ดย้ายที่
# What: ui.Win คือกรอบที่มีแถบหัวเรื่องมาให้แล้วจากเฟิร์มแวร์ text= คือข้อความ
#       บนแถบหัว ส่วนตัวเนื้อในเป็นกล่องอีกใบที่ .content() คืนมา
# How : wn = ui.Win(text="ชื่อการ์ด", ...) แล้ว body = wn.content() จากนั้นทุก
#       widget ที่จะอยู่ในการ์ดใบนี้สร้างด้วย parent=body และพิกัดนับจากมุม
#       ซ้ายบนของเนื้อใน ซึ่งอยู่ใต้แถบหัวลงมา
#
# ดูที่จอ: การ์ดสองใบเรื่องเดียวกัน ซ้ายเป็น ui.Win ขวาเป็น Panel+Label แบบเดิม
#          ทั้งคู่โชว์ระดับเสียงจากไมค์ตัวเดียวกัน แต่หัวเรื่องของใบขวาพาค่าล่าสุด
#          ไปด้วยได้ ส่วนหัวเรื่องของใบซ้ายค้างอยู่ที่ข้อความตอนสร้าง
# กับดัก : หัวเรื่องของ Win แก้ไม่ได้หลังสร้าง - ui_widget_mgr_set_text() ไม่มี
#          case ของชนิด Win เลย คำสั่ง .text() จึงตกไปที่ default แล้วไม่ทำอะไร
#          ไม่มี error ไม่มีคำเตือน จอไม่ขยับสักพิกเซล ไฟล์นี้สั่งเปลี่ยนหัวเรื่อง
#          ทุกรอบแล้วนับจำนวนครั้งไว้ให้ดู - เลขที่ป้ายล่างซ้ายรายงาน คือจำนวน
#          คำสั่งที่หายไปเงียบ ๆ ดังนั้น "ค่าที่เปลี่ยนได้ ห้ามอยู่บนหัวเรื่อง"
#          และแถบหัวยังกินความสูงไป 65 พิกเซล (วัดจากภาพเรนเดอร์ของไฟล์นี้เอง
#          16 ส.ค. 2026 แถบกิน y 132 ถึง 196 เนื้อในเริ่มที่ 197) ความสูงที่
#          เหลือให้เนื้อในจึงเป็น h ลบ 65 ไม่ใช่ h - ตั้ง h เท่าการ์ดข้าง ๆ
#          แล้วบรรทัดสุดท้ายในการ์ดใบนี้จะหายก่อนเพื่อนโดยไม่มีอะไรเตือน
#
# บน Eva Kit: mic ฝังมากับเฟิร์มแวร์ import ได้เลย ค่าที่เห็นมาจากไมค์จริง

import lcd
import mic
import time
import ui

COL_TEXT = 0xE8EAED
COL_DIM = 0x9AA3AF
COL_CARD = 0x171B22
COL_ACCENT = 0x4A9EFF

SENS = 3            # ความไวของไมค์ 1 ถึง 5 เท่ากับที่ใช้ใน 02_mic_sound_level_meter
ROUNDS = 90
PERIOD_MS = 200     # ตัวเลขที่คนต้องอ่าน ห้ามอัปเดตถี่กว่า 1 ครั้งต่อวินาที
SHOW_EVERY = 5      # 5 รอบ x 200 ms = 1 วินาที ตามเกณฑ์ S7.7.4

ui.screen()
time.sleep_ms(200)

ui.Label("การ์ดที่มีชื่อกำกับในตัว", x=24, y=8, color=COL_TEXT, value=28)

# ---- การ์ดใบซ้าย: ui.Win หัวเรื่องมาจากเฟิร์มแวร์ -------------------------
wn = ui.Win(text="ระดับเสียงในห้อง", x=24, y=56, w=360, h=304, color=COL_CARD)

# เรียก .content() ครั้งเดียวแล้วเก็บไว้ใช้ - เรียกซ้ำได้แฮนเดิลเดิมก็จริง
# (register_object() หาเจอว่าเคยจดไว้แล้ว) แต่การถือตัวแปรไว้อ่านง่ายกว่า
body = wn.content()

ui.Label("ค่าล่าสุด", x=24, y=16, color=COL_DIM, value=20, parent=body)
win_val = ui.Label("--", x=24, y=48, color=COL_TEXT, value=28, parent=body)
win_bar = ui.Bar(x=24, y=104, w=296, h=32, min=0, max=100, value=0, parent=body)
ui.Label("ช่วงปกติ 0 ถึง 60", x=24, y=152, color=COL_DIM, value=20,
         parent=body)

# ---- การ์ดใบขวา: Panel + Label แบบที่ใช้มาตลอดคาบ -------------------------
ui.Panel(x=408, y=56, w=360, h=304, color=COL_CARD, max=8)

# หัวเรื่องใบนี้เป็น Label ของเราเอง จึงพาค่าล่าสุดไปด้วยได้
pan_head = ui.Label("ระดับเสียงในห้อง", x=432, y=72, color=COL_TEXT, value=24)
ui.Label("ค่าล่าสุด", x=432, y=120, color=COL_DIM, value=20)
pan_val = ui.Label("--", x=432, y=152, color=COL_TEXT, value=28)
pan_bar = ui.Bar(x=432, y=216, w=296, h=32, min=0, max=100, value=0)
ui.Label("ช่วงปกติ 0 ถึง 60", x=432, y=264, color=COL_DIM, value=20)

# ---- สองบรรทัดล่าง: ผลของการสั่งเปลี่ยนหัวเรื่อง --------------------------
line = ui.Label("ยังไม่ได้สั่งเปลี่ยนหัวเรื่อง", x=24, y=368, color=COL_DIM,
                value=20)

lcd.clear()
lcd.console("<h2>ui.Win - การ์ดที่มีหัวเรื่องมาให้</h2>")
lcd.print("ซ้าย Win + content() = 2 แฮนเดิล / ขวา Panel + Label = 2 แฮนเดิล")
lcd.print("ราคาเท่ากัน ต่างกันที่ใครเป็นคนจัดตำแหน่งหัวเรื่อง")

mic.start(sens=SENS)
lcd.print("เปิดไมค์ที่ความไว", SENS, "จาก 5 - พูดใส่บอร์ดได้เลย")

asked = 0
level = 0

for i in range(ROUNDS):
    level = mic.level()

    if i % SHOW_EVERY == 0:
        # ทั้งสองการ์ดได้ค่าเดียวกัน ต่างกันแค่ที่ที่เอาไปเขียน
        text = str(level)
        win_val.text(text)
        win_bar.value(level)
        pan_val.text(text)
        pan_bar.value(level)

        # ใบขวาเขียนค่าไว้บนหัวเรื่องได้ เพราะหัวเรื่องเป็น Label ของเราเอง
        pan_head.text("ระดับเสียง " + text)

        # ใบซ้ายสั่งอย่างเดียวกัน แล้วไม่มีอะไรเกิดขึ้น - นับไว้ให้เห็นเป็นตัวเลข
        wn.text("ระดับเสียง " + text)
        asked += 1
        line.text("สั่งเปลี่ยนหัว Win " + str(asked) + " ครั้ง หัวยังเหมือนเดิม")

    ui.poll()
    time.sleep_ms(PERIOD_MS)

lcd.print("<span class=warn>สั่งเปลี่ยนหัว Win", asked, "ครั้ง จอไม่ขยับ</span>")
print("Win: text= ตอนสร้างเท่านั้น, .content() คือที่ของข้างใน")

# ตาคุณ
# 1) เปรียบเทียบสองการ์ดตอนพูดใส่บอร์ด - ใบขวาบอกค่าได้ตั้งแต่หัวเรื่อง
#    ใบซ้ายบอกไม่ได้ ลองตอบว่าถ้าเป็นเครื่องจริงในโรงงาน แบบไหนอันตรายกว่ากัน
#    เมื่อคนอ่านหัวเรื่องแล้วเชื่อว่ามันคือค่าปัจจุบัน
# 2) เปลี่ยน h ของ Win จาก 304 เป็น 220 แล้วรันใหม่ - ป้าย "ช่วงปกติ" จะหายไป
#    เพราะเนื้อในเหลือ 200 ลบ 65 เท่ากับ 135 พิกเซล ส่วนป้ายนั้นอยู่ที่ y=152
# 3) ลอง wn.content() ซ้ำอีกครั้งแล้วพิมพ์ .id() เทียบกับ body.id() บนบอร์ดจริง
#    ตัวเลขต้องเท่ากัน เพราะ CM55 จดไว้แล้วว่า object นี้มีแฮนเดิลอะไร
