# ชุดตัวอย่างประจำคาบ 08
#
# ไฟล์นี้สอน: mic.level() ยุบคลื่นเสียงทั้งชุดเหลือตัวเลขเดียวที่เอาขึ้นจอได้เลย
# ดูที่จอ   : แถบยาวขึ้นตามความดัง ตัวเลข 0-100 ในหน้าต่าง 7 ส่วน และกราฟตามเวลา
#             พูดใส่บอร์ดแล้วทั้งสามอย่างต้องขยับพร้อมกัน เงียบแล้วต้องตกลงมาเอง
# กับดัก    : ค่าเฉลี่ยธรรมดาของคลื่นเสียงเป็นศูนย์เสมอ เพราะคลื่นแกว่งรอบศูนย์
#             ถ้าจะเขียนเอง ต้องยกกำลังสองก่อนเฉลี่ย ซึ่ง rms() ทำให้แล้ว
#
# บน Eva Kit: mic ฝังมากับเฟิร์มแวร์ import ได้เลย ไม่ต้องคัดลอกไฟล์ไปไว้บนบอร์ด
#   วัดจริงบนบอร์ด 14 ส.ค. 2026 ห้องเงียบได้ rms 30 (ระดับ 7) พูดปกติราว 1000
#   (ระดับ 54) เปิดโทนใส่ไมค์ได้ 19335 (ระดับ 92)

import lcd
import mic
import time
import ui

SENS = 3           # ความไวของไมค์ 1 ถึง 5 ยิ่งมากยิ่งไวต่อเสียงเบา
QUIET = 35         # ต่ำกว่านี้ถือว่าห้องเงียบ ใช้เปลี่ยนสีป้ายอย่างเดียว
PERIOD_MS = 60     # อ่านถี่แค่ไหน ถี่กว่านี้ตาคนก็ตามแถบไม่ทันอยู่ดี

# ทำไมแถบถึงขยับทันทีที่พูด: level() หยิบเฉพาะเสียงล่าสุด แล้วทิ้งที่ค้างในคิว
# ไมค์ผลิตเสียงตลอดเวลาไม่ว่าเราจะอ่านหรือไม่ ถ้าลูปนี้มัวแต่วาดกราฟจนอ่านไม่ทัน
# คิวจะเต็มที่ 625 ms แล้วสิ่งที่แสดงคือห้องเมื่อครึ่งวินาทีที่แล้ว ไม่ใช่ตอนนี้
# เรียก mic.lag() ดูได้ว่าคิวค้างอยู่กี่ ms - อ่านแบบทิ้งของเก่าได้ 0-48 ms
# ส่วนแบบไม่ทิ้งวัดได้ 496-624 ms (วัดจริงบนบอร์ด 14 ส.ค. 2026)

ui.screen()
ui.Label("เครื่องวัดระดับเสียง", x=12, y=8, value=24)
ch = ui.Chart(x=12, y=40, w=472, h=200, min=0, max=100)
ui.Label("ฟ้า = ความดัง 0-100", x=496, y=44, value=16, color=0x4A9EFF)

ui.Label("ความดังตอนนี้", x=496, y=76, value=16)
seg = ui.Seg7(x=496, y=100, w=180, h=44)
ui.Label("แถบ = ตัวเลขเดียวกัน", x=496, y=152, value=16)
bar = ui.Bar(x=496, y=176, w=180, h=16, min=0, max=100)
ui.Label("ดังที่สุดที่เจอ", x=496, y=204, value=16)
lbl_max = ui.Label("0", x=496, y=228, value=28, color=0xF5A623)

ui.Panel(x=12, y=256, w=472, h=76)
st = ui.Label("กำลังเปิดไมค์", x=24, y=268, value=28)
sub = ui.Label("ยังไม่ได้อ่านค่าแรก", x=24, y=304, value=20)
ui.poll()

lcd.clear()
lcd.console("<h2>เครื่องวัดระดับเสียง</h2>")
lcd.print("เปิดไมค์ที่ความไว", SENS, "จาก 5")

# start() ทิ้งสองชุดแรกให้เองแล้ว เพราะชุดแรกหลังเปิดยังไม่นิ่ง
mic.start(sens=SENS)
st.text("พูดใส่บอร์ดได้เลย")
st.color(0x9AA0A6)
lcd.print("ไมค์พร้อมแล้ว พูดหรือตบมือใส่บอร์ดดู")

loudest = 0
loud = False

for _ in range(900):
    # level() คือ rms() แปลงเป็นเปอร์เซ็นต์ของสเกลเต็ม 16 บิต
    lv = mic.level()

    if lv > loudest:
        loudest = lv
        lbl_max.text(str(lv))

    # กราฟกินทุกรอบ เพราะรูปร่างของเส้นคือสิ่งที่ตัวเลขตัวเดียวบอกไม่ได้
    ch.set_next(0, lv)
    seg.text(str(lv))
    bar.value(lv)
    sub.text("ระดับ %d จาก 100 | ดังสุด %d" % (lv, loudest))

    # รายงานเฉพาะตอนสถานะเปลี่ยน ไม่ใช่ทุกรอบ ไม่งั้นคอนโซลจะท่วม
    now_loud = lv >= QUIET
    if now_loud != loud:
        loud = now_loud
        if loud:
            st.text("มีเสียง")
            st.color(0x55DD55)
            lcd.print("<span class=ok>มีเสียง - ระดับ " + str(lv) + "</span>")
        else:
            st.text("ห้องเงียบ")
            st.color(0x9AA0A6)
            lcd.print("<span class=muted>กลับมาเงียบแล้ว</span>")

    ui.poll()
    time.sleep_ms(PERIOD_MS)

mic.stop()
st.text("ปิดไมค์แล้ว")
st.color(0x9AA0A6)
lcd.print("ระดับสูงสุดที่เจอ", loudest, "จาก 100")
lcd.print("<span class=muted>ลองตั้ง SENS = 5 แล้ววัดห้องเดิมซ้ำ</span>")
print("ตัวเลข 0-100 มาจาก rms ที่ยกกำลังสองก่อนเฉลี่ย ไม่ใช่ค่าเฉลี่ยดิบ")
