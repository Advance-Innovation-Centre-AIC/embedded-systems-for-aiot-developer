# 06_compass_readout.py - เข็มทิศที่ใช้งานได้จริง พร้อมตัวเลของศา
# ชุดตัวอย่างประจำคาบ 08
#
# ไฟล์นี้สอน: heading() ยุบสนามแม่เหล็กสามแกนเหลือทิศเดียวที่คนอ่านออก
# ดูที่จอ   : เข็มทิศทางซ้าย ตัวเลของศาตัวใหญ่ทางขวา และกราฟทิศตามเวลา 0-360 องศา
#             หมุนบอร์ดช้า ๆ เข็มหมุนตาม วางนิ่งแล้วกราฟต้องเป็นเส้นตรง
#             เส้นที่สั่นคือเข็มที่ยังคาลิเบรตไม่พอ
# กับดัก    : ui.Seg7 รับข้อความ ไม่ใช่ตัวเลข seg.value(180) จะเงียบและไม่ขึ้นอะไร
#             ต้องใช้ seg.text("180") เท่านั้น และต้องเรียก ui.poll() ทุกรอบ
#
# [หน่วยยังไม่ยืนยัน] สามตัวเลขที่ lbl_raw แสดงคือค่าดิบสามแกนจาก magnetic() ไม่มี
#   หน่วยกำกับโดยตั้งใจ ขนาดรวมของมันวัดจากบอร์ดได้ราว 1532 ขณะที่สนามแม่เหล็กโลก
#   อยู่ที่ 25-65 uT จึงยังบอกไม่ได้ว่าหน่วยคืออะไร แต่ทิศไม่ผิด เพราะ heading()
#   ใช้ atan2 ซึ่งสนใจแค่อัตราส่วนระหว่างสองแกน ตัวคูณที่ผิดเท่ากันจึงหักล้างกันหมด
#   วัดจริงบนบอร์ด 2026-08-14 ได้ 215.8 ซึ่งตรงกับทิศจริง
#
# หมายเหตุ : มีแต่ heading() ที่ป้อนข้อมูลให้ตัวคาลิเบรต hard-iron ส่วน magnetic()
#             ไม่ได้ป้อนอะไรให้เลย และ heading() คืนค่าเฉลี่ยของสิบครั้งหลังสุด
#             สิบรอบแรกหลังบูตจึงเป็นค่าที่ยังเฉลี่ยไม่เต็มถัง อย่าเพิ่งตัดสิน
#
# บน Eva Kit: sensors.init() และ sensors.scan() ปฏิเสธด้วย OSError ไม่ต้องเรียก
#   ส่วน sensors.bmm350.* ใช้ได้เลย - heading() วัดจริงบนบอร์ด 2026-08-14 ได้ 215.8
#   หลังรีเซ็ต การอ่านครั้งแรกช้าได้ถึงราว 16 วินาที และอาจโยน OSError ระหว่างนั้น

import lcd
import sensors
import time
import ui

NAMES = ("N", "NE", "E", "SE", "S", "SW", "W", "NW")
STEP_DEG = 1.0     # ค่าขยับน้อยกว่านี้ไม่อัปเดตหน้าจอ กันจอกระพริบ


def cardinal(deg):
    # หาร 45 องศาต่อช่อง บวก 22.5 เพื่อให้ขอบช่องอยู่กึ่งกลางระหว่างชื่อ
    return NAMES[int((deg + 22.5) % 360 / 45)]


ui.screen()
ui.Label("เข็มทิศ BMM350", x=12, y=8, value=24)
comp = ui.Compass(x=12, y=44, w=200, value=0)
ch = ui.Chart(x=232, y=44, w=252, h=200, min=0, max=360)
ui.Label("ฟ้า = ทิศตามเวลา 0-360 องศา", x=232, y=252, value=16, color=0x4A9EFF)

ui.Label("องศา", x=500, y=44, value=16)
seg = ui.Seg7(x=500, y=68, w=180, h=44)
lbl_dir = ui.Label("--", x=500, y=120, value=28)
lbl_raw = ui.Label("mx my mz", x=500, y=164, value=16)
ui.Label("หมุนบอร์ดช้า ๆ", x=500, y=192, value=16)

st = ui.Label("อัปเดตจอเฉพาะตอนขยับเกิน 1 องศา", x=24, y=296, value=20)
ui.poll()

lcd.clear()
lcd.console("<h2>เข็มทิศ BMM350</h2>")
lcd.print("เข็มทิศทำงาน หมุนบอร์ดช้า ๆ")

last_deg = -1.0
moved = 0

for _ in range(900):
    try:
        deg = sensors.bmm350.heading()
    except OSError:
        # หลังรีเซ็ต CM55 ยังไม่พร้อมตอบ รอรอบหน้า ไม่ใช่ปล่อยให้โปรแกรมตาย
        st.text("รอ CM55 พร้อม - นานได้ถึง 16 วินาที")
        ui.poll()
        time.sleep_ms(100)
        continue

    # กราฟกินทุกรอบ เพราะรูปร่างของ "เส้นตรง" กับ "เส้นสั่น" คือคำตอบของบทนี้
    ch.set_next(0, int(deg))

    # อัปเดตจอเฉพาะตอนค่าขยับเกินหนึ่งองศา ไม่งั้นจอกระพริบตลอด
    if abs(deg - last_deg) >= STEP_DEG:
        comp.value(int(deg))
        seg.text(str(int(deg)))
        lbl_dir.text(cardinal(deg))
        mx, my, mz = sensors.bmm350.magnetic()
        lbl_raw.text("%d %d %d" % (int(mx), int(my), int(mz)))
        last_deg = deg
        moved += 1
        st.text("อัปเดตไปแล้ว %d ครั้ง" % moved)

    ui.poll()
    time.sleep_ms(100)

lcd.print("อัปเดตจอทั้งหมด", moved, "ครั้ง")
lcd.print("<span class=muted>เส้นสั่นมาก = ต้องคาลิเบรตก่อน</span>")
print("ถ้าเข็มสั่นหรือนิ่งผิดปกติ ให้คาลิเบรต hard-iron ก่อน")
print("ไฟล์คาลิเบรตอยู่ที่ examples/usecase/14_hard_iron_calibration.py")
