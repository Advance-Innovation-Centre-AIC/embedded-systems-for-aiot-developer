# 12_table_and_list.py - หลายค่าพร้อมกัน ต้องเป็นตาราง ไม่ใช่ป้ายเรียงกัน
# ชุดตัวอย่างประจำคาบ 04
#
# ไฟล์นี้สอน: ui.Table จัดคอลัมน์ให้เอง · ui.List คือรายการที่มีไอคอนและเลื่อนได้
#             · ui.Line วาดเส้นจากจุดที่เราป้อน · ui.Picture วางไอคอนหนึ่งใบ
# ดูที่จอ   : ซ้ายคือตารางสามค่าที่อ่านจากบอร์ดจริงและอัปเดตวินาทีละครั้ง
#             ขวาคือรายการเซ็นเซอร์ที่แตะเลือกได้ ล่างคือเส้นแนวโน้มกับไอคอน
# กับดัก    : ป้ายหลายบรรทัดที่จัดเป็นตารางด้วยการนับพิกเซลเอง จะเลื่อนทันที
#             ที่ค่าเปลี่ยนความยาว - "27.4" กับ "8.0" กว้างไม่เท่ากัน ตารางจริง
#             จัดคอลัมน์ให้ ส่วน .add_row() เขียนลงแถวถัดจากแถวที่ตัวมันเองเขียน
#             ล่าสุด ไม่ใช่แถวที่ว่าง ถ้าจะแก้ค่าในแถวเดิมต้องใช้ .cell(แถว, คอลัมน์)
#
# บน Eva Kit: sensors.init() ถูกปฏิเสธด้วย OSError เพราะ CM55 เป็นเจ้าของ SCB0
#             ค่าที่อ่านได้จึงมาจาก snapshot ที่ CM55 ส่งข้ามมาให้ ไม่ใช่จากบัส

import lcd
import time
import ui
import sensors

# จานสีของหลักสูตร - หนึ่งบทบาทหนึ่งค่า และหนึ่งหน้าจอมีสีเน้นสีเดียว
COL_TEXT = 0xE8EAED
COL_DIM = 0x9AA3AF
COL_ACCENT = 0x4A9EFF

ROUNDS = 40
ROW_POT, ROW_TILT, ROW_TOUCH = 1, 2, 3

# CM55 เป็นเจ้าของบัสเซนเซอร์บน Eva Kit การสั่ง init() จากฝั่งเราจึงถูกปฏิเสธ
# ไว้ตรงนี้ ไม่ใช่ตอนอ่านค่า - จับไว้แล้วเดินต่อ เพราะ snapshot ยังอ่านได้ปกติ
try:
    sensors.init()
except OSError:
    pass

ui.screen()
time.sleep_ms(200)

ui.Label("สามค่าในตารางเดียว", x=24, y=16, color=COL_TEXT, value=28)

# --- ตาราง: ค่ากับหน่วยอยู่คนละคอลัมน์ คอลัมน์จึงไม่เลื่อนตามความยาวค่า -----
ui.Label("ค่าที่อ่านได้ตอนนี้", x=24, y=64, color=COL_DIM, value=20)
tb = ui.Table(x=24, y=96, w=352, h=152, cols=2, rows=4)
tb.add_row("สิ่งที่วัด", "ค่า")
tb.add_row("ตัวหมุน", "รอ")
tb.add_row("เอียงแกน X", "รอ")
tb.add_row("แผ่นสัมผัส", "รอ")

# --- รายการ: ไอคอนช่วยให้กวาดตาเจอบรรทัดที่ต้องการโดยไม่ต้องอ่านทุกคำ ------
ui.Label("เลือกดูเซ็นเซอร์", x=416, y=64, color=COL_DIM, value=20)
li = ui.List("เซ็นเซอร์บนบอร์ด", x=416, y=96, w=352, h=152)
li.add_item("ตัวหมุน", ui.ICON_SETTINGS)
li.add_item("แผ่นสัมผัส", ui.ICON_EDIT)
li.add_item("ตัววัดความเร่ง", ui.ICON_REFRESH)

# --- เส้นแนวโน้ม กับไอคอนหนึ่งใบ ------------------------------------------
ui.Label("รูปร่างของค่าที่ผ่านมา", x=24, y=272, color=COL_DIM, value=20)
ui.Picture("star", x=24, y=304, w=48, h=48, color=COL_ACCENT)
ln = ui.Line(x=96, y=304, color=COL_ACCENT)
for pt in [(0, 48), (80, 16), (160, 40), (240, 8), (320, 32), (400, 24)]:
    ln.add_point(pt[0], pt[1])

ui.poll()

lcd.clear()
lcd.console("<h2>Table + List + Line + Picture</h2>")
print("Table + List + Line + Picture พร้อมแสดงผล")

# หนึ่งวินาทีต่อรอบ - ค่าที่คนต้องอ่าน ห้ามกระพริบเร็วกว่านี้ (S7.7.4)
for i in range(ROUNDS):
    pot = sensors.pot.percent()
    ax, ay, az = sensors.bmi270.acceleration()
    slider = sensors.capsense.slider()

    # .cell() เขียนทับช่องเดิม ตำแหน่งของตัวเลขจึงอยู่นิ่ง ไม่ไหลลงมาเรื่อย ๆ
    tb.cell(ROW_POT, 1, "%d %%" % int(pot))
    tb.cell(ROW_TILT, 1, "%.1f m/s2" % ax)
    tb.cell(ROW_TOUCH, 1, "%d" % int(slider))

    if i % 10 == 0:
        lcd.print("ตัวหมุน", int(pot), "%")
    ui.poll()
    time.sleep_ms(1000)

lcd.print("<span class=ok>จบรอบ - ตารางอยู่นิ่งทั้งรอบ</span>")

# ตาคุณ
# 1) เปลี่ยน .cell(ROW_POT, 1, ...) เป็น .add_row(...) แล้วดูว่าเกิดอะไรขึ้น
#    ตารางจะยาวลงไปเรื่อย ๆ จนเลยกรอบ เพราะ add_row เขียนแถวใหม่ทุกครั้ง
# 2) ลองสลับคอลัมน์ให้ค่ากับหน่วยอยู่ช่องเดียวกัน เช่น "27.4 องศา" แล้วดูว่า
#    ตอนค่าเป็นเลขหลักเดียว คอลัมน์ขยับหรือไม่ - นี่คือเหตุผลที่ต้องแยกคอลัมน์
# 3) เพิ่มบรรทัดที่สี่ใน ui.List แล้วดูว่ามันเลื่อนได้เอง โดยไม่ต้องเขียนโค้ดเลื่อน
