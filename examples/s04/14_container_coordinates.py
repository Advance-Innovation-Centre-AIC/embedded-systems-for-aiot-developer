# 14_container_coordinates.py - กล่องที่คอนเทนเนอร์คืนมา และระบบพิกัดของมัน
# ชุดตัวอย่างประจำคาบ 04
#
# Why : ตั้งแต่ 10_tabview_second_screen.py กับ 11_menu_settings_tree.py เราส่ง
#       "ของที่คืนมา" ไปใส่ parent= โดยไม่เคยถามว่ามันคืออะไร พอเริ่มวางของ
#       ในนั้นเองแล้วของหายออกนอกกรอบ ทุกทีมเดาเหมือนกันว่า widget พัง ทั้งที่
#       มันวางตรงตามพิกัดที่สั่งทุกพิกเซล เพียงแต่สั่งในระบบพิกัดคนละอันกับที่คิด
# What: ของที่คืนมาคือ "กล่อง" - ชนิดที่ 32 ในตารางของเฟิร์มแวร์ ซึ่ง
#       ipc_ui_protocol.h กำกับไว้ว่า Never created directly by CREATE แปลว่า
#       ไม่มี ui.Container() ให้เรียก มันเกิดทางเดียวคือถูกคืนมาจาก .add_tab()
#       .add_tile() .content() .add_page() .section() และ .row()
# How : ส่งกล่องไปเป็น parent= ตอนสร้างลูก แล้ว x= y= ของลูกจะนับจากมุมซ้ายบน
#       ของกล่องใบนั้น ไม่ใช่ของจอ
#
# ดูที่จอ: ป้ายสามใบเขียนข้อความเดียวกันว่า x=24 y=56 แต่ไปโผล่คนละที่ - ใบซ้ายบน
#          นับจากมุมจอ ใบกลางนับจากมุมการ์ด ใบขวานับจากมุมหน้าของแท็บ
# กับดัก : กล่องกินโควตาแฮนเดิลใบละหนึ่งใบเท่ากับ widget ปกติ แท็บสามใบจึงเป็น
#          4 แฮนเดิลตั้งแต่ยังไม่มีของอยู่ในนั้น และกล่องเป็นแค่ "ที่" ไม่ใช่
#          "ของที่ตอบได้" - ui_widget_mgr.c ไม่มี case ของชนิดกล่องทั้งใน
#          set_text และ set_value ส่วน get_value ตกไปที่ default ซึ่งคืน 0
#          สั่งเปลี่ยนข้อความหรือค่าของกล่อง จึงเงียบสนิททั้งสองทาง ไม่มี error
#          อีกข้อที่ผิดคาด: parent= ไม่ได้รับเฉพาะกล่อง มันรับ widget อะไรก็ได้
#          เพราะ CM55 แปลงแฮนเดิลเป็น object แล้วส่งให้ LVGL ตรง ๆ - ป้ายที่มี
#          parent=Panel จึงย้ายไปอยู่ในระบบพิกัดของการ์ดใบนั้นทันที และด่าน
#          check_overlap.py มองไม่เห็นมันเลย เพราะมันข้ามทุกตัวที่มี parent=

import lcd
import time
import ui

COL_TEXT = 0xE8EAED
COL_DIM = 0x9AA3AF
COL_CARD = 0x171B22
COL_ACCENT = 0x4A9EFF

ROUNDS = 60

# ข้อความเดียวกันเป๊ะทั้งสามใบ ความต่างที่เห็นบนจอจึงมาจากระบบพิกัดล้วน ๆ
SAME = "x=24 y=56"

ui.screen()
time.sleep_ms(200)

ui.Label("กล่องที่คอนเทนเนอร์คืนมา", x=24, y=8, color=COL_TEXT, value=28)

# ใบที่ 1 - ไม่มี parent= คือลูกของจอ พิกัดนับจากมุมซ้ายบนของพื้นที่วาด
ui.Label(SAME, x=24, y=56, color=COL_DIM, value=24)

# ใบที่ 2 - พ่อเป็น Panel ธรรมดา ไม่ใช่กล่องที่คอนเทนเนอร์คืนมา แต่ใช้ได้
card = ui.Panel(x=24, y=96, w=352, h=224, color=COL_CARD, max=8)
ui.Label("ป้ายใบนี้อยู่ในการ์ด", x=24, y=16, color=COL_DIM, value=20,
         parent=card)
ui.Label(SAME, x=24, y=56, color=COL_ACCENT, value=24, parent=card)

# ใบที่ 3 - พ่อเป็นหน้าของแท็บ ซึ่งคือกล่องของจริง เกิดจาก .add_tab()
tabs = ui.Tabview(x=400, y=96, w=368, h=224, color=COL_CARD, value=88)
page = tabs.add_tab("หน้าในแท็บ")
ui.Label("ป้ายใบนี้อยู่ในหน้าแท็บ", x=24, y=16, color=COL_DIM, value=20,
         parent=page)
ui.Label(SAME, x=24, y=56, color=COL_ACCENT, value=24, parent=page)

# กล่องเป็น "ที่" ไม่ใช่ "ของที่ตอบได้" - สั่งสองอย่างนี้แล้วจอไม่ขยับสักพิกเซล
page.text("ชื่อใหม่ที่ไม่มีวันขึ้นจอ")
page.value(1)
answer = page.value()

# แฮนเดิลของกล่องมาจากโควตาก้อนเดียวกับ widget ทั่วไป เอาเลขจริงมาดูกันเลย
budget = "แท็บ id " + str(tabs.id()) + " + หน้าของมัน id " + str(page.id())
ui.Label(budget, x=400, y=336, color=COL_DIM, value=20)

first = "ถามค่าจากกล่อง ได้ " + str(answer)
line = ui.Label(first, x=24, y=336, color=COL_DIM, value=20)

lcd.clear()
lcd.console("<h2>กล่อง - ที่อยู่ ไม่ใช่ของที่ตอบได้</h2>")
lcd.print("ป้ายสามใบ ข้อความเดียวกัน พิกัดเดียวกัน แต่คนละที่")
lcd.print("Tabview id", tabs.id(), "+ หน้าของมัน id", page.id(), "= 2 แฮนเดิล")
lcd.print("ถามค่าจากกล่องได้", answer, "- ทุกครั้ง ทุกกล่อง")

events = 0
for _ in range(ROUNDS):
    # กล่องไม่ได้ลงทะเบียน callback ไว้เลย register_object() ผูกไว้แค่
    # LV_EVENT_DELETE เพื่อคืนแฮนเดิล ตัวเลขข้างล่างจึงเป็นศูนย์เสมอ
    for ev in ui.poll():
        events += 1
    time.sleep_ms(200)

line.text("กล่องไม่ส่ง event - นับได้ " + str(events) + " ครั้ง")
lcd.print("<span class=ok>event จากกล่อง =", events, "</span>")
print("Container: parent= เปลี่ยนระบบพิกัดของลูก และกล่องกินแฮนเดิลใบละหนึ่ง")

# ตาคุณ
# 1) เปลี่ยน y=56 ของป้ายใบที่สามเป็น y=200 แล้วรันใหม่ - มันจะหายไป เพราะ
#    เนื้อที่ของหน้าแท็บสูงแค่ 224 ลบแถบแท็บ 88 เหลือ 136 พิกเซล ลูกที่เลย
#    ขอบล่างของกล่องถูกตัด ไม่ใช่ล้นลงมาบนจอ
# 2) ลบ parent=card ของป้ายใบที่สองออกหนึ่งคำ แล้วดูว่ามันเด้งไปไหน
#    นี่คือหน้าตาของบั๊ก "widget หาย" ที่เจอบ่อยที่สุดตอนเริ่มใช้คอนเทนเนอร์
# 3) พิมพ์ page.id() กับ card.id() เทียบกัน แล้วนับว่าหน้าจอนี้ใช้ไปกี่แฮนเดิล
