# 10_tabview_second_screen.py - จอที่สองที่ไม่ต้องเขียนโปรแกรมที่สอง
# ชุดตัวอย่างประจำคาบ 04
#
# Why : 06_layout_budget.py บอกว่าเรามีโควตา widget จำกัด แต่ปัญหาที่มาถึงก่อน
#       โควตาเสมอคือ "ที่ว่างบนจอหมดก่อน" หนึ่งหน้าจอรับการ์ดได้สี่ใบก่อนที่คน
#       จะเริ่มอ่านไม่ทัน ทีมที่มีของต้องโชว์หกอย่างจึงยัดจนตัวหนังสือชนกัน
#       แล้วโทษว่าจอเล็ก ทั้งที่ปัญหาคือหน้าจอเดียวไม่พอ ไม่ใช่จอเล็กไป
# What: ui.Tabview คือคอนเทนเนอร์ที่แบ่งพื้นที่เดิมออกเป็นหลายหน้า สลับด้วยการแตะ
#       แถบบนสุด ของที่อยู่คนละแท็บไม่แย่งที่กัน เพราะไม่เคยอยู่บนจอพร้อมกัน
# How : .add_tab("ชื่อ") คืน "หน้า" กลับมาหนึ่งใบ เอาหน้านั้นไปใส่ parent= ของ
#       widget ที่ต้องการให้อยู่ในแท็บนั้น พิกัดของลูกนับจากมุมซ้ายบนของหน้า
#       ไม่ใช่ของจอ
#
# ดูที่จอ: แถบสามแท็บอยู่บนสุด ใต้ลงมาคือของประจำแท็บที่เลือกอยู่
#          แตะสลับแท็บแล้วบรรทัดล่างจะบอกว่าตอนนี้อยู่แท็บที่เท่าไร
# กับดัก : value= ของ Tabview ไม่ใช่ "ค่าเริ่มต้น" แต่คือ "ความสูงของแถบแท็บ"
#          ตั้ง value=88 แปลว่าแถบสูง 88 พิกเซล ไม่ได้แปลว่าเปิดแท็บที่ 88
#          ถ้าอยากเลือกแท็บเริ่มต้น ต้องใช้ .value(n) หรือ .prop(ui.PROP_ACTIVE_TAB, n)
#          และแท็บสามใบกินโควตาไปสี่แฮนเดิลตั้งแต่ยังไม่มีอะไรอยู่ในนั้นเลย
#          คือ Tabview เองหนึ่ง บวกหน้าที่ add_tab() คืนมาอีกใบละหนึ่ง

import lcd
import time
import ui

# จานสีของหลักสูตร - หนึ่งบทบาทหนึ่งค่า และหนึ่งหน้าจอมีสีเน้นสีเดียว
COL_TEXT = 0xE8EAED
COL_DIM = 0x9AA3AF
COL_CARD = 0x171B22
COL_ACCENT = 0x4A9EFF
COL_WARN = 0xF5A623
COL_OK = 0x30A46C

TAB_BAR_H = 88          # แถบแท็บคือของที่ต้องแตะ จึงสูงไม่ต่ำกว่า 88 พิกเซล
ROUNDS = 240            # ราวสี่สิบวินาทีที่ 160 ms ต่อรอบ

ui.screen()
time.sleep_ms(200)

ui.Label("หกอย่างไม่ลงจอเดียว ลงสามแท็บได้", x=24, y=16, color=COL_TEXT,
         value=28)

# Tabview กินพื้นที่เท่าที่เราให้ ไม่ได้ขยายเต็มจอเอง - จบที่ y=336 เพราะมุมขวาล่าง
# ของจอเป็นที่ของปุ่ม Console ที่เฟิร์มแวร์จองไว้ ห้ามวางของทับ
tv = ui.Tabview(x=24, y=64, w=744, h=272, color=COL_CARD, value=TAB_BAR_H)

# add_tab() คืน "หน้า" กลับมา ไม่ใช่คืนตัวเลข - เก็บไว้ในตัวแปรแล้วส่งต่อให้ parent=
tab_now = tv.add_tab("ตอนนี้")
tab_day = tv.add_tab("ทั้งวัน")
tab_set = tv.add_tab("เกณฑ์")

# ---- แท็บ 1: ค่าปัจจุบัน -------------------------------------------------
# พิกัดข้างล่างนี้นับจากมุมซ้ายบนของ "หน้า" ไม่ใช่ของจอ ตัวเลข 16 จึงหมายถึง
# ห่างจากขอบหน้า 16 พิกเซล ไม่ได้แปลว่าอยู่ที่ x=16 ของจอ
ui.Label("อุณหภูมิห้องเครื่อง", x=16, y=16, color=COL_DIM, value=20,
         parent=tab_now)
seg_now = ui.Seg7(text="0.0", x=16, y=48, w=224, h=88, color=COL_ACCENT,
                  parent=tab_now)
ui.Label("องศาเซลเซียส", x=256, y=80, color=COL_DIM, value=20, parent=tab_now)

# ---- แท็บ 2: ย้อนหลัง ---------------------------------------------------
ui.Label("สูงสุดที่เจอในรอบนี้", x=16, y=16, color=COL_DIM, value=20,
         parent=tab_day)
seg_max = ui.Seg7(text="0.0", x=16, y=48, w=224, h=88, color=COL_TEXT,
                  parent=tab_day)
bar_day = ui.Bar(x=256, y=72, w=400, h=40, color=COL_ACCENT, min=0, max=100,
                 value=0, parent=tab_day)

# ---- แท็บ 3: เกณฑ์ ------------------------------------------------------
ui.Label("แจ้งเตือนเมื่อเกินกี่องศา", x=16, y=16, color=COL_DIM, value=20,
         parent=tab_set)
sp = ui.Spinbox(x=16, y=48, w=224, h=88, color=COL_TEXT, min=0, max=100,
                value=60, parent=tab_set)
ui.Label("แตะลูกศรขึ้นลงเพื่อปรับ", x=256, y=80, color=COL_DIM, value=20,
         parent=tab_set)

# บรรทัดสถานะอยู่นอก Tabview จึงเห็นได้ทุกแท็บ - ของที่ต้องเห็นตลอดเวลา
# ห้ามเอาไปซ่อนไว้ในแท็บใดแท็บหนึ่ง
line = ui.Label("แตะแถบข้างบนเพื่อสลับแท็บ", x=24, y=344, color=COL_DIM,
                value=20)

lcd.clear()
lcd.console("<h2>Tabview - จอที่สองในโปรแกรมเดียว</h2>")
lcd.print("Tabview 1 + หน้าอีก 3 = 4 แฮนเดิล ก่อนมีเนื้อหา")

TAB_NAME = ("ตอนนี้", "ทั้งวัน", "เกณฑ์")

peak = 0.0
active = 0

for i in range(ROUNDS):
    # ค่าจำลองในไฟล์นี้เราสร้างเอง เพราะคาบ 4 ยังไม่ได้เปิดโมดูลเซนเซอร์
    # รูปคลื่นสามเหลี่ยมช้า ๆ ให้เห็นตัวเลขขยับโดยไม่ต้องมีของจริงมาต่อ
    phase = i % 120
    temp = 20.0 + (phase if phase < 60 else 120 - phase) * 0.75

    if temp > peak:
        peak = temp

    # ค่าที่ต้องอ่านอัปเดตไม่เร็วกว่าวินาทีละครั้ง - ตัวเลขที่กระพริบเร็วกว่านั้น
    # อ่านไม่ทันและทำให้คนไม่เชื่อจอ
    if i % 8 == 0:
        seg_now.text("%.1f" % temp)
        seg_max.text("%.1f" % peak)
        bar_day.value(int(peak))
        seg_now.color(COL_WARN if temp >= 60 else COL_ACCENT)

    for ev in ui.poll():
        # Tabview ส่ง value_changed พร้อมลำดับของแท็บที่กำลังเปิด เริ่มที่ 0
        # ส่วน Spinbox ในแท็บ 3 ส่ง value_changed ของตัวเองมาด้วยแฮนเดิลคนละตัว
        if ev["handle"] == tv.id() and ev["type"] == "value_changed":
            active = ev["value"]
            name = TAB_NAME[active] if 0 <= active < len(TAB_NAME) else "?"
            line.text("อยู่แท็บที่ " + str(active) + " ชื่อ " + name)
            line.color(COL_ACCENT)
            lcd.print("สลับไปแท็บ", active, name)
        elif ev["handle"] == sp.id() and ev["type"] == "value_changed":
            line.text("เกณฑ์แจ้งเตือนใหม่คือ " + str(ev["value"]) + " องศา")
            line.color(COL_OK)
            lcd.print("เกณฑ์ใหม่", ev["value"])

    time.sleep_ms(160)

line.text("จบรอบ - ของสามชุดอยู่ครบ โดยไม่มีใครทับใคร")
line.color(COL_DIM)
lcd.print("<span class=ok>สามแท็บ = สามหน้าจอ ในโปรแกรมเดียว</span>")

# ตาคุณ
# 1) ลบ parent=tab_day ของ bar_day ออกหนึ่งบรรทัด แล้วรันใหม่ - แถบจะไปโผล่
#    ที่มุมซ้ายบนของจอทับหัวเรื่อง เพราะไม่มี parent แปลว่า "อยู่บนจอ"
#    ไม่ใช่ "อยู่ในแท็บ" และพิกัด 256,72 ที่เคยนับจากหน้า กลายเป็นนับจากจอ
# 2) เพิ่ม tv.value(2) ไว้ก่อนเข้าลูป แล้วดูว่าเปิดมาที่แท็บไหน
#    เทียบกับการเปลี่ยน value=88 ตอนสร้างเป็น value=2 ซึ่งจะได้แถบแท็บสูง 2 px
#    จนแตะไม่ได้ - สองที่นี้ชื่อเหมือนกันแต่คนละความหมาย
# 3) นับดูว่าหน้าจอนี้ใช้ไปกี่แฮนเดิลจากเพดาน 64 แล้วลองเพิ่มแท็บที่สี่
#    ราคาของแท็บหนึ่งใบคือหนึ่งแฮนเดิล ก่อนที่จะใส่อะไรลงไปข้างใน
