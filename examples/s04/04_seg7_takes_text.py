# 04_seg7_takes_text.py - Seg7 รับได้ทั้งสองทาง แต่ให้ผลไม่เท่ากัน
#
# Why : .value(n) กับ .text(s) ไม่ใช่ทางเลือกที่เท่ากัน .value() ส่งได้แต่จำนวนเต็ม
#       จอจึงแสดงได้แค่จำนวนเต็ม ถ้าอยากได้ทศนิยม ต้องเป็นคนตัดสินใจเองว่ากี่ตำแหน่ง
#       แล้วส่งเป็นข้อความ ตัวเลขดิบไม่ได้พกข้อมูลนั้นมาด้วย
# What: Slider Arc Bar รับ .value(n) แล้วจบ เพราะมันแสดงเป็นตำแหน่ง ไม่ใช่ตัวเลข
#       ส่วน Seg7 แสดง "ตัวหนังสือ" จึงต้องรู้รูปแบบ 50 กับ 50.0 กับ 050
#       เป็นคนละภาพบนจอ ทั้งที่เป็นค่าเดียวกัน
#
# ดูที่จอ: Seg7 ไต่ขึ้นทีละ 0.5 แล้วเปลี่ยนเป็นสีแดงเมื่อเกิน 60
#         Bar ขยับตามค่าเดียวกัน และกราฟข้างล่างวาดเส้นไต่ขึ้นของค่าเดิมนั้น
# กับดัก : seg.value(88) ขึ้น 88 ไม่ใช่ 88.0 ถ้าโปรแกรมอื่นในหน้าเดียวกันแสดง 88.0
#         อยู่ ผู้ใช้จะเห็นสองเลขที่ดูไม่เหมือนกันทั้งที่เป็นค่าเดียวกัน
#
# หมายเหตุประวัติ: ก่อน 2026-09-05 .value() บน Seg7 "ไม่ทำอะไรเลย" ไม่มี exception
#         ไม่มี error จอค้างอยู่ที่ค่าเดิมตลอดกาล ตัวอย่างที่แล้วมา 15 ไฟล์ในคลัง
#         จึงค้างอยู่แบบนั้นโดยไม่มีใครรู้ ตอนนี้แก้แล้ว แต่จำรูปแบบของบั๊กไว้
#         เพราะบั๊กที่เงียบสนิทกินเวลามากกว่าบั๊กที่พังดัง ๆ เสมอ

import ui
import lcd
import time

# จานสีของหลักสูตร - บทบาทละหนึ่งค่า ตาม SPEC S7.13
COL_TEXT = 0xE8EAED      # ข้อความหลัก และค่าที่ยังไม่เกินเกณฑ์
COL_DIM = 0x9AA3AF       # ข้อความรอง หน่วย เชิงอรรถ
COL_CARD = 0x171B22      # พื้นการ์ด พื้นกราฟ
COL_ACCENT = 0x4A9EFF    # เส้นกราฟค่าเดียว
COL_BAD = 0xE5484D       # เกินเกณฑ์ - ใช้กับเรื่องนี้เรื่องเดียวทั้งจอ

WARN_AT = 60            # เส้นเกณฑ์ที่ทำให้สีเปลี่ยน หน่วยเดียวกับค่าที่ไต่
STEP_MS = 40            # หน่วงต่อก้าว ต้องมี ไม่งั้นเฟรมหายเงียบ ๆ

ui.screen()
time.sleep_ms(200)

ui.Label("Seg7 - text() คุมรูปแบบ value() ได้จำนวนเต็ม", x=24, y=8, color=COL_TEXT, value=24)

ui.Panel(x=24, y=56, w=744, h=136, color=COL_CARD, min=COL_CARD, max=12,
         value=1)

# Seg7 ตั้งต้นด้วยข้อความ "0.0" ไปเลย จะได้เห็นรูปแบบที่ตั้งใจตั้งแต่แรก
# ถ้าไม่ใส่ text= มันจะขึ้น "0000" ซึ่งเป็นค่าตั้งต้นของ widget ชนิดนี้
ui.Label("Seg7 - ใช้ text()", x=40, y=72, color=COL_DIM, value=16)
seg = ui.Seg7(text="0.0", x=40, y=104, w=240, h=72, color=COL_TEXT)

# Bar รับค่าด้วย .value() ตามที่ชื่อบอก min กับ max กำหนดช่วงของมัน
# วางให้กึ่งกลางแนวตั้งตรงกับ Seg7 ตาจึงอ่านว่าทั้งสองพูดถึงค่าเดียวกัน
ui.Label("Bar - ใช้ value()", x=336, y=72, color=COL_DIM, value=16)
bar = ui.Bar(x=336, y=120, w=400, h=40, color=COL_ACCENT, min=0, max=100,
             value=0)

# Label ที่สร้างด้วยข้อความว่าง LVGL จะเติมคำว่า "Label" ให้เอง
# แล้วคำนั้นค้างบนจอจนกว่าจะมีการเขียนทับครั้งแรก จึงต้องตั้งข้อความตั้งต้นเสมอ
# บรรทัดนี้เป็นหลักฐานของบทเรียน ไม่ใช่คำเตือนของอุปกรณ์ จึงใช้สีข้อความหลัก
# ไม่ใช่สีส้ม - สีส้มบนจอนี้ต้องว่างไว้ ไม่งั้นจะแย่งความหมายกับเกณฑ์ 60
proof = ui.Label("ยังไม่ได้พิสูจน์อะไร", x=24, y=208, color=COL_TEXT, value=16)

# กราฟคือมุมมองที่สาม ค่าเดียวกันแต่เห็น "แนวโน้ม" ที่ตัวเลขตัวเดียวไม่บอก
# สีของ Chart คือสีของ series ที่ 0 ซึ่งเราไม่ได้ใช้ จึงเพิ่ม series ของเราเอง
# เส้นค่าเดียวใช้สีเน้นเสมอ ไม่ใช่เขียว - เขียวแปลว่า "ปกติ" อย่างเดียว
chart = ui.Chart(x=24, y=240, w=744, h=96, color=COL_CARD, min=0, max=100)
s_ramp = chart.add_series(COL_ACCENT)

status = ui.Label("กำลังไต่ค่า 0 ถึง 100", x=24, y=352, color=COL_DIM, value=20)

lcd.print("Seg7 ใช้ text() - Bar ใช้ value() - Chart ใช้ set_next()")

# หลักฐานชิ้นแรก ยิง value() ใส่ Seg7 ตรง ๆ แล้วดูว่าได้อะไรกลับมา
# จอขึ้น 88 ไม่ใช่ 88.0 เพราะจำนวนเต็มไม่ได้บอกว่าอยากได้ทศนิยมกี่ตำแหน่ง
seg.value(88)
ui.poll()
time.sleep_ms(800)
proof.text("seg.value(88) ขึ้น 88 - ไม่ใช่ 88.0")
lcd.print("value() ส่งได้แต่จำนวนเต็ม - ทศนิยมต้องใช้ text()")

# ไต่ค่าด้วยจำนวนเต็มหน่วย "หนึ่งในสิบ" เลี่ยงเศษทศนิยมของ float สะสม
v10 = 0
while v10 <= 1000:
    # แปลงเป็นข้อความก่อนส่ง คุมทศนิยมเองด้วย เพราะเราคือคนที่รู้ว่าอยากได้กี่ตำแหน่ง
    whole = v10 // 10
    tenth = v10 % 10
    seg.text(str(whole) + "." + str(tenth))

    # Bar รับตัวเลขตรง ๆ ช่วงของมันเป็น 0-100 จึงส่งเฉพาะส่วนจำนวนเต็ม
    bar.value(whole)

    # Chart เก็บได้ 50 จุดต่อ series จึงป้อนทุก 2.0 หน่วย ได้ 51 จุดพอดีกับหน้าต่าง
    if v10 % 20 == 0:
        chart.set_next(s_ramp, whole)

    # เปลี่ยนสีตามค่า สีเป็นช่องทางที่ตาอ่านได้ก่อนตัวเลขเสมอ
    if whole >= WARN_AT:
        seg.color(COL_BAD)
    else:
        seg.color(COL_TEXT)

    v10 = v10 + 5

    # ต้อง poll ทุกรอบ แม้ในลูปที่ไม่มีปุ่มให้กด ไม่งั้นจอจะไม่ยอมโชว์
    ui.poll()
    time.sleep_ms(STEP_MS)

seg.text("DONE")     # ฟอนต์เจ็ดส่วนมี A-Z และ a-z จึงขึ้นเป็นคำได้
seg.color(COL_TEXT)
status.text("จบแล้ว - Seg7 ขึ้น DONE ได้ เพราะมันรับข้อความ")
proof.text("จำไว้: อยากคุมรูปแบบ ต้องใช้ text()")
ui.poll()

lcd.print("สรุป: value() ได้จำนวนเต็ม - text() ได้ทุกอย่างที่ฟอนต์มี")
