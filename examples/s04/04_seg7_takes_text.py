# 04_seg7_takes_text.py - Seg7 กินข้อความ ไม่ใช่กินตัวเลข
#
# Why : เขียน seg.value(50) แล้วจอค้างที่ 0.0 ไม่มี exception ไม่มีคำเตือน
#       นักศึกษาจะไปไล่หาที่ IPC ที่สายจอ ที่ค่าเซนเซอร์ ทุกที่ยกเว้นบรรทัดที่ผิด
#       บั๊กที่เงียบสนิทกินเวลามากกว่าบั๊กที่พังดัง ๆ เสมอ
# What: widget ตระกูล Slider Arc Bar รับค่าด้วย .value(n) ตามที่ชื่อบอก
#       แต่ Seg7 ไม่รับ ต้องส่งเป็นข้อความด้วย .text("50.0") เท่านั้น
#       เพราะจอเจ็ดส่วนต้องรู้ว่าจะแสดงกี่ตำแหน่งทศนิยม ซึ่งตัวเลขดิบไม่ได้บอก
#
# ดูที่จอ: Seg7 ไต่ขึ้นทีละ 0.5 แล้วเปลี่ยนเป็นสีแดงเมื่อเกิน 60
#         Bar ขยับตามค่าเดียวกัน และกราฟข้างล่างวาดเส้นไต่ขึ้นของค่าเดิมนั้น
# กับดัก : seg.value(50) ไม่ทำอะไรเลย และไม่มี error ให้จับ จอจะยังค้างที่ค่าเดิม
#         อยู่อย่างนั้น เป็นบั๊กที่หาเจอยากมากถ้าไม่รู้มาก่อน

import ui
import lcd
import time

COL_TEXT = 0xFFFFFF
COL_DIM = 0xA0B4CC
COL_CARD = 0x142240
COL_OK = 0x00E676
COL_WARN = 0xFFA726
COL_BAD = 0xFF5252

WARN_AT = 60            # เส้นเกณฑ์ที่ทำให้สีเปลี่ยน หน่วยเดียวกับค่าที่ไต่
STEP_MS = 40            # หน่วงต่อก้าว ต้องมี ไม่งั้นเฟรมหายเงียบ ๆ

ui.screen()
time.sleep_ms(200)

ui.Label("Seg7 รับข้อความเท่านั้น", x=20, y=12, color=COL_TEXT, value=24)

ui.Panel(x=20, y=50, w=650, h=120, color=COL_CARD, min=COL_DIM, max=12, value=1)

# Seg7 ตั้งต้นด้วยข้อความ "0.0" ไปเลย จะได้เห็นรูปแบบที่ตั้งใจตั้งแต่แรก
# ถ้าไม่ใส่ text= มันจะขึ้น "0000" ซึ่งเป็นค่าตั้งต้นของ widget ชนิดนี้
ui.Label("Seg7 - ใช้ text()", x=40, y=60, color=COL_DIM, value=16)
seg = ui.Seg7(text="0.0", x=40, y=88, w=240, h=48, color=COL_OK)

# Bar รับค่าด้วย .value() ตามที่ชื่อบอก min กับ max กำหนดช่วงของมัน
ui.Label("Bar - ใช้ value()", x=330, y=60, color=COL_DIM, value=16)
bar = ui.Bar(x=330, y=90, w=320, h=26, min=0, max=100, value=0)

# Label ที่สร้างด้วยข้อความว่าง LVGL จะเติมคำว่า "Label" ให้เอง
# แล้วคำนั้นค้างบนจอจนกว่าจะมีการเขียนทับครั้งแรก จึงต้องตั้งข้อความตั้งต้นเสมอ
proof = ui.Label("ยังไม่ได้พิสูจน์อะไร", x=40, y=134, color=COL_WARN, value=14)

# กราฟคือมุมมองที่สาม ค่าเดียวกันแต่เห็น "แนวโน้ม" ที่ตัวเลขตัวเดียวไม่บอก
# สีของ Chart คือสีของ series ที่ 0 ซึ่งเราไม่ได้ใช้ จึงเพิ่ม series ของเราเอง
chart = ui.Chart(x=20, y=184, w=650, h=140, color=COL_CARD, min=0, max=100)
s_ramp = chart.add_series(COL_OK)

status = ui.Label("กำลังไต่ค่า 0 ถึง 100", x=20, y=334, color=COL_DIM, value=18)

lcd.print("Seg7 ใช้ text() - Bar ใช้ value() - Chart ใช้ set_next()")

# หลักฐานชิ้นแรก ยิง value() ใส่ Seg7 ตรง ๆ หนึ่งครั้งแล้วดูว่าเกิดอะไรขึ้น
# ไม่มี exception ไม่มี return code จอก็ไม่ขยับ นี่คือหน้าตาของบั๊กเงียบ
seg.value(88)
ui.poll()
time.sleep_ms(800)
proof.text("ยิง seg.value(88) ไปแล้ว จอยังเป็น 0.0")
lcd.print("seg.value(88) ไม่มีผล ไม่มี error - จอยังเป็น 0.0")

# ไต่ค่าด้วยจำนวนเต็มหน่วย "หนึ่งในสิบ" เลี่ยงเศษทศนิยมของ float สะสม
v10 = 0
while v10 <= 1000:
    # แปลงเป็นข้อความก่อนส่ง คุมทศนิยมเองด้วย เพราะเราคือคนที่รู้ว่าอยากได้กี่ตำแหน่ง
    whole = v10 // 10
    tenth = v10 % 10
    seg.text(str(whole) + "." + str(tenth))

    # Bar รับตัวเลขตรง ๆ ช่วงของมันเป็น 0-100 จึงส่งเฉพาะส่วนจำนวนเต็ม
    bar.value(whole)

    # Chart เก็บได้ 50 จุดต่อ series จึงป้อนทุก 2.0 หน่วย ได้ 51 จุดพอดีกับหน้าต่าง
    if v10 % 20 == 0:
        chart.set_next(s_ramp, whole)

    # เปลี่ยนสีตามค่า สีเป็นช่องทางที่ตาอ่านได้ก่อนตัวเลขเสมอ
    if whole >= WARN_AT:
        seg.color(COL_BAD)
    else:
        seg.color(COL_OK)

    v10 = v10 + 5

    # ต้อง poll ทุกรอบ แม้ในลูปที่ไม่มีปุ่มให้กด ไม่งั้นจอจะไม่ยอมโชว์
    ui.poll()
    time.sleep_ms(STEP_MS)

seg.text("DONE")     # Seg7 แสดงตัวอักษรบางตัวได้ด้วย ไม่ได้จำกัดแค่ตัวเลข
seg.color(COL_OK)
status.text("จบแล้ว - Seg7 ขึ้น DONE ได้ เพราะมันรับข้อความ")
proof.text("จำไว้: Seg7 ใช้ text() เท่านั้น")
ui.poll()

lcd.print("สรุป: บั๊กนี้เงียบสนิท ไม่มี exception ให้จับ")
