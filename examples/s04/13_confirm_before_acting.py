# 13_confirm_before_acting.py - คำสั่งที่ทำให้ของจริงขยับ ต้องถามก่อนหนึ่งครั้ง
# ชุดตัวอย่างประจำคาบ 04
#
# ไฟล์นี้สอน: ui.ButtonMatrix วางปุ่มหลายใบเป็นตารางด้วย widget เดียว
#             · ui.MsgBox คือกล่องยืนยันที่มีหัวเรื่อง เนื้อความ และปุ่มของตัวเอง
# ดูที่จอ   : แถวปุ่มสองใบ "เปิดพัดลม" กับ "ปิดพัดลม" แยกกันคนละใบ
#             แตะแล้วกล่องยืนยันขึ้นมาบอกว่ากำลังจะเกิดอะไร ไม่ใช่ถามลอย ๆ
# กับดัก    : ปุ่มเดียวที่สลับเปิด-ปิด ดูประหยัดพื้นที่ แต่คนที่เดินมาถึงแผงแล้ว
#             ไม่รู้ว่าตอนนี้เปิดอยู่หรือปิดอยู่ จะกดแล้วได้ผลตรงข้ามกับที่ตั้งใจ
#             แผงจริงจึงแยกปุ่มเปิดกับปุ่มปิดเสมอ (S7.7.7) และคำยืนยันต้องบอก
#             "สิ่งที่จะเกิด" ไม่ใช่คำว่า "ยืนยันไหม" ซึ่งไม่ได้เพิ่มข้อมูลอะไรเลย
#
# บน Eva Kit: ui.ButtonMatrix กับ ui.MsgBox เป็นของใหม่ในไลบรารี เพิ่ม 15 ส.ค. 2026

import lcd
import time
import ui

COL_TEXT = 0xE8EAED
COL_DIM = 0x9AA3AF
COL_ACCENT = 0x4A9EFF

RUN_MS = 30000

ui.screen()
time.sleep_ms(200)

ui.Label("สั่งของจริง ต้องยืนยันก่อน", x=24, y=16, color=COL_TEXT, value=28)

state = ui.Label("ตอนนี้: พัดลมปิดอยู่", x=24, y=64, color=COL_TEXT, value=24)

# --- ปุ่มสั่งงาน: เปิดกับปิดแยกกันคนละใบ ----------------------------------
ui.Label("สั่งงาน", x=24, y=112, color=COL_DIM, value=20)
bm = ui.ButtonMatrix(x=24, y=144, w=352, h=96)
bm.add_button("เปิดพัดลม")
bm.add_button("ปิดพัดลม")

# --- กล่องยืนยัน: หัวเรื่องกับเนื้อความคั่นด้วยขึ้นบรรทัดใหม่ ------------------
ui.Label("กล่องยืนยัน", x=416, y=112, color=COL_DIM, value=20)
mb = ui.MsgBox("ยืนยันคำสั่ง\nพัดลมจะเริ่มหมุนทันที", x=416, y=144, w=352)
mb.add_button("ตกลง")

hint = ui.Label("แตะปุ่มซ้าย แล้วอ่านกล่องขวาก่อนตัดสินใจ", x=24, y=264,
                color=COL_DIM, value=20)

ui.poll()

lcd.clear()
lcd.console("<h2>MsgBox + ButtonMatrix</h2>")
print("MsgBox + ButtonMatrix พร้อมให้ยืนยัน")

# ปุ่มใน ButtonMatrix ส่ง value_changed พร้อมลำดับของปุ่มที่ถูกแตะ เริ่มที่ 0
# เหมือน Dropdown - ไม่ได้ส่งข้อความบนปุ่มกลับมา ต้องเปิดตารางของเราเอง
ACTION = {0: ("เปิด", "พัดลมจะเริ่มหมุนทันที"),
          1: ("ปิด", "พัดลมจะหยุดหมุนทันที")}

pending = None
t0 = time.ticks_ms()
while time.ticks_diff(time.ticks_ms(), t0) < RUN_MS:
    for ev in ui.poll():
        if ev["handle"] == bm.id() and ev["type"] == "value_changed":
            pending = ev["value"]
            what, why = ACTION.get(pending, ("ไม่รู้จัก", "คำสั่งนี้ไม่มีในตาราง"))
            # คำยืนยันบอกสิ่งที่จะเกิด ไม่ใช่ถามว่ายืนยันไหม
            # ข้อความยาวเกิน 126 ไบต์จะถูกตัดพร้อมคำเตือน - Thai หนึ่งตัว 3 ไบต์
            # สองบรรทัดนี้จึงรวมกันต้องไม่เกิน 42 ตัวอักษร
            mb.text("ยืนยัน " + what + "\n" + why)
            hint.text("กำลังรอการยืนยัน - กดตกลงในกล่องขวา")
            hint.color(COL_ACCENT)
            lcd.print("ขอยืนยัน:", why)
        elif ev["handle"] == mb.id() and pending is not None:
            what, why = ACTION.get(pending, ("ไม่รู้จัก", ""))
            state.text("ตอนนี้: พัดลม" + ("หมุนอยู่" if pending == 0 else "ปิดอยู่"))
            hint.text("ทำคำสั่งแล้ว - แตะปุ่มซ้ายเพื่อสั่งใหม่")
            hint.color(COL_DIM)
            lcd.print("<span class=ok>ทำแล้ว:", why + "</span>")
            pending = None
    time.sleep_ms(50)

lcd.print("<span class=muted>หมดเวลา</span>")

# ตาคุณ
# 1) ลองรวมสองปุ่มเป็นปุ่มเดียวชื่อ "สลับ" แล้วให้เพื่อนที่ไม่เห็นหน้าจอมาก่อน
#    มากดดู - ถามว่าเขารู้ไหมว่ากำลังจะเปิดหรือปิด นั่นคือเหตุผลของ S7.7.7
# 2) เปลี่ยนข้อความในกล่องเป็น "ยืนยันไหม" เฉย ๆ แล้วเทียบกับของเดิม
#    ข้อความไหนทำให้คนหยุดคิดก่อนกดจริง
# 3) เพิ่มปุ่มใบที่สามด้วย bm.add_button("ทดสอบ", True) - True คือขึ้นแถวใหม่
