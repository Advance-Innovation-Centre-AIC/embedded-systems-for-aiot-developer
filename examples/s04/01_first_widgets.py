# 01_first_widgets.py - widget ตัวแรก และเหตุผลที่ต้องใส่ x กับ y ทุกครั้ง
#
# ไฟล์นี้สอน: เรียกคลาสของ ui หนึ่งครั้งได้ widget หนึ่งตัว ที่ค้างบนจอจนกว่า
#             จะมีใครเรียก ui.screen() ล้างใหม่
# ดูที่จอ   : การ์ดหนึ่งใบที่มีตัวนับ "แตะไปกี่ครั้ง" กับชื่อปุ่มที่แตะล่าสุด
#             ปุ่มสองใบ และบรรทัดสถานะ แตะปุ่มแล้วตัวนับเดินขึ้นทันที
# กับดัก    : ถ้าไม่ใส่ x= y= จอจะเรียงให้เองบนกริด 200 พิกเซล ข้อความยาวจะล้นไปทับ
#             ช่องถัดไป เคยทำให้แผงควบคุมของคอร์สนี้เพี้ยนมาแล้วครั้งหนึ่ง

import ui
import lcd
import time

RUN_MS = 25000

COL_TEXT = 0xFFFFFF
COL_DIM = 0xA0B4CC
COL_CARD = 0x142240
COL_OK = 0x00E676
COL_INFO = 0x40C4FF

# ล้างหน้าก่อนเสมอ ถ้ากลุ่มก่อนหน้าทิ้ง widget ค้างไว้ เราจะนับโควตา 32 ตัวผิด
ui.screen()
time.sleep_ms(200)      # ให้ CM55 ล้างเสร็จก่อนยิงคำสั่งชุดใหม่

# value= ของ Label คือ "ขนาดฟอนต์" ไม่ใช่ค่าตัวเลขใด ๆ รับได้ห้าค่า
# คือ 14 16 20 24 28 เห็น value= ที่ Label เมื่อไร ให้อ่านว่าขนาดตัวอักษรทันที
ui.Label("widget ตัวแรก", x=20, y=12, color=COL_TEXT, value=24)

# การ์ดรายงาน สร้างกรอบก่อนแล้วค่อยวางของข้างใน ลำดับการสร้างคือลำดับการวาดทับ
ui.Panel(x=20, y=52, w=650, h=110, color=COL_CARD, min=COL_DIM, max=12, value=1)
ui.Label("แตะไปแล้ว (ครั้ง)", x=40, y=62, color=COL_DIM, value=16)

# Seg7 คือตัวเลขตัวโต และมันรับ "ข้อความ" เท่านั้น str() จึงจำเป็น
seg = ui.Seg7(text="0", x=40, y=92, w=160, h=50, color=COL_OK)

ui.Label("ปุ่มที่แตะล่าสุด", x=260, y=62, color=COL_DIM, value=16)
last = ui.Label("ยังไม่มี", x=260, y=92, color=COL_INFO, value=24)

# ปุ่มสองใบ กำหนดตำแหน่งเองทั้งคู่ กว้าง 200 ห่างกัน 220 เหลือช่องว่าง 20
# ตำแหน่งของปุ่มเป็นส่วนหนึ่งของการออกแบบ ไม่ใช่เรื่องที่ปล่อยให้บังเอิญ
b_hello = ui.Button("ทักทาย", x=20, y=180, w=200, h=80, color=0x1E88E5, value=20)
b_bye = ui.Button("ลาก่อน", x=240, y=180, w=200, h=80, color=0x546E7A, value=20)
ui.Label("แตะปุ่มสองใบนี้", x=470, y=205, color=COL_DIM, value=20)

# เก็บหมายเลขประจำตัวไว้ เพราะเหตุการณ์ที่ ui.poll() ส่งกลับมา
# บอกแค่ handle เป็นตัวเลข ไม่ได้บอกชื่อตัวแปรของเรา
id_hello = b_hello.id()
id_bye = b_bye.id()

status = ui.Label("ยังไม่ได้แตะอะไร", x=20, y=286, color=COL_DIM, value=20)
ui.Label("ทุก widget ต้องระบุ x= y= เสมอ", x=20, y=330, color=COL_DIM, value=16)

# บรรทัดเปิดเรื่องลงคอนโซล เขียนก่อนเข้าลูป คนเปิดลิ้นชักดูตอนไหนก็เจอ
lcd.print("widget ตัวแรก - แตะปุ่มแล้วตัวนับบนจอจะเดิน")
lcd.print("เหตุการณ์แต่ละครั้งจะถูกบันทึกไว้ตรงนี้")

taps = 0
t0 = time.ticks_ms()

while time.ticks_diff(time.ticks_ms(), t0) < RUN_MS:
    # ui.poll() คืน list ของ dict ครั้งละไม่เกิน 8 เหตุการณ์ ว่างได้ ไม่ใช่ None
    # ต้องเรียกทุกรอบ เพราะ CM55 ซ่อนกล่องบรรจุไว้จนกว่า poll ครั้งแรกจะมาถึง
    for ev in ui.poll():
        if ev["type"] == "clicked":
            # เช็ก handle ด้วย เพราะปุ่มทุกใบส่ง type เดียวกันหมด
            if ev["handle"] == id_hello:
                name = "ทักทาย"
            elif ev["handle"] == id_bye:
                name = "ลาก่อน"
            else:
                continue

            taps = taps + 1
            seg.text(str(taps))      # ตัวเลขต้องแปลงเป็นข้อความก่อนเสมอ
            last.text(name)
            status.text("แตะปุ่ม " + name + " แล้ว")
            lcd.print("clicked -> " + name + " (ครั้งที่ " + str(taps) + ")")

    # หน่วงอย่างน้อย 50 ms คืนเวลาให้ระบบไปวาดจอ
    # ลูปที่เร็วกว่านี้ทำให้เฟรมหายเงียบ ๆ ไม่มี error ให้จับ
    time.sleep_ms(50)

# ปิดท้ายบนจอก่อน แล้วค่อยลงคอนโซล คนที่ดูแต่จอต้องรู้ว่าจบแล้วเหมือนกัน
status.text("หมดเวลา - แตะทั้งหมด " + str(taps) + " ครั้ง")
last.text("จบแล้ว")
lcd.print("สรุป: แตะทั้งหมด " + str(taps) + " ครั้ง")
lcd.print("widget ยังค้างบนจอ จนกว่าจะมีใครเรียก ui.screen()")
