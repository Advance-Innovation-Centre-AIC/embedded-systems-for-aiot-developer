# 11_menu_settings_tree.py - จอที่สองแบบที่สอง เมื่อของไม่ได้เท่ากันทุกหัวข้อ
# ชุดตัวอย่างประจำคาบ 04
#
# Why : 10_tabview_second_screen.py แบ่งจอด้วยแท็บ ซึ่งเหมาะกับของที่ "เท่ากัน"
#       เช่นตอนนี้ ทั้งวัน เกณฑ์ - สามหัวข้อที่ใครก็ได้มาก่อนหลัง แต่หน้าตั้งค่า
#       ของเครื่องจริงไม่ใช่แบบนั้น มันเป็นชั้น ๆ คือมีหัวข้อใหญ่ แตะแล้วลงไป
#       เจอหัวข้อย่อย แล้วมีปุ่มย้อนกลับ ยัดของแบบนั้นลงแท็บจะได้แท็บสิบใบ
#       ที่ไม่มีใครหาของเจอ
# What: ui.Menu คือกองหน้าซ้อนกัน หนึ่งหน้ามีได้หลายแถว แต่ละแถวชี้ไปอีกหน้าได้
#       ด้วย .opens() เฟิร์มแวร์จัดปุ่มย้อนกลับกับหัวเรื่องให้เอง
# How : menu.add_page("ชื่อ") คืนหน้ามาหนึ่งใบ - หน้าแรกที่สร้างคือหน้าที่โชว์
#       page.section() คืนกล่องจัดกลุ่ม แล้ว section.row("ข้อความ") คืนแถว
#       สุดท้าย row.opens(page) คือเส้นที่เชื่อมแถวกับหน้า
#
# ดูที่จอ: ซ้ายคือเมนูสามแถว แตะแถวไหนก็ลงไปหน้านั้น มีลูกศรย้อนกลับที่หัวเมนู
#          ขวาคือการ์ดสรุปว่าค่าที่ตั้งไว้ตอนนี้คืออะไร
# กับดัก : "ตัวเมนู" ไม่บอกว่าตอนนี้เปิดหน้าไหนอยู่ การเดินหน้าจบภายใน LVGL
#          แต่ "แถว" เป็น widget ที่มีแฮนเดิลของตัวเอง จึงขอ pressed ได้ด้วย
#          row.listen("pressed") แล้วโปรแกรมจะรู้ว่าคนแตะแถวไหนไป
#
#          บรรทัดเหล่านี้เคยเขียนว่า "เมนูไม่ส่ง event เลยสักตัว ทั้งตัวเมนูและ
#          แถวของมัน" ครึ่งหลังไม่จริงตั้งแต่ 15 ส.ค. 2026 - examples/widgets/
#          menu.py ถูกแก้ไปแล้วตอนนั้น แต่ไฟล์นี้ตกค้าง ทีม RED จับได้ 16 ส.ค.
#          และพิสูจน์บนตัวจำลองด้วยการแตะจริงว่าแถวส่ง pressed กลับมา
#          และ section ไม่ใช่ page: เรียก row.opens(section) จะเงียบสนิท
#          เพราะ CM55 เช็กว่าแฮนเดิลปลายทางต้องเป็นชนิดหน้าเท่านั้น

import lcd
import time
import ui

COL_TEXT = 0xE8EAED
COL_DIM = 0x9AA3AF
COL_CARD = 0x171B22
COL_ACCENT = 0x4A9EFF

ROUNDS = 150

# ค่าตั้งของเครื่องอยู่ใน dict ของเรา ไม่ได้อยู่ในเมนู - เมนูเป็นแค่หน้าต่าง
# ที่มองเข้ามาดู ใครแก้ค่าจริงต้องแก้ที่นี่ แล้วค่อยเขียนขึ้นจอ
setting = {"ssid": "AIoT-Class", "แจ้งเตือนที่": 60, "รอบส่ง": 5}

ui.screen()
time.sleep_ms(200)

ui.Label("หน้าตั้งค่าแบบเป็นชั้น", x=24, y=16, color=COL_TEXT, value=28)

# value=1 เปิดปุ่มย้อนกลับที่หน้าราก ทำให้หัวเมนูมีลูกศรตลอดเวลา
# ไม่ใช่โผล่มาเฉพาะตอนอยู่หน้าลูก - คนใช้จะได้ไม่ต้องเดาว่ากดตรงไหนถึงจะออก
menu = ui.Menu(x=24, y=64, w=440, h=272, color=COL_CARD, value=1)

# หน้าแรกที่ add_page() คือหน้าที่เมนูเปิดให้เอง จึงต้องเป็นหน้าราก
page_root = menu.add_page("ตั้งค่าเครื่อง")
page_net = menu.add_page("เครือข่าย")
page_alarm = menu.add_page("การแจ้งเตือน")
page_about = menu.add_page("เกี่ยวกับเครื่อง")

# หน้าราก: หนึ่ง section สามแถว - section คือกล่องจัดกลุ่ม ไม่ใช่หน้า
sec_root = page_root.section()
row_net = sec_root.row("เครือข่าย")
row_alarm = sec_root.row("การแจ้งเตือน")
row_about = sec_root.row("เกี่ยวกับเครื่อง")

# เส้นที่เชื่อมแถวกับหน้า - ถ้าไม่มีสามบรรทัดนี้ เมนูจะแตะได้แต่ไม่ไปไหน
# ขอ pressed จากทั้งสามแถว - นี่คือสิ่งที่ทำให้โปรแกรมรู้ว่าคนแตะแถวไหน
# ตัวเมนูเองยังเงียบอยู่ แต่แถวไม่ใช่ ค่าตั้งต้นคือเงียบ จึงต้องขอก่อน
row_net.listen("pressed")
row_alarm.listen("pressed")
row_about.listen("pressed")
ROW_NAME = {row_net.id(): "เครือข่าย",
            row_alarm.id(): "การแจ้งเตือน",
            row_about.id(): "เกี่ยวกับเครื่อง"}

row_net.opens(page_net)
row_alarm.opens(page_alarm)
row_about.opens(page_about)

# หน้าลูก: ข้อความของแถวพาค่าไปด้วย เพราะไม่มีทางอื่นให้ค่าขึ้นไปอยู่ในเมนู
sec_net = page_net.section()
sec_net.row("วง " + setting["ssid"])
sec_net.row("ต่ออัตโนมัติเมื่อเปิดเครื่อง")

sec_alarm = page_alarm.section()
sec_alarm.row("เตือนเมื่อเกิน " + str(setting["แจ้งเตือนที่"]) + " องศา")
sec_alarm.row("ส่งซ้ำทุก " + str(setting["รอบส่ง"]) + " วินาที")

sec_about = page_about.section()
sec_about.row("รุ่น Eva Kit EPC2")
sec_about.row("เฟิร์มแวร์ BENTO")

# การ์ดขวา: ค่าเดียวกันที่เมนูโชว์ แต่เห็นได้โดยไม่ต้องเดินเข้าไป
# หน้าตั้งค่าที่ดีต้องตอบได้ทั้งสองแบบ - ดูรวดเดียว และเดินดูทีละชั้น
ui.Panel(x=496, y=64, w=272, h=272, color=COL_CARD, max=8)
ui.Label("ค่าที่ใช้อยู่ตอนนี้", x=520, y=88, color=COL_DIM, value=20)
ui.Label(setting["ssid"], x=520, y=136, color=COL_TEXT, value=24)
ui.Label("เตือนที่ 60 องศา", x=520, y=184, color=COL_TEXT, value=24)
ui.Label("ส่งทุก 5 วินาที", x=520, y=232, color=COL_TEXT, value=24)
ui.Label("แตะเมนูซ้ายดูเพิ่ม", x=520, y=280, color=COL_DIM, value=20)

# ป้ายนี้สั้นเพราะข้อความตอนสร้างมีเพดาน - ยาวเกินแล้วถูกตัดกลางคันเงียบ ๆ
line = ui.Label("เมนูพาคนเดินดู แต่ไม่บอกโปรแกรม", x=24, y=344,
                color=COL_DIM, value=20)

lcd.clear()
lcd.console("<h2>Menu - หน้าตั้งค่าแบบเป็นชั้น</h2>")
lcd.print("Menu 1 + หน้า 4 + section 4 + แถว 9 = 18 แฮนเดิล")
lcd.print("จากเพดาน 64 - โครงลึกกินโควตาเร็วกว่าที่คิด")

events = 0
for i in range(ROUNDS):
    # นับเฉพาะที่มาจากแถว - ตัวเมนูไม่ส่งอะไรเลย และนั่นคือครึ่งที่ยังจริงอยู่
    # ของกับดักข้างบน ส่วนอีกครึ่งพิสูจน์ได้ด้วยตัวเลขนี้ว่ามันไม่จริงแล้ว
    for ev in ui.poll():
        events += 1
        who = ROW_NAME.get(ev["handle"], "ตัวเมนูเอง")
        line.text("แตะแถว " + who)
        lcd.print("event:", ev["type"], "จาก", who)
    time.sleep_ms(200)

lcd.print("<span class=ok>event จากแถวเมนู =", events, "</span>")
lcd.print("ถ้าแตะแถวแล้วยังได้ศูนย์ แปลว่า .listen() ไปไม่ถึง CM55")
print("Menu: .add_page() -> .section() -> .row() -> .opens()")

# ตาคุณ
# 1) เดินเข้าไปทุกหน้าแล้วกดย้อนกลับ นับดูว่าคอนโซลขึ้น event กี่บรรทัด
#    ถ้าได้ศูนย์ แปลว่าเมนูทำงานถูกต้องตามที่ไลบรารีเป็นอยู่ ไม่ใช่เมนูเสีย
# 2) ลบ row_alarm.opens(page_alarm) ออกหนึ่งบรรทัด แล้วแตะแถวนั้น - มันจะนิ่ง
#    ไม่มี error ไม่มีอะไรเลย แถวที่ไม่ได้ชี้ไปไหนกับแถวที่พัง หน้าตาเหมือนกัน
# 3) เปลี่ยน row_about.opens(page_about) เป็น row_about.opens(sec_about)
#    section ไม่ใช่หน้า CM55 จึงปฏิเสธเงียบ ๆ - ลองหาให้เจอว่าต่างกันตรงไหน
#    โดยดูจากค่าที่ .section() กับ .add_page() คืนมา
