# 10_roller_picks_the_filter.py - เลือกด้วยการปัดนิ้ว ไม่ใช่กดวนทีละครั้ง
# ชุดตัวอย่างประจำคาบ 05
#
# Why : 08_six_filters_one_signal.py ให้เลือกตัวกรองด้วยปุ่ม "ตัวถัดไป" ซึ่งแปลว่า
#       จะไปดู Kalman ต้องกดห้าครั้ง และตลอดเวลานั้นไม่มีใครเห็นว่ามีอะไรให้เลือกบ้าง
#       ปุ่มวนแบบนั้นซ่อนทั้งรายการไว้ในหัวคนเขียน จอสัมผัสไม่ควรทำงานแบบนั้น
# What: ui.Roller คือวงล้อเลือกที่กางตัวเลือกให้เห็นพร้อมกันหลายบรรทัด แล้วเลื่อน
#       ด้วยนิ้ว ตัวที่เลือกอยู่ถูกไฮไลต์ค้างไว้เสมอ จึงตอบสองคำถามพร้อมกัน
#       คือ "ตอนนี้เลือกอะไรอยู่" กับ "มีอะไรให้เลือกอีกบ้าง"
# How : สร้างเปล่า ๆ แล้วเติมทีละบรรทัดด้วย .add_option() อ่านตัวที่เลือกด้วย
#       .value() หรือรอ event value_changed ซึ่งส่ง "ลำดับ" ของบรรทัด เริ่มที่ 0
#
# ดูที่จอ: ซ้ายคือวงล้อ มีหกตัวเลือกแต่เห็นทีละสี่บรรทัด ตัวที่เลือกอยู่เป็นแถบสีเน้น
#          ขวาคือกราฟที่วาดค่าดิบ (เทา) คู่กับตัวกรองที่เลือกอยู่ (ฟ้า)
#          ปัดวงล้อแล้วสองบรรทัดล่างเปลี่ยนตามทันที
#          ที่ว่างเหนือแถบสีคือเรื่องปกติของวงล้อ มันแปลว่าเราอยู่บรรทัดแรกของรายการ
# กับดัก : value= ตอนสร้าง Roller ทำสองหน้าที่พร้อมกัน คือ "บรรทัดที่เลือก"
#          และ "ขนาดฟอนต์ของข้อความไทย" (ui_widget_mgr.c เรียก
#          ui_apply_content_font ด้วย cfg->init_val ตัวเดียวกัน) ตั้ง value=24
#          เพราะอยากได้ตัวหนังสือขนาด 24 จะได้บรรทัดที่ 24 ซึ่งไม่มีอยู่จริงแถมมาด้วย
#          ไฟล์นี้จึงไม่ตั้ง value= เลย แล้วสั่งเลือกบรรทัดด้วย .value(n) ทีหลัง
#          และตัวเลือกทั้งหมดรวมกันยาวได้ไม่เกิน 320 ไบต์ (UI_OPTIONS_MAX)
#          เกินแล้วบรรทัดที่เกินหายเงียบ ๆ ไม่มี error เพราะ ITEM_ADD ยิงแล้วลืม
#
# ทำไมไม่ไปแก้ 08 ให้ใช้ Roller แทนปุ่ม (SPEC S7.10.2): 08 ทำงานอยู่และถูกอ้าง
#   ในสไลด์คาบนี้แล้ว การเปลี่ยน widget ในไฟล์ที่ใช้สอนอยู่ ทำให้สไลด์พูดของเก่า
#   ทันที จึงเก็บ 08 ไว้เป็นแบบ "ปุ่มวน" และให้ไฟล์นี้เป็นแบบ "เลือกด้วยนิ้ว"
#   วางคู่กันแล้วเปรียบเทียบได้ ซึ่งมีค่ากว่าการแทนที่
#
# ไม่ต้องใช้เซนเซอร์ สัญญาณสร้างในไฟล์นี้ รันซ้ำได้ผลเดิมทุกครั้ง

import dsp
import lcd
import time
import ui

DT_MS = 200
FS = 5.0
N = 60
STEP_AT = 20
SPIKES = (34, 47)
WOBBLE = (0.0, 1.2, -0.9, 0.6, -1.4, 1.0, -0.5, 0.8)
ROUNDS = 200

COL_TEXT = 0xE8EAED
COL_DIM = 0x9AA3AF
COL_CARD = 0x171B22
COL_ACCENT = 0x4A9EFF

# ชื่อสั้นเพราะเพดาน 320 ไบต์นับรวมทุกบรรทัด และภาษาไทยหนึ่งตัวกิน 3 ไบต์
NAMES = ("EMA a=0.2", "SMA w=8", "LPF 0.4Hz", "HPF 0.4Hz", "Median w=5",
         "Kalman r=4")


def signal(n):
    base = 40.0 if n < STEP_AT else 60.0
    v = base + WOBBLE[n % len(WOBBLE)]
    if n in SPIKES:
        v += 35.0
    return v


filters = (dsp.EMA(alpha=0.2), dsp.SMA(window=8), dsp.LPF(cutoff=0.4, fs=FS),
           dsp.HPF(cutoff=0.4, fs=FS), dsp.Median(window=5),
           dsp.Kalman1D(q=0.05, r=4.0))

ui.screen()
time.sleep_ms(200)

ui.Label("เลือกตัวกรองด้วยนิ้ว", x=24, y=16, color=COL_TEXT, value=28)

# ไม่ตั้ง value= ด้วยเหตุผลในหัวไฟล์ - เป้าสัมผัสกว้าง 232 สูง 248
# ซึ่งเกินขั้นต่ำ 88 พิกเซลของ NUREG-0700 อยู่มาก เพราะนิ้วต้องลากไม่ใช่แค่จิ้ม
ro = ui.Roller(x=24, y=72, w=232, h=248, color=COL_TEXT)
for name in NAMES:
    ro.add_option(name)

# ไม่เรียก ro.prop(ui.PROP_VISIBLE_ROWS, n) ที่นี่โดยตั้งใจ - มันไปสั่ง
# lv_roller_set_visible_row_count() ซึ่ง "เขียนทับความสูง" ที่เราตั้งไว้ด้วย h=
# แล้วคำนวณจากความสูงบรรทัดของฟอนต์ธีม ไม่ใช่ฟอนต์ไทยที่วงล้อนี้ใช้จริง
# ผลที่วัดได้บนตัวจำลอง: ขอ 5 บรรทัด ได้กล่องเตี้ยลงจนเห็นจริง 3 บรรทัด
# ระหว่าง "ตั้งความสูงเอง" กับ "สั่งจำนวนบรรทัด" ให้เลือกอย่างเดียว

ch = ui.Chart(x=288, y=72, w=480, h=176, min=0, max=110, color=COL_DIM)
s_raw = 0
s_sel = ch.add_series(COL_ACCENT)

l_pick = ui.Label("กำลังวาด: " + NAMES[0], x=288, y=264, color=COL_ACCENT,
                  value=24)
l_val = ui.Label("รอค่าแรก", x=288, y=304, color=COL_DIM, value=24)

lcd.clear()
lcd.console("<h2>Roller - เลือกด้วยการปัดนิ้ว</h2>")
lcd.print("เทาคือค่าดิบ ฟ้าคือตัวกรองที่เลือกอยู่")
lcd.print("Roller ส่ง value_changed พร้อมลำดับบรรทัด เริ่มที่ 0")

sel = 0
n = 0

for i in range(ROUNDS):
    x = signal(n % N)

    # ป้อนทุกตัวทุกรอบ ไม่ใช่เฉพาะตัวที่เลือก - ตัวกรองมีความจำ ถ้าหยุดป้อน
    # แล้วสลับมาหาทีหลัง มันจะตอบด้วยความจำเก่าที่ขาดช่วง
    outs = []
    for f in filters:
        outs.append(f.update(x))

    ch.set_next(s_raw, int(x))
    # HPF แกว่งรอบศูนย์ ยกขึ้น 50 เฉพาะตอนวาด เพื่อให้เห็นบนแกนเดียวกัน
    drawn = outs[sel] + 50.0 if sel == 3 else outs[sel]
    ch.set_next(s_sel, int(drawn))

    # ค่าที่ต้องอ่าน อัปเดตวินาทีละครั้ง ไม่ใช่ทุกรอบ - ลูปนี้ 200 ms
    if i % 5 == 0:
        l_val.text("ค่าล่าสุด " + "%.2f" % outs[sel] + " จากค่าดิบ "
                   + "%.1f" % x)

    for ev in ui.poll():
        if ev["handle"] == ro.id() and ev["type"] == "value_changed":
            # ค่าที่ส่งมาคือลำดับบรรทัด ไม่ใช่ข้อความ ต้องเปิดตารางชื่อเอง
            # เหมือน Dropdown ทุกประการ ต่างกันแค่ท่าที่นิ้วใช้
            sel = ev["value"]
            if sel < 0 or sel >= len(NAMES):
                sel = 0
            l_pick.text("กำลังวาด: " + NAMES[sel])
            lcd.print("เลือกบรรทัดที่", sel, NAMES[sel])

    n += 1
    time.sleep_ms(DT_MS)

l_val.text("จบรอบ - ปัดวงล้อได้อีกในการรันครั้งหน้า")
lcd.print("<span class=ok>วงล้อบอกทั้งตัวที่เลือกและตัวที่เหลือพร้อมกัน</span>")
print("Roller: .add_option() เติมทีละบรรทัด .value() อ่านลำดับที่เลือก")

# ตาคุณ
# 1) สั่ง ro.value(5) ก่อนเข้าลูป แล้วดูว่าวงล้อเลื่อนไปบรรทัดสุดท้ายเอง
#    แล้วลองเทียบกับการใส่ value=5 ตอนสร้าง ซึ่งจะได้ผลเดียวกันแต่พ่วงเรื่อง
#    ขนาดฟอนต์มาด้วย - สองทางนี้ไม่เท่ากัน
# 2) เพิ่ม ro.add_option() ด้วยชื่อยาว ๆ ภาษาไทยไปเรื่อย ๆ จนเกิน 320 ไบต์
#    แล้วนับว่าบรรทัดหายไปตั้งแต่ตัวที่เท่าไร - ไม่มี error ให้จับสักตัว
# 3) เติม ro.prop(ui.PROP_VISIBLE_ROWS, 5) เข้าไปหลังลูป add_option แล้วรันใหม่
#    วัดดูว่ากล่องสูงเท่าเดิมไหม และเห็นกี่บรรทัด - เทียบกับ h=248 ที่เราขอไว้
#    นี่คือกรณีที่คำสั่งสองคำสั่งเถียงกันเรื่องเดียวกัน แล้วคำสั่งหลังชนะเงียบ ๆ
#    จำนวนบรรทัดที่เห็นคือสิ่งที่บอกว่า "ยังมีของให้เลือกอีก" ถ้าเห็นบรรทัดเดียว
#    มันก็กลายเป็น Dropdown ที่ปัดได้ ไม่ใช่วงล้อ
