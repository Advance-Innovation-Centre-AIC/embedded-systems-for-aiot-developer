# 08_six_filters_one_signal.py - ตัวกรองทั้งหกตัวของ dsp บนสัญญาณเส้นเดียวกัน
# ชุดตัวอย่างประจำคาบ 05
#
# ไฟล์นี้สอน: dsp มีตัวกรองหกตัว ไม่ใช่สองตัว - EMA SMA LPF HPF Median Kalman1D
#             ทั้งหกใช้ท่าเดียวกันหมดคือ .update(x) / .value() / .reset()
#             ป้อนสัญญาณเดียวกันเข้าไปพร้อมกัน แล้วดูว่าใครทำอะไรกับมัน
# ดูที่จอ   : กราฟซ้ายวาดค่าดิบคู่กับตัวกรองที่เลือกอยู่ กดปุ่มเพื่อวนดูทีละตัว
#             คอลัมน์ขวาคือ .value() ของทั้งหกตัวพร้อมกัน อัปเดตทุกรอบ
# กับดัก    : ค่า window ที่นอกช่วงจะถูกหนีบเงียบ ๆ ไม่มี error - SMA หนีบไว้ 2..64
#             ส่วน Median หนีบไว้ 3..15 แล้วบังคับให้เป็นเลขคี่ด้วย ขอ 4 จะได้ 5
#             และ HPF คืน 0.0 เสมอในรอบแรก เพราะยังไม่มีค่าก่อนหน้าให้ลบ
#
# ต่อจากคาบ 1: examples/s01/13_raw_and_filtered.py ให้เห็น EMA กับ Median วิ่งคู่กัน
#   บนกราฟใบเดียวมาแล้ว โดยยังไม่ได้บอกว่าทำไมถึงเลือกสองตัวนั้น ไฟล์นี้เอาอีกสี่ตัว
#   ที่เหลือมาวางข้าง ๆ กัน เพื่อให้ "เลือก" กลายเป็นการตัดสินใจ ไม่ใช่การเดา
#
# ไม่ต้องใช้เซนเซอร์ใด ๆ สัญญาณสร้างขึ้นเองในไฟล์นี้ จึงรันซ้ำแล้วได้ผลเหมือนเดิม
# ทุกครั้ง เอาไว้เถียงกันด้วยตัวเลขได้ ต่างจากการหมุนลูกบิดซึ่งไม่มีวันซ้ำรอยเดิม

import dsp
import lcd
import time
import ui

DT_MS = 200        # คาบลูปเท่ากับที่ใช้จริงในคาบเรียน 5 Hz
FS = 5.0           # จึงเป็น 5 Hz พอดี ตัวเลขนี้ต้องบอก LPF/HPF ให้ตรงกัน
N = 60             # จำนวนจุดหนึ่งรอบก่อนวนกลับ

# สัญญาณทดสอบ: ฐาน 40 มีขั้นบันไดขึ้นไป 60 ตอนกลาง มีคลื่นสั่นเล็ก ๆ ตลอด
# และมีหนามแหลมโดดเดี่ยวสองจุด - ครบทั้งสามอย่างที่ตัวกรองแต่ละแบบถนัดคนละอย่าง
STEP_AT = 20
SPIKES = (34, 47)
WOBBLE = (0.0, 1.2, -0.9, 0.6, -1.4, 1.0, -0.5, 0.8)


def signal(n):
    base = 40.0 if n < STEP_AT else 60.0
    v = base + WOBBLE[n % len(WOBBLE)]
    if n in SPIKES:
        v += 35.0          # หนามที่ไม่ใช่ของจริง - เอาไว้ดูว่าใครกลืนมันได้
    return v


# ตัวกรองทั้งหก สร้างครั้งเดียวนอกลูป เพราะทุกตัวมี "ความจำ" อยู่ข้างใน
# อาร์กิวเมนต์ของทั้งหมดเป็น keyword-only - เขียน dsp.EMA(0.2) จะได้ TypeError
f_ema = dsp.EMA(alpha=0.2)
f_sma = dsp.SMA(window=8)
f_lpf = dsp.LPF(cutoff=0.4, fs=FS)     # ตัดที่ 0.4 Hz บนลูป 5 Hz
f_hpf = dsp.HPF(cutoff=0.4, fs=FS)     # ตัวเดียวกันแต่เอาส่วนที่ "เปลี่ยนเร็ว" ออกมา
f_med = dsp.Median(window=5)
f_kal = dsp.Kalman1D(q=0.05, r=4.0)    # เชื่อการวัดน้อย (r สูง) จึงนิ่งมาก

# ชื่อที่จะโชว์ กับตัวจริง เรียงคู่กันไว้ให้ลูปเดินได้
NAMES = ("EMA a=0.2", "SMA w=8", "LPF 0.4Hz", "HPF 0.4Hz", "Median w=5",
         "Kalman r=4")
FILTERS = (f_ema, f_sma, f_lpf, f_hpf, f_med, f_kal)
COLORS = (0xFF5555, 0x50D890, 0x00BFFF, 0xFFD24A, 0xB388FF, 0xFF9800)

lcd.clear()
lcd.console("<h2>ตัวกรองหกตัวบนสัญญาณเดียวกัน</h2>")
lcd.print("ลูป", DT_MS, "ms = fs", FS, "Hz | ขั้นบันไดที่จุด", STEP_AT)

# พิสูจน์การหนีบค่าเงียบ ๆ ด้วยตัวมันเอง ไม่ใช่ด้วยคำพูดในคอมเมนต์
# repr ของอ็อบเจกต์บอกค่าที่ได้จริงหลังถูกหนีบ ลองอ่านสองบรรทัดนี้ให้ดี
lcd.print("ขอ SMA window=200 ได้จริง:", repr(dsp.SMA(window=200)))
lcd.print("ขอ Median window=4 ได้จริง:", repr(dsp.Median(window=4)))

# ---- หน้าจอ ------------------------------------------------------------------
ui.screen()
ui.Label("dsp: ตัวกรองหกตัว ท่าเดียวกันหมด", x=24, y=24, value=24)

ch = ui.Chart(x=24, y=68, w=448, h=160, min=0, max=110, color=0x9AA3AF)
s_raw = 0                              # ซีรีส์ 0 เกิดมาพร้อมกราฟ สีมาจาก color= ข้างบน
s_sel = ch.add_series(0xE5484D)        # เส้นของตัวกรองที่เลือกอยู่ สีคงที่ตลอด

ui.Label("เทา = ค่าดิบ", x=24, y=240, value=16, color=0x9AA3AF)
lbl_sel = ui.Label("กำลังวาด: EMA a=0.2", x=136, y=240, value=16,
                   color=0xE5484D)
# สีของเส้นเปลี่ยนกลางคันไม่ได้ ป้ายนี้จึงเป็นตัวบอกว่าเส้นแดงคือตัวไหนอยู่

# คอลัมน์ขวา: .value() ของทั้งหกตัวพร้อมกัน นี่คือเหตุผลที่ .value() มีอยู่
# มันขอค่าล่าสุดซ้ำได้โดยไม่ต้องป้อนตัวอย่างใหม่เข้าไป
ui.Label("value() ของทั้งหกตัว", x=488, y=68, value=16)
rows = []
for i in range(6):
    rows.append(ui.Label(NAMES[i] + "  ----", x=488, y=100 + i * 24, value=16,
                         color=COLORS[i]))

# การ์ดเตือนเรื่อง HPF วางใต้คอลัมน์ขวา จบที่ y=340 พอดี ต่ำกว่านั้นคือมุมที่
# ปุ่มคอนโซลจองไว้ Panel ต้องมาก่อนสามบรรทัดที่วางบนมัน ไม่งั้นมันทาทับจนหาย
ui.Panel(x=488, y=252, w=280, h=88)
ui.Label("HPF คนละเรื่องกับอีกห้าตัว", x=504, y=260, value=16, color=0xF5A623)
ui.Label("เก็บส่วนที่เปลี่ยนเร็ว", x=504, y=284, value=16, color=0xF5A623)
ui.Label("ไม่ใช่ระดับของสัญญาณ", x=504, y=308, value=16, color=0xF5A623)

# ปุ่มสามตัวอยู่ใต้กราฟ กว้างพอดีคอลัมน์ซ้าย จึงไม่ไปชนการ์ด HPF ทางขวา
btn_next = ui.Button("ตัวถัดไป >", x=24, y=280, w=128, h=88, color=0x4A9EFF,
                     value=20)
btn_reset = ui.Button("reset ทั้งหมด", x=184, y=280, w=160, h=88,
                      color=0x4A9EFF, value=20)
btn_exit = ui.Button("ออก", x=376, y=280, w=88, h=88, color=0x9AA3AF,
                     value=20)
id_next = btn_next.id()
id_reset = btn_reset.id()
id_exit = btn_exit.id()

sel = 0
n = 0
running = True

while running:
    x = signal(n % N)

    # ป้อนค่าเดียวกันเข้าทั้งหกตัวในรอบเดียว จึงเทียบกันได้ตรง ๆ
    # ทุกตัวคืนค่าที่กรองแล้วออกมาทันทีจาก .update() ไม่ต้องเรียก .value() ตาม
    outs = []
    for f in FILTERS:
        outs.append(f.update(x))

    ch.set_next(s_raw, int(x))
    # HPF แกว่งรอบศูนย์ ถ้าวาดบนแกนเดียวกับที่เหลือจะจมอยู่ก้นกราฟ
    # จึงยกขึ้น 50 เฉพาะตอนวาด - เป็นการเลื่อนเพื่อให้เห็น ไม่ใช่การแก้ค่า
    draw = outs[sel] + 50.0 if sel == 3 else outs[sel]
    ch.set_next(s_sel, int(max(0, min(110, draw))))

    # .value() ไม่ได้ป้อนอะไรเข้าไป มันแค่ถามค่าล่าสุดซ้ำ - ปลอดภัยที่จะเรียกกี่ครั้งก็ได้
    for i in range(6):
        rows[i].text(NAMES[i] + "  {:6.2f}".format(FILTERS[i].value()))

    for ev in ui.poll():
        h = ev['handle']
        if h == id_next:
            sel = (sel + 1) % 6
            lbl_sel.text("กำลังวาด: " + NAMES[sel])
            lbl_sel.color(COLORS[sel])
        elif h == id_reset:
            # .reset() ล้างความจำทุกตัวพร้อมกัน รอบถัดไปทุกตัวจะเริ่มนับหนึ่งใหม่
            # สังเกตว่าค่าที่เห็นกระโดดไปเท่ากับค่าดิบทันที นั่นคือหลักฐานว่าความจำหายจริง
            for f in FILTERS:
                f.reset()
            lcd.print("reset ทั้งหกตัวแล้ว - ดูรอบถัดไปว่าทุกตัวเริ่มใหม่พร้อมกัน")
        elif h == id_exit:
            running = False

    n += 1
    time.sleep_ms(DT_MS)

ui.clear()
print("เทียบกันแล้วจะเห็นว่า Median กลืนหนามได้ ส่วน EMA/SMA/Kalman โดนลากตาม")
print("และ HPF ไม่สนใจระดับของสัญญาณเลย มันสนแค่ว่าเปลี่ยนเร็วแค่ไหน")
