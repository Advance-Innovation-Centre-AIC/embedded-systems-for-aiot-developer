# 07_spangroup_event_log.py - บันทึกเหตุการณ์บนจอ ที่ยังอ่านออกตอนถ่ายเอกสารขาวดำ
# ชุดตัวอย่างประจำคาบ 12
#
# Why : สไลด์ "ส่งเหตุการณ์ ไม่ใช่สตรีมดิบ" ของคาบนี้บอกว่าสิ่งที่ควรส่งขึ้นไปคือ
#       เหตุการณ์ และสิ่งที่ควรอยู่บนจอก็คือเหตุการณ์ชุดเดียวกัน แต่พอเขียนจริง
#       ทุกทีมทำเหมือนกันหมด คือ Label หลายบรรทัดแล้วเปลี่ยน "สีข้อความ"
#       ตามความรุนแรง ซึ่งตกเกณฑ์ S7.7.1 ทันที - แปลงเป็นขาวดำแล้วสามสถานะ
#       กลายเป็นสีเทาเหมือนกันหมด และคนตาบอดสีก็แยกไม่ออกตั้งแต่แรก
# What: ui.SpanGroup คือย่อหน้าเดียวที่ประกอบจาก "ท่อน" หลายท่อน แต่ละท่อนมี
#       ขนาด สี และเส้นใต้ของตัวเองได้ - เส้นใต้กับขนาดคือสิ่งที่รอดจากขาวดำ
# How : .pen(สี) ตั้งสีของ "ท่อนที่จะเติมต่อจากนี้" แล้ว .add_span(ข้อความ,
#       ขนาด, ธง) เติมทีละท่อน จบรอบแล้ว .clear_items() เพื่อเขียนใหม่ทั้งย่อหน้า
#
# ดูที่จอ: การ์ดกลางจอคือบันทึกเหตุการณ์ห้าบรรทัดล่าสุด เวลาเป็นตัวเล็กสีจาง
#          ข้อความเป็นตัวปกติ ส่วนคำที่บอกความรุนแรงมีเส้นใต้
#          ลองหรี่ตามองให้ภาพเบลอ - บรรทัดที่มีเส้นใต้ยังโดดออกมาอยู่
# กับดัก : .pen() เป็นปากกา ไม่ใช่คำสั่งทาสีของที่มีอยู่แล้ว - มันมีผลกับท่อนที่
#          เติม "หลังจากนั้น" เท่านั้น เรียง pen ผิดที่ ท่อนที่แล้วไม่เปลี่ยนสี
#          และท่อนไม่มีแฮนเดิล จึงแก้ทีละท่อนไม่ได้เลย ต้อง clear_items()
#          แล้วเขียนใหม่ทั้งย่อหน้า - ส่วน .text() บน SpanGroup คือคำสั่งล้าง
#          ทุกท่อนทิ้งแล้วเหลือท่อนเดียว ไม่ใช่ "เติมข้อความ"

import lcd
import time
import ui

COL_TEXT = 0xE8EAED
COL_DIM = 0x9AA3AF
COL_CARD = 0x171B22
COL_WARN = 0xF5A623
COL_BAD = 0xE5484D
COL_OK = 0x30A46C

MAX_LINES = 5
ROUNDS = 60

# เหตุการณ์สมมติที่จะไหลเข้ามา - ในงานจริงมาจากท่าที่ 2 Decide ของโครงเริ่มต้น
# แต่ละแถวคือ (วินาทีที่เกิด, ระดับ, ข้อความ)
FEED = (
    (3, "ปกติ", "เริ่มทำงาน รอบส่ง 5 วินาที"),
    (9, "ปกติ", "ต่อ broker ได้"),
    (15, "เฝ้าระวัง", "อุณหภูมิ 62 องศา"),
    (21, "ผิดปกติ", "อุณหภูมิ 81 องศา"),
    (27, "เฝ้าระวัง", "อุณหภูมิ 64 องศา"),
    (33, "ปกติ", "กลับเข้าพิสัย"),
    (39, "ผิดปกติ", "เน็ตหลุด เข้าคิวไว้"),
    (45, "ปกติ", "ต่อกลับได้ ส่งของค้าง 2 ชิ้น"),
)

# ระดับ -> (สี, มีเส้นใต้ไหม) - สีอย่างเดียวไม่พอ จึงมีคอลัมน์ที่สองเสมอ
LEVEL = {
    "ปกติ": (COL_OK, 0),
    "เฝ้าระวัง": (COL_WARN, ui.SPAN_UNDERLINE),
    "ผิดปกติ": (COL_BAD, ui.SPAN_UNDERLINE),
}

ui.screen()
time.sleep_ms(200)

ui.Label("บันทึกเหตุการณ์บนจอ", x=24, y=16, color=COL_TEXT, value=28)

ui.Panel(x=24, y=64, w=744, h=272, color=COL_CARD, max=8)
# color= ของ SpanGroup คือสีตั้งต้นของท่อนที่ไม่ได้สั่ง pen ไว้
log = ui.SpanGroup(x=48, y=88, w=696, h=224, color=COL_TEXT)

line = ui.Label("เส้นใต้รอดจากภาพขาวดำ", x=24, y=344, color=COL_DIM,
                value=20)

lcd.clear()
lcd.console("<h2>SpanGroup - ย่อหน้าเดียว หลายท่อน</h2>")
lcd.print("pen() มีผลกับท่อนที่เติมหลังจากนั้น ไม่ใช่ท่อนเดิม")

shown = []


def redraw():
    """เขียนย่อหน้าใหม่ทั้งอัน จากรายการที่เก็บไว้ฝั่ง MicroPython

    ท่อนไม่มีแฮนเดิล เราจึงเป็นเจ้าของ "ความจริง" เองในตัวแปร shown
    แล้ววาดใหม่ทั้งย่อหน้าทุกครั้ง วิธีนี้คือวิธีเดียวที่ทำได้ และมันตรงกับ
    หลักที่ใช้มาทั้งคอร์สอยู่แล้ว คือมีที่เดียวที่มีสิทธิ์เปลี่ยนสถานะ
    """
    log.clear_items()
    for at, level, text in shown:
        color, decor = LEVEL[level]

        # ท่อนที่ 1 เวลา - ตัวเล็กสุดที่กติกายอมให้ใช้ และสีจางที่สุด
        log.pen(COL_DIM)
        log.add_span("%3d s  " % at, 20)

        # ท่อนที่ 2 ระดับ - สีบอกความรุนแรง และเส้นใต้บอกซ้ำอีกทางหนึ่ง
        # ทางที่สองนี่แหละที่ทำให้ผ่านการทดสอบขาวดำ
        log.pen(color)
        log.add_span(level, 24, decor)

        # ท่อนที่ 3 เนื้อความ - กลับมาสีข้อความปกติ ต้องสั่ง pen ใหม่
        # ถ้าลืมบรรทัดนี้ เนื้อความจะติดสีของระดับไปด้วย แล้วทั้งบรรทัดแดง
        log.pen(COL_TEXT)
        log.add_span("  " + text + "\n", 24)


for i in range(ROUNDS):
    now = i               # หนึ่งรอบเท่ากับหนึ่งวินาทีในเรื่องสมมตินี้

    for at, level, text in FEED:
        if at == now:
            shown.append((at, level, text))
            # เก็บเฉพาะห้าบรรทัดล่าสุด - จอที่ยาวเกินหน้าคือจอที่อ่านไม่ทัน
            if len(shown) > MAX_LINES:
                shown.pop(0)
            redraw()
            lcd.print("[%d s] %s - %s" % (at, level, text))

    time.sleep_ms(1000)

line.text("จบ - หรี่ตามองแล้วยังแยกสามระดับออก")
lcd.print("<span class=ok>สีบอกซ้ำ ไม่ใช่บอกอย่างเดียว</span>")
print("SpanGroup: pen() ทาท่อนถัดไป, add_span() เติม, clear_items() ล้างทั้งย่อหน้า")

# ตาคุณ
# 1) ย้าย log.pen(COL_TEXT) ท่อนที่สามขึ้นไปไว้ก่อน log.pen(color) แล้วรันใหม่
#    ทั้งบรรทัดจะเป็นสีเดียว - นั่นคือความหมายของคำว่า "ปากกา"
# 2) เอา decor ออกจาก add_span ของท่อนที่สอง ให้เหลือแค่สี แล้วถ่ายจอด้วยมือถือ
#    เปิดโหมดขาวดำดู - นี่คือการทดสอบ S7.7.1 ที่ทำเองได้ในสามสิบวินาที
# 3) เพิ่ม MAX_LINES เป็น 12 แล้วดูว่าย่อหน้าล้นการ์ดออกไปไหม
#    SpanGroup ตัดคำเองแต่ไม่เลื่อนเองและไม่ตัดบรรทัดที่เกินให้
