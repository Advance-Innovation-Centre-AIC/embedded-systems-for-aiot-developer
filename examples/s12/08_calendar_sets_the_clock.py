# 08_calendar_sets_the_clock.py - บอร์ดไม่รู้ว่าวันนี้วันที่เท่าไร แล้วใครบอกมัน
# ชุดตัวอย่างประจำคาบ 12
#
# Why : schema ของโครงเริ่มต้นในคาบนี้มีฟิลด์ t และสไลด์เขียนไว้ตรง ๆ ว่า
#       "เวลาบนบอร์ด ใช้เรียงลำดับ" - ไม่ได้เขียนว่าเป็นวันที่ เพราะมันไม่ใช่
#       t คือ ticks_ms ซึ่งนับจากตอนเปิดเครื่อง ไม่ใช่เวลาบนปฏิทิน
#       เหตุผลอยู่ในเฟิร์มแวร์: machine_rtc.c ตั้ง RTC_INIT_YEAR เป็น 15 บนฐาน
#       ปี 2000 และคอมเมนต์ของ reset เขียนว่า "Resets RTC to 1st Jan' 2015"
#       ทุกครั้งที่ตัดไฟ นาฬิกาของบอร์ดกลับไปที่ 1 ม.ค. 2015 เสมอ
#       ทีมที่ส่งวันที่ขึ้น platform โดยไม่ได้ตั้งนาฬิกา จะได้ข้อมูลปี 2015 ทั้งชุด
#       และไม่มีใครสังเกตจนกว่าจะเอาไปทำกราฟย้อนหลัง
# What: ui.Calendar คือปฏิทินที่แตะเลือกวันได้ ใช้ตอนที่ "คน" ต้องเป็นคนบอกวันที่
#       ให้เครื่อง - ซึ่งบนโต๊ะทดลองที่ไม่มี NTP คือทางเดียวที่เหลืออยู่
# How : min=ปี max=เดือน value=วัน ตอนสร้าง แล้วรอ event value_changed
#       ที่ส่งค่ามาเป็นเลขแปดหลัก YYYYMMDD ก้อนเดียว
#
# ดูที่จอ: ซ้ายคือปฏิทิน เปิดมาที่เดือนที่บอร์ดคิดว่าเป็นปัจจุบัน คือ ม.ค. 2015
#          ขวาคือการ์ดเทียบสองวันที่ - ของบอร์ด กับ ของคนที่เพิ่งแตะยืนยัน
# กับดัก : min กับ max ของ Calendar "ไม่ใช่ช่วงค่า" เหมือน Slider หรือ Bar
#          แต่คือ ปี กับ เดือน ส่วน value คือวัน (ui_widget_mgr.c ราวบรรทัด 2100)
#          ใส่ค่านอกพิสัยแล้วมันเงียบ ๆ ถอยไปใช้ 2026-01-01 ไม่มี error
#          และลูกศรเปลี่ยนเดือนที่หัวปฏิทิน "ไม่ส่ง event" - เฟิร์มแวร์กรองทิ้ง
#          ด้วย lv_calendar_get_pressed_date() ที่ตอบไม่ผ่านเมื่อไม่ได้แตะวัน
#          จึงรู้ได้เฉพาะตอนคนแตะ "วัน" ไม่ใช่ตอนคนพลิกดูเดือน
#
# ทั้ง Eva Kit และ Dev Kit: machine.RTC มีอยู่จริง (พอร์ตเดียวกัน modmachine.c ไม่มีเงื่อนไข
#   ตามบอร์ด) ต่างจาก machine.PWM กับ machine.ADC ที่ไม่มี - เรียกได้เลยโดยไม่ต้อง try/except

import lcd
import machine
import time
import ui

COL_TEXT = 0xE8EAED
COL_DIM = 0x9AA3AF
COL_CARD = 0x171B22
COL_ACCENT = 0x4A9EFF
COL_WARN = 0xF5A623
COL_OK = 0x30A46C

RUN_MS = 40000

rtc = machine.RTC()
# ทูเปิลแปดช่องของพอร์ตนี้: ปี เดือน วัน วันในสัปดาห์ ชั่วโมง นาที วินาที เศษวินาที
boot = rtc.datetime()
boot_txt = "%04d-%02d-%02d" % (boot[0], boot[1], boot[2])

ui.screen()
time.sleep_ms(200)

ui.Label("วันนี้วันที่เท่าไร ใครบอก", x=24, y=16, color=COL_TEXT, value=28)

# เปิดปฏิทินที่เดือนที่บอร์ดเชื่อว่าเป็นปัจจุบัน ไม่ใช่ที่เดือนจริงของโลก
# เพราะประเด็นทั้งไฟล์คือ "บอร์ดเชื่ออะไรอยู่"
cal = ui.Calendar(x=24, y=64, w=304, h=272, color=COL_TEXT,
                  min=boot[0], max=boot[1], value=boot[2])

ui.Panel(x=360, y=64, w=408, h=272, color=COL_CARD, max=8)
ui.Label("นาฬิกาของบอร์ดหลังเปิดเครื่อง", x=384, y=88, color=COL_DIM, value=20)
l_board = ui.Label(boot_txt, x=384, y=120, color=COL_WARN, value=24)
ui.Label("วันที่ที่คนยืนยันบนจอ", x=384, y=184, color=COL_DIM, value=20)
l_human = ui.Label("ยังไม่มีใครยืนยัน", x=384, y=216, color=COL_DIM, value=24)
l_hint = ui.Label("แตะวันในปฏิทินเพื่อตั้ง", x=384, y=280, color=COL_DIM,
                  value=20)

line = ui.Label("t ใน payload คือ ticks ไม่ใช่วันที่", x=24, y=344,
                color=COL_DIM, value=20)

lcd.clear()
lcd.console("<h2>Calendar - ใครบอกบอร์ดว่าวันนี้วันที่เท่าไร</h2>")
lcd.print("นาฬิกาบอร์ดหลังเปิดเครื่อง:", boot_txt)
lcd.print("ปี 2015 คือลายเซ็นของนาฬิกาที่ไม่เคยถูกตั้ง")

t0 = time.ticks_ms()
while time.ticks_diff(time.ticks_ms(), t0) < RUN_MS:
    for ev in ui.poll():
        if ev["handle"] == cal.id() and ev["type"] == "value_changed":
            # เลขก้อนเดียวแปดหลัก แกะเองด้วยการหารและมอด ไม่มี tuple ให้
            ymd = ev["value"]
            if ymd < 19000101:
                continue
            y = ymd // 10000
            m = (ymd // 100) % 100
            d = ymd % 100
            picked = "%04d-%02d-%02d" % (y, m, d)

            # ตั้งนาฬิกาจริงตามที่คนแตะ - ชั่วโมงนาทีวินาทีตั้งเป็นศูนย์ เพราะ
            # ปฏิทินให้ได้แค่วัน ค่าที่เราไม่รู้ต้องไม่แต่งขึ้นมาเอง
            rtc.datetime((y, m, d, 0, 0, 0, 0, 0))

            l_human.text(picked)
            l_human.color(COL_OK)
            l_hint.text("ตั้งนาฬิกาแล้ว")
            line.text("ตั้งแล้วอยู่จนกว่าจะตัดไฟ")
            line.color(COL_ACCENT)
            lcd.print("คนยืนยันวันที่", picked, "- ตั้ง RTC แล้ว")

    time.sleep_ms(100)

l_hint.text("หมดเวลา")
lcd.print("<span class=warn>ตัดไฟแล้วกลับไป 2015 เหมือนเดิม</span>")
print("Calendar: min=ปี max=เดือน value=วัน และ event คือ YYYYMMDD ก้อนเดียว")

# ตาคุณ
# 1) กดลูกศรเปลี่ยนเดือนที่หัวปฏิทินสิบครั้ง แล้วนับบรรทัดในคอนโซล - จะได้ศูนย์
#    การพลิกดูเดือนไม่ใช่การเลือก จึงไม่มีเหตุการณ์ให้รับ
# 2) เปลี่ยน min=boot[0] เป็น min=15 (ปี ค.ศ. แบบสองหลักที่ RTC เก็บจริง)
#    ปฏิทินจะเด้งไปที่ 2026-01 เงียบ ๆ เพราะ 15 อยู่นอกพิสัย 1900-2200
# 3) หลังตั้งนาฬิกาแล้ว เพิ่ม lcd.print(rtc.datetime()) ในลูป แล้วดูว่าวินาที
#    เดินเองไหม จากนั้นถอดสาย USB แล้วเสียบใหม่ - แล้วดูว่าเหลืออะไร
