# s02_ai_observer.py - สมุดบันทึกผลการทดลอง แล้วพาบอร์ดขึ้นเน็ต (ฉบับฝึกเติมโค้ด)
# วิธีรัน: 1) ทดลองกับบอร์ดจริงจนได้ผลครบ 3 แถว แล้วจดลงตัวแปร TRIALS
#          2) แตะการ์ด Playground บนจอบอร์ดค้างไว้ ก่อนส่งโค้ดขึ้นไป
#          3) เติมช่องว่างตามคำใบ้ให้ครบ กด Program to Device แล้วอ่านผลบนจอ
#
# ไฟล์นี้ทำสองอย่างที่คาบ 2 ต้องการ อย่างแรกคือเอาผลที่เราจดมาด้วยมือขึ้นจอ
# ให้คนอื่นอ่านเป็นตารางได้ อย่างที่สองคือพาบอร์ดออกเน็ตแล้วรายงานเลข IP กลับมา
# สองอย่างนี้รวมกันคือรูปแบบของเครื่องมือหน้างานแทบทุกตัว - วัด จด แล้วรายงานออกไป
#
# ชุดตัวอย่างของคาบนี้อยู่ที่ examples/s02/ สามไฟล์ และมันคือลำดับคำถามเรื่องลิงก์
# ต่อครั้งแรกแล้วได้เลขที่อยู่มาไหม (examples/s02/01_wifi_first_connect.py)
# "ต่อติดตอนนั้น" กับ "ยังต่ออยู่ตอนนี้" ต่างกันอย่างไร (examples/s02/02_link_uptime.py)
# และลิงก์แบบไหนที่เรียกว่าใช้งานได้จริง (examples/s02/03_your_link_rule.py)
# เปิดอ่านก่อนกรอกตาราง TRIALS ข้างล่าง จะได้รู้ว่าคอลัมน์ไหนจดแล้วตอบคำถามได้จริง
#
# ดูที่จอ: ซ้ายคือตารางผลการทดลองที่เติมทีละแถวตอนรัน ขวาคือไฟสถานะลิงก์สองดวง
#         และมาตรวัดเวลาต่อเฉลี่ย เทียบกับเพดาน 85 วินาทีที่คนยืนรอไหว
#         ส่วนหน้าจอเขียนมาให้ครบแล้ว ช่องว่างหกจุดอยู่ที่ตรรกะ ไม่ได้อยู่ที่การวาด
# กับดัก : ตารางนี้เป็นค่าที่ทีมจดมาด้วยมือ ไม่ใช่ค่าที่บอร์ดวัดสด ๆ ตอนนี้
#         หน้าจอจึงต้องเขียนกำกับไว้ ค่าที่ไม่บอกว่าตัวเองมาจากไหน คือค่าที่เชื่อไม่ได้

import lcd
import time
import ui
import wifi

# ---------- ค่าที่ทีมต้องแก้ก่อนรัน (อยู่บนสุดที่เดียว หาเจอโดยไม่ต้องอ่านทั้งไฟล์) ----------
TEAM_NAME = "BentoBuilders"
WIFI_SSID = "AIoT-Class"
WIFI_PASS = "<รหัสผ่านของห้องเรียน>"

# --- ท่าที่ 1: เปิดสมุดบันทึกของทีม ---
# ท่าเปิดเหมือนคาบ 1 ทุกประการ เพราะมันคือการพิสูจน์ว่าช่องทางถึงจอยังใช้ได้
# เติม: lcd.clear()
pass

# เติม: lcd.console("<h2>บันทึกการต่อเน็ต - คาบ 2</h2>")
pass

lcd.console("<span class=muted>ทีม " + TEAM_NAME + " - บันทึกผลการทดลอง</span>")

# --- ท่าที่ 2: ผลการทดลองที่จดมาจากบอร์ด ---
# แต่ละแถว: (ชื่อสิ่งที่ทดลอง, เงื่อนไขที่ทำ, ได้ผลไหม, เวลาที่ใช้เป็น ms)
# สามแถวที่ใส่ไว้ให้เป็นแค่ "ตัวอย่างรูปแบบ" จากรอบเก่า ทีมต้องเขียนทับให้ครบทั้งสามแถว
# ด้วยผลที่ลงมือทดลองเองบนบอร์ดตัวนี้ ไม่ใช่ผลที่ลอกจากเอกสารหรือจากทีมอื่น
# ทีมที่จดผลการต่อลิงก์: examples/s02/02_link_uptime.py บอกไว้ว่าทำไม "ต่อติดตอนนั้น"
# กับ "ยังต่ออยู่ตอนนี้" ถึงต้องจดแยกกัน สองคำถามนี้คำตอบต่างกันได้ทุกวินาที
TRIALS = [
    ("2.4GHz", "ยืนข้างเราเตอร์", True, 3180),
    ("2.4GHz", "เดินไปสุดห้อง", True, 9240),
    ("5GHz", "ยืนข้างเราเตอร์", False, 85000),
]

# --- ท่าที่ 3: กางหน้ารายงานบนจอ ก่อนจะมีข้อมูลอะไรไปใส่ ---
# ลิ้นชัก Console เก็บบรรทัดไว้ให้เราอ่านย้อนหลัง แต่คนที่เดินมาดูโต๊ะเราตอนนี้
# ต้องการหน้าเดียวที่ตอบได้ทันทีว่า "ทดลองไปกี่รอบ ผลเป็นยังไง แล้วตอนนี้ต่ออยู่ไหม"
# หน้าจอจึงสร้างก่อน แล้วค่อยเติมข้อมูลลงไประหว่างทาง ไม่ใช่รอจนจบแล้วค่อยวาดทีเดียว
COL_TEXT, COL_DIM = 0xE8EAED, 0x9AA3AF
COL_CARD, COL_OK, COL_BAD = 0x171B22, 0x30A46C, 0xE5484D
WAIT_CEILING_MS = 85000        # เพดานที่คนยืนรอจริงได้ ก่อนจะสรุปว่าบอร์ดแฮงก์

ui.screen()
time.sleep_ms(200)

# ui.Table แทนการเรียง ui.Label เอง เพราะสี่คอลัมน์ที่ความยาวไม่เท่ากันทุกแถว
# ถ้าจัดด้วยมือจะเยื้องกันจนอ่านไม่ออกทันทีที่ทีมเปลี่ยนข้อความในช่อง cond
# แถวหนึ่งสูงราว 70 พิกเซล และจะสูงเป็นสองเท่าทันทีที่ข้อความในช่องยาวเกิน
# ความกว้างคอลัมน์แล้วตัดบรรทัด - ตั้ง col_width ให้พอกับข้อความที่ยาวที่สุดเสมอ
tbl = ui.Table(x=16, y=36, w=500, h=352, cols=4)
tbl.col_width(0, 120)
tbl.col_width(1, 190)
tbl.col_width(2, 90)
tbl.col_width(3, 100)
tbl.add_row("ย่าน", "เงื่อนไข", "ผล", "ms")

ui.Label("ผลการทดลองของทีม " + TEAM_NAME, x=16, y=8, color=COL_TEXT, value=20)

# ไฟสองดวงบอกสถานะลิงก์ ติดทีละดวงเสมอ - แผงที่ติดพร้อมกันสองดวงคือแผงที่อ่านไม่ออก
ui.Panel(x=524, y=36, w=256, h=352, color=COL_CARD, min=COL_DIM, max=12, value=1)
ui.Label("สถานะลิงก์ตอนนี้", x=536, y=44, color=COL_DIM, value=20)
led_up = ui.Led(x=540, y=72, w=48, h=48, color=COL_OK, value=0)
ui.Label("ต่ออยู่", x=584, y=76, color=COL_DIM, value=20)
led_down = ui.Led(x=596, y=112, w=48, h=48, color=COL_BAD, value=1)
ui.Label("ยังไม่ต่อ", x=652, y=120, color=COL_DIM, value=20)
lbl_ip = ui.Label("IP: ยังไม่มี", x=536, y=164, color=COL_DIM, value=20)

# ที่มาของค่าต้องอยู่บนหน้าจอเดียวกับค่า ไม่ใช่อยู่ในหัวคนที่พิมพ์มันเข้าไป
ui.Label("ตารางซ้าย = ค่าที่จดมือ", x=536, y=200, color=COL_DIM, value=20)
ui.Label("ไม่ใช่ค่าที่วัดสดตอนนี้", x=536, y=224, color=COL_DIM, value=20)

# มาตรวัดเวลา: เลข ms ลอย ๆ ไม่บอกว่านานไหม เทียบกับเพดาน 85 วินาทีแล้วบอกทันที
# ui.Scale คือไม้บรรทัด ไม่มีเข็มและไม่รับ .value() ตัวที่ขยับคือ ui.Bar ที่วางทับ
ui.Label("เวลาต่อเฉลี่ย เทียบเพดาน", x=528, y=256, color=COL_DIM, value=20)
lbl_wait = ui.Label("- วินาที", x=536, y=292, color=COL_TEXT, value=20)
bar_wait = ui.Bar(x=632, y=312, w=148, h=12, color=0x4A9EFF,
                  min=0, max=WAIT_CEILING_MS, value=0)
sc_wait = ui.Scale(x=536, y=328, w=148, h=44, color=COL_TEXT,
                   min=0, max=WAIT_CEILING_MS // 1000)
# ไม้บรรทัดสั้น ๆ ที่มีตัวเลขหกตัวจะทับกันจนอ่านไม่ออก - เอาแค่สามพอ
sc_wait.ticks(11, 5)
ui.poll()

# --- ท่าที่ 4: ไล่พิมพ์ทีละแถว ---
for name, cond, hit, ms in TRIALS:
    # เลือกแท็กสีตามผล เขียวเมื่อต่อติด แดงเมื่อไม่ติด - ตาอ่านสีได้ก่อนตัวอักษร
    mark = "<span class=ok>ต่อติด</span>" if hit else "<span class=error>ไม่ติด</span>"

    # เติม: lcd.print(name, "|", cond, "|", mark, "|", ms, "ms")
    # คอลัมน์ผลบอกได้แค่ติดหรือไม่ติด ซึ่งทิ้งรายละเอียดไปมาก
    #   examples/s02/03_your_link_rule.py ชี้ให้เห็นว่า "ไม่ผ่าน" มีได้หลายแบบ
    #   และกฎที่มองเห็นแค่แบบเดียว จะรายงานน้อยกว่าความจริงโดยไม่มีอะไรฟ้อง
    #   ทีมที่อยากได้คะแนนเต็มข้อวิเคราะห์ ควรจดให้เห็นด้วยว่าไม่ผ่านแบบไหน
    pass

    # แถวเดียวกันลงตารางบนจอด้วย (เขียนมาให้แล้ว) ลิ้นชักตอบว่า "ที่ผ่านมาเกิดอะไร"
    # ตารางตอบว่า "สรุปแล้วผลเป็นยังไง" - คนละคำถาม จึงต้องมีทั้งคู่
    # ช่องผลเขียนเป็นคำ ไม่ใช่ระบายสีอย่างเดียว ภาพขาวดำก็ยังอ่านออก
    tbl.add_row(name, cond, "ต่อติด" if hit else "ไม่ติด", str(ms))
    ui.poll()

    # หน่วงให้แถวไล่ขึ้นทีละบรรทัด ดูทันว่ากำลังพิมพ์ถึงแถวไหน
    time.sleep_ms(400)

# --- ท่าที่ 5: สรุปผลรวมของการทดลอง ---
hits = 0
total_ms = 0
for row in TRIALS:
    if row[2]:
        hits += 1
    total_ms += row[3]

avg_ms = 0                     # ตั้งค่าเริ่มต้นไว้ก่อน ไฟล์จะได้รันได้แม้ยังไม่เติมบรรทัดล่าง
# เติม: avg_ms = total_ms // len(TRIALS)
# ก่อนเชื่อเลขเฉลี่ยนี้: ค่าเฉลี่ยจากสามครั้งยังไม่นับว่าเป็นการวัด ให้จดต่ำสุดกับสูงสุด
#   คู่ไปด้วยเสมอ เพราะช่วงของค่าบอกเรื่องที่ค่าเฉลี่ยเดี่ยว ๆ กลบไว้หมด
#   และเวลาที่จดต้องเป็นเวลาที่คนยืนรอจริง ไม่ใช่แค่ช่วงที่โปรแกรมนับได้
pass

lcd.print("สรุป: ต่อติด", hits, "จาก", len(TRIALS), "ครั้ง")
lcd.print("เวลาที่ใช้ต่อ เฉลี่ย", avg_ms, "ms")

# มาตรวัดขยับครั้งเดียวหลังคำนวณเสร็จ ไม่ใช่ขยับตามทุกแถวระหว่างลูป
# ตัวเลขที่กระพริบเร็วกว่าวินาทีละครั้ง คนอ่านไม่ทัน และไม่มีใครได้ประโยชน์จากมัน
# ถ้ายังไม่เติม avg_ms ข้างบน แถบนี้จะนิ่งอยู่ที่ศูนย์ - นั่นคือคำตอบว่าเติมครบหรือยัง
bar_wait.value(avg_ms)
lbl_wait.text(str(avg_ms // 1000) + " วินาที")
ui.poll()

# --- ท่าที่ 6: ต่อ WiFi แล้วรายงาน IP ---
# พิมพ์คำเตือนก่อนเรียก ไม่ใช่หลัง เพราะคำสั่งนี้บล็อกได้นานถึงราว 85 วินาที
lcd.print("<span class=muted>กำลังต่อ WiFi รอได้ถึง 85 วินาที</span>")

ok = False                     # ตั้งค่าเริ่มต้นไว้ก่อน กัน NameError ตอนยังไม่เติม
# เติม: ok = wifi.connect(WIFI_SSID, WIFI_PASS)
pass

if ok:
    # เติม: lcd.print("<span class=ok>WiFi OK - IP " + wifi.ip() + "</span>")
    pass

    # ไฟสลับกันสองดวง ดวงที่ดับจะหรี่ลง ไม่ใช่หายไป คนดูจึงยังเห็นว่ามีดวงนั้นอยู่
    led_up.value(1)
    led_down.value(0)
    lbl_ip.text("IP: " + wifi.ip())
else:
    lcd.print("<span class=muted>ต่อไม่สำเร็จ ตรวจ SSID และรหัสผ่าน</span>")
    led_up.value(0)
    led_down.value(1)
    lbl_ip.text("IP: ต่อไม่สำเร็จ")
ui.poll()

print("จบการบันทึกผล - ถ้าจอเงียบ เช็กว่าเข้าเมนู Playground หรือยัง")
