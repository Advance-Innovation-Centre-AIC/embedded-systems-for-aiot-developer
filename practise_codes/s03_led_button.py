btn = gpio.button(0)   # เก็บไว้ในตัวแปรครั้งเดียว แล้วใช้ซ้ำทั้งโปรแกรม

# --- ท่าที่ 1: ถามบอร์ดก่อนว่ามีอะไรให้เล่นบ้าง ---
