# การ์ดซ้ายล่าง: ปุ่มเปิดกับปุ่มปิดแยกกันคนละปุ่ม ตามกฎของแผงควบคุมจริง
# ปุ่มสูง 88 px และเว้นห่างกัน 32 px ตามระยะนิ้วจริง ไม่ใช่ตามที่ตาว่าพอ
