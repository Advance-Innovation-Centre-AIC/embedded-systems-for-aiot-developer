touch_scale = ui.Scale(x=28, y=300, w=428, h=40, color=COL_TEXT, min=0, max=100)
touch_scale.ticks(11, 2)
# ไฟแทนตัวหนังสือสี: ถ่ายจอเป็นขาวดำแล้วยังแยกออกว่าดวงไหนติด
led_b0 = ui.Led(x=28, y=344, w=48, h=48, color=COL_OK, value=0)
ui.Label("ปุ่ม 0", x=84, y=356, color=COL_DIM, value=20)
led_b1 = ui.Led(x=160, y=344, w=48, h=48, color=COL_OK, value=0)
ui.Label("ปุ่ม 1", x=216, y=356, color=COL_DIM, value=20)

# --- ท่าที่ 4: บรรทัดคุณภาพของค่า และการเทียบค่าดิบกับค่ากรองแล้ว ---
ui.Panel(x=280, y=336, w=196, h=52, color=COL_CARD, min=COL_DIM, max=12, value=1)
ui.Label("คุณภาพของค่า", x=292, y=340, color=COL_DIM, value=16)
lbl_health = ui.Label("อ่านค่าปกติ", x=292, y=364, color=COL_TEXT, value=16)
health = "อ่านค่าปกติ"      # ข้อความล่าสุดของบรรทัดคุณภาพ คิดใหม่วินาทีละครั้ง

raw_line = ui.Label("ดิบ 0.00 %", x=252, y=196, color=COL_TEXT, value=16)
ema_line = ui.Label("กรอง 0.00 %", x=368, y=196, color=COL_TEXT, value=16)
ui.Label("อัลฟา 0.2", x=252, y=216, color=COL_DIM, value=16)
ui.poll()

# ฟิลเตอร์ต้องเกิดนอกลูป เพราะมันต้องจำอดีต - สร้างในลูปเมื่อไร ค่าที่ได้จะเท่าค่าดิบเป๊ะ
# เติม: ema = dsp.EMA(alpha=0.2)
# 0.2 นี้แปลว่ากรองแรงแค่ไหน: examples/s05/06_ema_time_constant.py แปลง alpha เป็นวินาที
#   ด้วย tau = dt * (1-alpha)/alpha แล้ววาดเทียบกับ alpha ของขั้นก่อนหน้าให้เห็นบนกราฟเดียวกัน
#   ที่นั่นยังเตือนไว้ด้วยว่า ถ้าไม่ใส่ alpha ค่าตั้งต้นคือ 0.1 ไม่ใช่ 0.5 อย่างที่หลายคนเดา
pass

# ค่าเริ่มต้นสำหรับรอบก่อนเติมโค้ด ทำให้จอขึ้นครบแม้ตัวเลขยังไม่ขยับ
raw, pct, volts = 0, 0.0, 0.0
ema_pct = 0.0
slider = 0
last_sec = -1        # วินาทีที่เพิ่งเขียนตัวเลขลงจอ กันไม่ให้เขียนถี่กว่าวินาทีละครั้ง

# --- ท่าที่ 5: ลูปหลักและจังหวะที่ปลอดภัย ---
while True:
    fresh = True
    try:
        # ทุกบรรทัดที่อ่านค่า = ถามคอร์จอหนึ่งรอบ อยากได้ทั้งชุดในการถามครั้งเดียว
        # ให้ใช้ sensors.snapshot() ซึ่งคืน dict ที่มีคีย์ bmi270 capsense pot
        raw = sensors.pot.read()
        # โวลต์ทั้งสองบอร์ดคำนวณจากเปอร์เซ็นต์ ไม่ได้วัดมาตรง ๆ และแรงดันอ้างอิง 3.3 V
        # ที่ใช้คูณยังไม่มีใครเอามิเตอร์ไปยืนยันบนบอร์ดไหนเลย ใช้ดูแนวโน้มได้ แต่อย่าอ้างเป็นค่าวัด
        volts = sensors.pot.voltage()

        # เติม: pct = sensors.pot.percent()
        # สงสัยว่าเลขดิบกับเปอร์เซ็นต์กับโวลต์ผูกกันอย่างไร: examples/s05/05_adc_counts_to_volts.py
        #   ลากเส้นทั้งสองเส้นคู่กัน ค่าจริงที่เรียบ กับค่าที่ ADC เห็นซึ่งเป็นบันได
        #   และชี้กับดักตัวหารสองตัว 2**n กับ 2**n - 1 ที่สลับกันแล้วเพี้ยนน้อยจนจับไม่ได้
        pass

        # เติม: slider = sensors.capsense.slider()
        # ปล่อยนิ้วแล้วค่าไม่กลับเป็นศูนย์ นั่นไม่ใช่บั๊ก: examples/s05/01_capsense_dimmer.py
        #   วาดค่าดิบคู่กับระดับที่สั่งไฟจริง ให้เห็นว่าตอนไม่มีนิ้วแตะ ค่าดิบลงไปติดลบ
        #   และเตือนว่า slider() == 0 ไม่ได้แปลว่าปล่อยนิ้ว มันแปลว่าแตะที่ปลายซ้ายก็ได้
        pass

        b0, b1 = sensors.capsense.buttons()
    except OSError:
        # อ่านพลาดหนึ่งรอบไม่ควรทำให้จอดับทั้งหน้า ใช้ค่าเดิมไปก่อน
        # แต่ต้องบอกให้คนดูรู้ว่าตัวเลขบนจอตอนนี้ไม่ใช่ค่าปัจจุบันแล้ว
        fresh = False
        b0, b1 = 0, 0

    # เติม: pot_bar.value(int(max(0, min(100, pct))))
    # แถบสั่นยิบ ๆ ทั้งที่ไม่มีใครแตะลูกบิด: examples/s05/03_pot_setpoint_deadband.py
    #   เพิ่มกติกาข้อเดียวว่า "ขยับไม่ถึงเท่านี้ ถือว่าไม่ได้ขยับ" แล้วค่าที่รายงานกลายเป็น
    #   ขั้นบันไดที่นิ่ง ใช้ตอนต้องส่งค่าออกเครือข่าย จะลดจำนวนข้อความลงหลายเท่า
    pass

    # ครอบขอบเขตก่อนส่งเข้า widget เสมอ ค่าที่มาจากภายนอกโปรแกรมเราไม่มีใครรับประกันให้
    touch_bar.value(max(0, min(100, slider)))

    # เติม: ema_pct = ema.update(pct)
    # ป้อนเข้า เอาค่าที่กรองแล้วออก - แค่นั้นจริง ๆ แต่ EMA ไม่ได้ชนะทุกงาน
    #   examples/s05/07_median_beats_mean.py ยิงค่าหลุดเข้าไปหนึ่งค่า แล้วให้ดูว่าค่าเฉลี่ย
    #   ถูกลากตามไปหลายรอบ ส่วน median แบนสนิท ถ้างานของทีมเจอค่าหลุดบ่อย ให้เลือกจากภาพนั้น
    pass

    # แถบกับไฟขยับได้ทุกรอบ เพราะตาคนอ่าน "ตำแหน่ง" ได้โดยไม่ต้องหยุดอ่าน
    # หนึ่งดวงติดเท่านั้น แผงที่ติดพร้อมกันหลายดวงคือแผงที่อ่านไม่ออก
    over = ema_pct >= th
    led_ok.value(0 if over else 1)
    led_bad.value(1 if over else 0)
    led_b0.value(1 if b0 else 0)
    led_b1.value(1 if b1 else 0)

    # เติม: events = ui.poll()
    # กฎเหล็กข้อ 1: ต้องเรียกทุกรอบ ไม่งั้น widget บางตัวจะถูกซ่อนไว้นานถึงสองวินาที
    #   และปุ่มเพิ่ม/ลดเกณฑ์จะกดไม่ติดเลย เพราะ event ไม่มีทางเดินทางกลับมาถึงเรา
    events = []
    pass

    # --- ปุ่มเพิ่ม/ลดเกณฑ์: คนละปุ่มกันคนละทิศ ไม่ใช่ปุ่มเดียวสลับ ---
    for ev in events:
        if ev.get("type") != "clicked":
            continue
        if ev.get("handle") == btn_up.id():
            th = min(TH_MAX, th + TH_STEP)
            sp_th.value(th)
        elif ev.get("handle") == btn_dn.id():
            th = max(TH_MIN, th - TH_STEP)
            sp_th.value(th)

    # ตัวเลขที่คนต้องอ่าน เขียนใหม่ไม่เกินวินาทีละครั้ง และอยู่ตำแหน่งเดิมเสมอ
    sec = time.ticks_ms() // 1000
    if sec != last_sec:
        last_sec = sec
        lbl_pct.text("{:.1f} %".format(pct))
        lbl_raw.text("ค่าดิบ {}".format(raw))
        lbl_volt.text("โวลต์ {:.3f} V".format(volts))
        raw_line.text("ดิบ    {:.2f} %".format(pct))
        ema_line.text("กรอง  {:.2f} %".format(ema_pct))
        # ตั้งสีก่อนแล้วค่อยเขียนข้อความ สองบรรทัดนี้เป็นคำสั่งคนละครั้งข้ามคอร์
        if not fresh:
            lbl_health.color(COL_WARN)
            health = "ค่าค้าง - เลขคือค่าล่าสุด"
        elif over:
            lbl_health.color(COL_BAD)
            health = "เกินเกณฑ์ {} %".format(th)
        else:
            lbl_health.color(COL_DIM)
            health = "ปกติ ต่ำกว่า {} %".format(th)

    # --- ชีพจรของช่องทางข้ามคอร์: ส่งบรรทัดสถานะซ้ำทุกรอบโดยตั้งใจ ---
    # ฝั่งจอมีตัวจับเวลาสองจังหวะ โหมดเร็ว 5 ms กับโหมดปกติ 200 ms และมันจะอยู่
    # โหมดเร็วต่อไปอีก 500 ms ทุกครั้งที่ได้รับคำสั่ง "เขียนข้อความ" หรือ "ย้าย/ย่อ/เปลี่ยนสี"
    # แต่ .value() ของแถบกับไฟ "ไม่" ปลุกโหมดนั้น ลูปที่อัปเดตเฉพาะแถบกับไฟจึงเงียบเกิน
    # ครึ่งวินาที แล้วจอจะถอยไปโหมดช้า ภาพกระตุกทั้งที่โค้ดไม่ได้เปลี่ยนสักบรรทัด
    # ข้อความที่ส่งไปนี้เท่าเดิมเกือบทุกรอบ และเฟิร์มแวร์ไม่วาดซ้ำถ้าข้อความไม่เปลี่ยน
    # เราจึงจ่ายแค่ค่าส่งข้ามคอร์ ไม่ได้จ่ายค่าวาดใหม่
    lbl_health.text(health)

    time.sleep_ms(200)   # จังหวะที่ผ่านการทดสอบสำหรับจอที่มีของหลายชิ้น
