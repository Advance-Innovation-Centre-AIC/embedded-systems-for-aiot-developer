ui.Label("เปอร์เซ็นต์ที่วัดได้", x=28, y=152, color=COL_DIM, value=20)
lbl_pct = ui.Label("0.0 %", x=28, y=180, color=COL_TEXT, value=28)
lbl_raw = ui.Label("ค่าดิบ 0", x=252, y=148, color=COL_DIM, value=16)
