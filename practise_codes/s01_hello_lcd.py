# s01_hello_lcd.py - ข้อความแรกของทีม ขึ้นจอ Eva Kit (ฉบับฝึกเติมโค้ด)
# วิธีรัน: 1) บนจอบอร์ด แตะการ์ด Playground บนหน้า Home ก่อน (สำคัญมาก)
#          2) แก้ชื่อทีมและรายชื่อสมาชิก แล้วเติมช่องว่างตามคำใบ้ให้ครบ
#          3) เปิดไฟล์นี้ใน BENTO IDE กด "Program to Device" แล้วอ่านผลบนจอบอร์ด
#
# คาบนี้เราคุยกับจอผ่านโมดูล lcd: ข้อความถูกพิมพ์จากคอร์ CM33 (ฝั่งที่รัน Python)
# แล้ววิ่งข้ามกล่องจดหมาย IPC ไปให้คอร์ CM55 วาดลงจอ
# เห็นข้อความบนจอเมื่อไร แปลว่าเราคุยครบทั้งสองสมองของบอร์ดแล้ว
#
# ตัวอย่างของคาบนี้อยู่ที่ examples/s01/ ทุกไฟล์รันเดี่ยว ๆ ได้ ไม่ต้องต่อกับไฟล์นี้
# ถ้าส่งขึ้นบอร์ดแล้วจอเงียบสนิทตั้งแต่บรรทัดแรก ให้เปิด examples/s01/01_first_line.py ก่อนอย่างอื่น
# มันไล่ให้ดูว่าข้อความหนึ่งบรรทัดไปโผล่ได้สามที่ และที่ที่เราคิดว่ามันอยู่ มักไม่ใช่ที่ที่มันอยู่จริง
#
# ดูที่จอ: ท่าที่ 1-4 คือช่องว่างที่ต้องเติม ทุกบรรทัดไปเข้าลิ้นชัก Console
#         ท่าที่ 5 เขียนมาให้ครบแล้ว ไม่มีช่องว่าง - มันวางป้ายประจำทีมลงหน้า Playground
#         อ่านมันให้จบก่อนรัน แล้วเทียบว่าของที่ ui วาง กับของที่ lcd พิมพ์ ไปคนละที่กันยังไง

import lcd
import time
import ui

# ---------- ข้อมูลของทีม (แก้สามบรรทัดนี้ให้เป็นของทีมเราก่อนรัน) ----------
TEAM_NAME = "BentoBuilders"                      # ชื่อทีม (ไทยหรืออังกฤษก็ได้)
MEMBERS = ["สมชาย", "สมหญิง", "สมศรี"]              # รายชื่อสมาชิก 2-3 คน
MOTTO = "เล่นของจริงก่อน แล้วค่อยแกะ"                 # คำขวัญทีมสั้น ๆ

# --- ท่าที่ 1: ล้างจอให้สะอาด แล้วปักหัวเรื่อง ---
# จอ Playground อาจมีของจากโปรแกรมก่อนหน้าค้างอยู่ เริ่มจากสถานะที่รู้แน่เสมอ
# เติม: lcd.clear()
# ยังไม่แน่ใจว่า clear() ล้างอะไรไปบ้าง: examples/s01/05_clear_and_refresh.py วางท่าล้างแล้ววาดใหม่ทั้งหน้า
#   ไว้ข้างท่าที่แก้เฉพาะค่าเดิม ให้เห็นกับตาว่าสองท่านี้ให้ผลบนจอคนละแบบ
pass

# lcd.console() เขียนลงพื้นที่ console บนจอ - แท็ก <h2> ทำให้เป็นหัวเรื่องใหญ่
# เติม: lcd.console("<h2>AIoT in Action - คาบ 1</h2>")
# ใส่แท็กแล้วหน้าตาไม่เปลี่ยน: examples/s01/02_markup_tags.py พิมพ์เนื้อความชุดเดียวกันสองรอบ
#   ติดคลาสกับไม่ติดคลาส และบอกไว้ด้วยว่าชื่อคลาสที่พิมพ์ผิดจะเงียบสนิท ไม่มี error ให้จับ
pass

# <span class=muted> คือตัวหนังสือสีจาง เหมาะกับข้อความประกอบที่ไม่ใช่พระเอก
lcd.console("<span class=muted>ทดสอบจอครั้งแรกของทีม " + TEAM_NAME + "</span>")

# --- ท่าที่ 2: ประโยคทักทายจากทีม ---
# lcd.print() รับหลายอาร์กิวเมนต์แบบเดียวกับ print() ปกติ
# มันคั่นแต่ละค่าด้วยช่องว่างให้เอง (sep=' ') เราไม่ต้องต่อสตริงเอง
# เติม: lcd.print("สวัสดีจากทีม", TEAM_NAME)
# พิมพ์แล้วหาไม่เจอบนจอ: examples/s01/01_first_line.py แยกให้ดูว่า ui.Label ขึ้นหน้า Playground ทันที
#   ส่วนบรรทัดของ lcd ไปรออยู่ในลิ้นชัก Console มุมขวาล่าง ที่ต้องกดเปิดเองก่อนถึงจะเห็น
pass

lcd.print("คำขวัญของเรา:", MOTTO)

# print() ธรรมดาขึ้นที่คอนโซลของ BENTO IDE ฝั่งคอม ไม่ใช่จอบอร์ด
# มีไว้เทียบให้เห็นว่า "ปลายทาง" ของสองคำสั่งนี้คนละที่กัน
print("ส่งข้อความทักทายขึ้นจอบอร์ดแล้ว ดูที่จอ ไม่ใช่ที่หน้าคอม")

# --- ท่าที่ 3: แนะนำสมาชิกทีละคนด้วยลูป ---
# รายชื่ออยู่ใน list เพิ่มหรือลดสมาชิกได้โดยไม่ต้องแตะตัวลูปเลย
for i in range(len(MEMBERS)):
    # i นับจาก 0 ตามธรรมเนียม Python - บวก 1 ตอนแสดงผลให้คนอ่านเข้าใจง่าย
    # เติม: lcd.print("สมาชิกคนที่", i + 1, ":", MEMBERS[i])
    # ชื่อยาวแล้วบรรทัดขาดหายไปดื้อ ๆ: examples/s01/06_safe_print.py ย้ายกฎ 127 ไบต์เข้าไปอยู่ใน
    #   ฟังก์ชันเดียว แล้วเรียกฟังก์ชันนั้นแทน จะได้ไม่ต้องนั่งนับไบต์เองทุกบรรทัดที่พิมพ์
    pass

    # หน่วง 800 ms ให้ชื่อขึ้นทีละคน คนดูอ่านทัน
    # เติม: time.sleep_ms(800)
    pass

# --- ท่าที่ 4: ปิดท้ายด้วยสถานะสีเขียว ---
# <span class=ok> คือสีเขียว "งานสำเร็จ" - จบโปรแกรมด้วยการบอกผลชัดเจนทุกครั้ง
# ระวังความยาวรวมต่อการเรียกหนึ่งครั้ง: อย่าเกิน 127 ไบต์ (ไทยตัวละ 3 ไบต์ = ราว 42 ตัวอักษร) เกินแล้วถูกตัดเงียบ ให้แบ่งพิมพ์
# ต้องแยกเป็นสองครั้ง เพราะรวมกันแล้วเกิน 127 ไบต์ ระบบจะตัดทิ้งเงียบ ๆ
# เติม: lcd.print("<span class=ok>ขึ้นจอสำเร็จ</span>")
# อยากเห็นเพดาน 127 ไบต์ด้วยตาก่อนเชื่อ: examples/s01/03_byte_limit.py วัดไบต์ของทุกก้อนขึ้นจอสด ๆ
#   เขียวคือส่งได้ครบ แดงคือเกินแล้ว และมันชี้ให้ดูด้วยว่า \n ท้ายบรรทัดหายไปพร้อมกับส่วนที่ถูกตัด
pass

TAIL = "ทีม " + TEAM_NAME + " พร้อมลุยคาบต่อไป"
# เติม: lcd.print("<span class=ok>" + TAIL + "</span>")
pass

# --- ท่าที่ 5: ป้ายประจำทีมบนหน้าจอ (เขียนมาให้ครบแล้ว ไม่ต้องเติม) ---
# สี่ท่าที่ผ่านมาทุกบรรทัดไปเข้าคิวในลิ้นชัก Console ซึ่งต้องกดเปิดเองถึงจะเห็น
# ป้ายที่คนเดินผ่านโต๊ะต้องอ่านได้ทันทีจึงเป็นงานของโมดูล ui ไม่ใช่ของ lcd
# คาบ 4 จะสอน ui เต็ม ๆ ตอนนี้แค่รันแล้วสังเกตว่าของสองชุดนี้ไปอยู่คนละที่บนจอ
ui.screen()
time.sleep_ms(200)

COL_TEXT, COL_DIM = 0xE8EAED, 0x9AA3AF
COL_CARD, COL_OK, COL_RUN = 0x171B22, 0x30A46C, 0x4A9EFF
BYTE_LIMIT = 127

ui.Panel(x=16, y=8, w=760, h=372, color=COL_CARD, min=COL_DIM, max=12, value=1)
ui.Label("ป้ายประจำทีม", x=32, y=16, color=COL_DIM, value=20)
ui.Label(TEAM_NAME, x=32, y=40, color=COL_TEXT, value=28)
ui.Label(MOTTO, x=32, y=84, color=COL_DIM, value=20)

# ui.Table จัดคอลัมน์ให้เอง แถวหนึ่งสูงราว 62 พิกเซล หัวตารางบวกสมาชิกสามคน
# จึงต้องการความสูง 250 - ถ้าตั้งเตี้ยกว่านี้ แถวสุดท้ายจะถูกตัดโดยไม่มี error
tbl = ui.Table(x=32, y=116, w=340, h=252, cols=2)
tbl.col_width(0, 100)
tbl.col_width(1, 230)
tbl.add_row("ลำดับ", "ชื่อสมาชิก")

# ไฟสองดวงแทนการบอกสถานะด้วยสีตัวอักษร ไฟมีทั้งรูปทรงและความสว่าง
# ถ่ายจอเป็นขาวดำแล้วยังแยกออกว่าดวงไหนติด ส่วนตัวหนังสือสีเขียวกับสีเทาแยกไม่ออก
ui.Label("สถานะการเขียนตาราง", x=400, y=116, color=COL_DIM, value=20)
led_run = ui.Led(x=408, y=144, w=48, h=48, color=COL_RUN, value=1)
ui.Label("กำลังเขียน", x=452, y=148, color=COL_DIM, value=20)
led_done = ui.Led(x=408, y=188, w=48, h=48, color=COL_OK, value=0)
ui.Label("เขียนครบแล้ว", x=452, y=192, color=COL_DIM, value=20)

for i in range(len(MEMBERS)):
    tbl.add_row(str(i + 1), MEMBERS[i])
    ui.poll()
    time.sleep_ms(500)

# value(0) ทำให้ไฟหรี่ ไม่ใช่หาย โดยตั้งใจ - ดวงที่หายไปตอนดับ ทำให้คนดูแยกไม่ออก
# ว่าดับจริงหรือจอเสีย ส่วนดวงที่หรี่อยู่ยังยืนยันว่าจอยังวาดอยู่
led_run.value(0)
led_done.value(1)

# มาตรวัดไบต์: ตัวเลขลอย ๆ ไม่บอกว่าใกล้เพดานแค่ไหน มาตรวัดบอก
# ภาษาไทยตัวละ 3 ไบต์ บรรทัดที่ดูสั้นบนจอคอมจึงกินโควตาเร็วกว่าที่ตาประเมิน
used = len(TAIL.encode())
ui.Label("ความยาวบรรทัดปิดท้าย จากเพดาน 127", x=400, y=240, color=COL_DIM, value=20)
ui.Bar(x=408, y=272, w=332, h=16, color=COL_OK, min=0, max=BYTE_LIMIT, value=used)
ui.Scale(x=408, y=288, w=332, h=44, color=COL_TEXT, min=0, max=BYTE_LIMIT)
ui.Label(str(used) + " ไบต์", x=408, y=336, color=COL_TEXT, value=20)
ui.poll()

# ปิดท้ายฝั่งคอมด้วย เผื่อทีมไหนจอมีปัญหา จะได้รู้ว่าโค้ดรันจบจริง
print("โปรแกรมจบแล้ว ถ้าจอไม่ขึ้นข้อความ เช็กว่าเข้าเมนู Playground หรือยัง")
