# --- ท่าที่ 2: สองแกน สองแถบ และไม้บรรทัดที่บอกพิสัยของมันเอง ---
# ผังหน้าจอ: หัวเรื่อง+คุณภาพของค่า y=8..40 · การ์ดวัดสองแกน y=48..176
#            การ์ดเทียบเกณฑ์ x=616..768 · การ์ดตั้งค่าและคำสั่ง y=192..380
