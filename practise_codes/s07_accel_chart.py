import ui
ui.screen()
import time
import sensors

COL_TEXT, COL_DIM = 0xE8EAED, 0x9AA3AF
COL_CARD = 0x171B22
# สามเส้นนี้หยิบจาก "จานสีเส้นข้อมูล" ของ SPEC §S7.13 ไม่ใช่จานสีบทบาท
# และไม่มีสีสถานะปนอยู่เลยสักตัว โดยตั้งใจ - เส้นกราฟสีแดงที่ไม่ได้แปลว่า
# ผิดปกติ คือสิ่งที่ §S7.7.2 ห้ามไว้
COL_AX = 0x4A9EFF      # แกน X - เส้นที่ 1 ของจานสีเส้นข้อมูล สีฟ้า
COL_AY = 0x8E7BFF      # แกน Y - เส้นที่ 2 ของจานสีเส้นข้อมูล สีม่วง
COL_AZ = 0x2FB6A8      # แกน Z - เส้นที่ 3 ของจานสีเส้นข้อมูล สีเขียวน้ำทะเล
COL_RUN = 0x4A9EFF     # สีเน้นของจานบทบาท - ใช้กับไฟบอกว่ากำลังบันทึกอยู่
PERIOD_MS = 200        # คาบการสุ่มที่เราเลือก

# --- ท่าที่ 1: เตรียมเซนเซอร์และหน้าจอให้พร้อม ---
# Eva Kit ไม่มี sensors.init() ให้เรียก IMU อยู่บนบัสที่คอร์จอ (CM55) ถือไว้คนเดียว
# ฝั่ง Python ขอค่าที่คอร์จออ่านเก็บไว้ให้ทุก 200 ms จึงเรียก motion() ได้เลย
# ถ้าเผลอเรียก sensors.init() จะได้ OSError ทันที ไม่ใช่ค้าง
#
# หลังรีเซ็ต คอร์จอเริ่มตอบเรื่องเซนเซอร์ราว 13 วินาที การอ่านครั้งแรก
# จึงนิ่งได้ถึง 16 วินาที ครั้งถัดไปเร็วปกติ อุ่นเครื่องหนึ่งครั้งตรงนี้ก่อนสร้างกราฟ
try:
    sensors.bmi270.motion()
except OSError:
    print("คอร์จอยังไม่ตอบรอบแรก จะลองใหม่ในลูป")

ui.clear()
time.sleep_ms(200)

# ผังหน้าจอ: หัวเรื่อง y=8..45 · กราฟ x=24..316 y=52..196 · ตาราง x=332..768 y=52..332
#            สถานะกับปุ่มอยู่คอลัมน์ซ้ายใต้กราฟ ปุ่มจบที่ y=384
ui.Label("กราฟความเร่งสามแกน หน่วย m/s2", x=24, y=8, color=COL_TEXT, value=28)

# --- ท่าที่ 2: กราฟหนึ่งใบ สามเส้น และตารางสรุปข้าง ๆ ---
# min/max คือขอบแกน Y ตั้ง -20..20 เพราะแรงโน้มถ่วงอยู่ที่ 9.81 มีที่เหลือให้โยกได้อีกเท่าตัว
chart = ui.Chart(x=24, y=52, w=292, h=144, min=-20, max=20, color=COL_AX)
s_ay = chart.add_series(COL_AY)      # คืนค่าเป็น "หมายเลข series"

s_az = s_ay                          # ค่าชั่วคราวให้ไฟล์รันได้ก่อนเติมบรรทัดล่าง
# เติม: s_az = chart.add_series(COL_AZ)
# เส้นที่เพิ่มมาต้องเก็บหมายเลขไว้เสมอ ไม่งั้นเรียก set_next ไม่ถูกเส้น
# examples/s07/01_imu_vibration_monitor.py ทำแบบเดียวกันกับสามเส้น ค่าจริง เส้นเฝ้าดู เส้นเตือน
# ดูวิธีที่มันตั้งชื่อตัวแปรของแต่ละ series ไว้ แล้วจะไม่หลงว่าเลข 0 คือเส้นไหน
pass

# ตารางแทนการเรียง Label หลายบรรทัดให้ดูเหมือนตาราง: ui.Table จัดคอลัมน์ให้เอง
# ความกว้างคอลัมน์ต้องกว้างพอสำหรับข้อความที่ยาวที่สุด ถ้าแคบไปข้อความจะขึ้นบรรทัดใหม่
# แล้วความสูงของ "ทุกแถว" จะเด้งเป็นสองเท่าทันที และ value= คือขนาดฟอนต์ในช่อง
# ตัวเลขคอลัมน์ชุดนี้วัดจากภาพเรนเดอร์ ไม่ได้คำนวณเอา - เคยลองบีบเหลือ 64/76/76/76
# แล้วทุกช่องขึ้นบรรทัดที่สอง ("ต่ำสุ" / "ด") ความสูงแถวเด้งเป็นสองเท่า และแถว Z
# หลุดออกนอกตารางพร้อมแถบเลื่อน ทั้งที่ประตูตรวจพิกัดบอกว่าผ่าน - เห็นได้จากภาพเท่านั้น
tbl = ui.Table(x=332, y=52, w=436, h=280, cols=4, value=16)
tbl.col_width(0, 100)
tbl.col_width(1, 108)
tbl.col_width(2, 108)
tbl.col_width(3, 108)
tbl.add_row("แกน", "ต่ำสุด", "สูงสุด", "ล่าสุด")
tbl.add_row("X", "-", "-", "-")
tbl.add_row("Y", "-", "-", "-")
tbl.add_row("Z", "-", "-", "-")

# --- ท่าที่ 3: ไฟบอกสถานะ และปุ่มเริ่มกับปุ่มหยุดที่แยกกันคนละปุ่ม ---
# ปุ่มเดียวที่สลับไปมาบอกไม่ได้ว่าตอนนี้อยู่สถานะไหน คนกดจึงต้องเดา และเดาผิดได้เสมอ
# เดิมสามอย่างนี้อยู่ในการ์ดสูง 64 px ทั้งที่ปุ่มสูง 88 px ปุ่มจึงยื่นพ้นการ์ดของตัวเอง
# ลงไปนอกจอ 18 px แล้วกดไม่ได้ ตอนนี้เลิกใช้การ์ด แล้ววางเป็นสามชั้นในคอลัมน์ซ้ายแทน
led_rec = ui.Led(x=24, y=212, w=48, h=48, color=COL_RUN, value=1)
lbl_rec = ui.Label("กำลังบันทึก", x=88, y=216, color=COL_TEXT, value=20)
rec_msg = "กำลังบันทึก"       # ข้อความสถานะล่าสุด เปลี่ยนเฉพาะตอนกดปุ่ม
lbl_dt = ui.Label("คาบลูป -- ms", x=88, y=252, color=COL_DIM, value=20)
btn_start = ui.Button("เริ่มบันทึก", x=24, y=296, w=128, h=88,
                      color=0x30A46C, value=20)
btn_stop = ui.Button("หยุดบันทึก", x=184, y=296, w=128, h=88,
                     color=0x3A4150, value=20)
start_id = btn_start.id()
stop_id = btn_stop.id()
ui.poll()

running = True
last_ms = time.ticks_ms()
dt = PERIOD_MS
last_sec = -1                    # วินาทีที่เพิ่งเขียนตัวเลขลงจอ
ax, ay, az = 0.0, 0.0, 9.81      # ค่าตั้งต้น เผื่อรอบแรกยังอ่านไม่ได้
lo = [None, None, None]
hi = [None, None, None]


def note(i, v):
    """จำค่าต่ำสุดกับสูงสุดของแกนหนึ่ง - กราฟจำให้ไม่ได้เพราะจุดเก่าถูกเขี่ยทิ้ง"""
    if lo[i] is None or v < lo[i]:
        lo[i] = v
    if hi[i] is None or v > hi[i]:
        hi[i] = v


def cell(v):
    return "-" if v is None else "{:+.2f}".format(v)


while True:
    # --- ท่าที่ 4: อ่านหกแกนจาก snapshot ชุดเดียว แล้วป้อนสามเส้น ---
    if running:
        # อ่านพลาดหนึ่งรอบไม่ควรทำให้กราฟดับทั้งหน้า ใช้ค่าเดิมไปก่อน แล้วลองใหม่รอบหน้า
        try:
            ax, ay, az, gx, gy, gz = sensors.bmi270.motion()
        except OSError:
            pass

        # เติม: chart.set_next(0, int(ax))
        # int() ไม่ได้ใส่ไว้เผื่อสวย มันบังคับ และการปัดทิ้งทศนิยมคือการทิ้งความละเอียด
        #   examples/s07/01_imu_vibration_monitor.py แก้ปัญหาเดียวกันด้วยการคูณค่าขึ้น
        #   ก่อนป้อน แล้วขยายช่วง min/max ของกราฟตามไปด้วย ถ้าเส้นของเราออกมาเป็นขั้นบันได
        #   นั่นคือท่าที่ต้องใช้
        pass

        chart.set_next(s_ay, int(ay))
        chart.set_next(s_az, int(az))
        # ตารางเก็บของที่กราฟเก็บไม่ได้: ค่าสุดขีดที่ผ่านไปแล้วเกิน 50 จุด
        note(0, ax)
        note(1, ay)
        note(2, az)

    # --- ท่าที่ 5: วัดคาบลูปจริงแล้วรายงาน ---
    now = time.ticks_ms()

    # เติม: dt = time.ticks_diff(now, last_ms)
    pass

    last_ms = now

    # poll ทุกรอบไม่ว่าจะหยุดบันทึกอยู่หรือไม่ ถ้ากั้น poll ไว้ใน if running ปุ่มจะกดไม่ได้ตลอดกาล
    for ev in ui.poll():
        h = ev.get('handle')
        if h == start_id:
            # เติม: running = True
            # "หยุด" ที่ปลอดภัยคือหยุดป้อนข้อมูล ไม่ใช่หยุดลูป
            #   examples/s07/01_imu_vibration_monitor.py มีปุ่มหยุดกราฟแบบเดียวกัน และเขียนกฎ
            #   ไว้ตรง ๆ ว่าหยุดกราฟคือหยุดวาด ยังต้อง poll ปุ่มอยู่ ไม่งั้นจะไม่มีทางกดกลับมาได้เลย
            pass

            # เริ่มรอบใหม่ = ล้างค่าสุดขีดของรอบเก่าทิ้ง ไม่งั้นตารางจะปนสองรอบเข้าด้วยกัน
            lo = [None, None, None]
            hi = [None, None, None]
            led_rec.value(1)
            lbl_rec.color(COL_TEXT)
            rec_msg = "กำลังบันทึก"
        elif h == stop_id:
            # เติม: running = False
            # ปุ่มเริ่มกับปุ่มหยุดแยกกันคนละปุ่ม ไม่ใช่ปุ่มเดียวสลับ เพราะปุ่มสลับบอกไม่ได้
            #   ว่าตอนนี้อยู่สถานะไหน ตัวที่บอกสถานะคือไฟกับป้ายข้าง ๆ มัน
            pass

            # ไฟที่ดับจะ "หรี่" ไม่ใช่หายไป ดวงที่หายไปทำให้คนดูแยกไม่ออกว่าดับหรือจอเสีย
            led_rec.value(0)
            lbl_rec.color(COL_DIM)
            rec_msg = "หยุดแล้ว ค่าล่าสุด"


    # --- ชีพจรของช่องทางข้ามคอร์: ส่งบรรทัดสถานะซ้ำทุกรอบโดยตั้งใจ ---
    # ฝั่งจอมีตัวจับเวลาสองจังหวะ โหมดเร็ว 5 ms กับโหมดปกติ 200 ms และมันจะอยู่
    # โหมดเร็วต่อไปอีก 500 ms ทุกครั้งที่ได้รับคำสั่ง "เขียนข้อความ" หรือ "ย้าย/ย่อ/เปลี่ยนสี"
    # แต่ set_next() ของกราฟกับ .value() ของไฟ "ไม่" ปลุกโหมดนั้น ลูปที่ป้อนแต่กราฟ
    # จึงเงียบเกินครึ่งวินาที แล้วจอถอยไปโหมดช้า เส้นกระตุกทั้งที่โค้ดไม่ได้เปลี่ยน
    # ข้อความที่ส่งไปนี้เท่าเดิมเกือบทุกรอบ และเฟิร์มแวร์ไม่วาดซ้ำถ้าข้อความไม่เปลี่ยน
    # เราจึงจ่ายแค่ค่าส่งข้ามคอร์ ไม่ได้จ่ายค่าวาดใหม่
    lbl_rec.text(rec_msg)

    # ตัวเลขที่คนต้องอ่าน เขียนใหม่ไม่เกินวินาทีละครั้ง และอยู่ตำแหน่งเดิมเสมอ
    # เส้นกราฟยังเดินห้าครั้งต่อวินาทีตามเดิม เพราะตาคนอ่าน "รูปร่าง" ได้โดยไม่ต้องหยุดอ่าน
    sec = time.ticks_ms() // 1000
    if sec != last_sec:
        last_sec = sec
        # .cell(แถว, คอลัมน์, ข้อความ) เขียนทับช่องเดิม ไม่ได้เพิ่มแถวใหม่
        # แถว 0 คือหัวตาราง แกน X Y Z จึงเป็นแถว 1 2 3
        for i, v in enumerate((ax, ay, az)):
            tbl.cell(i + 1, 1, cell(lo[i]))
            tbl.cell(i + 1, 2, cell(hi[i]))
            tbl.cell(i + 1, 3, "{:+.2f}".format(v))
        # อัปเดต Label ในลูปเสมอ - การส่งงานเข้า IPC สม่ำเสมอคือสิ่งที่ทำให้ช่องทาง
        # ข้ามคอร์อยู่ในโหมดเร็ว ถ้าเงียบไปหลายรอบมันจะถอยไปโหมดช้า
        lbl_dt.text("คาบลูป {} ms".format(dt))

    # เติม: time.sleep_ms(PERIOD_MS)
    # PERIOD_MS = 200 แปลว่าเราสุ่ม 5 ครั้งต่อวินาที ซึ่งเห็นการโยกมือได้ แต่เห็นการสั่นเร็ว ๆ ไม่ได้
    # examples/s07/03_aliasing_nyquist.py แสดงว่าเมื่อสุ่มช้ากว่าที่ควร เราจะไม่ได้เส้นที่หายไปเฉย ๆ
    # แต่จะได้ความถี่ที่ไม่เคยมีอยู่จริงมาแทน และกรองทิ้งทีหลังไม่ได้ด้วย
    # ก่อนจะแก้เลขนี้เป็นค่าอื่น อ่านไฟล์นั้นก่อน จะได้รู้ว่ากำลังแลกอะไรกับอะไร
    pass
