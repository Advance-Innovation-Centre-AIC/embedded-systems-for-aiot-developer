# s04_touch_panel.py - แผงควบคุม LED บนจอสัมผัส (ฉบับฝึกเติมโค้ด)
# วิธีรัน: 1) บนจอบอร์ด แตะการ์ด Playground ค้างไว้ (widget เกิดบนหน้านี้เท่านั้น)
#          2) เติมช่องว่างตามคำใบ้ให้ครบทีละท่า ส่งขึ้นบอร์ดดูผลทุกครั้ง
#          3) กด Program to Device แล้วมองสองที่พร้อมกัน: จอ กับ หลอด LED จริง
#
# คาบนี้เราสร้างหน้า Controls ของทีมเราเอง นิ้วแตะกระจกที่ CM55
# กลายเป็นเหตุการณ์ในคิว แล้วโค้ด Python ที่ CM33 มารับด้วย ui.poll()
# โจทย์จริงของคาบนี้ไม่ใช่ "กดแล้วไฟติด" แต่คือ "จอกับไฟจริงต้องตรงกันเสมอ"
#
# ประโยคสุดท้ายนั้นมีตัวอย่างเป็นเรื่องเป็นราวอยู่ที่ examples/s04/03_switch_matches_led.py
# มันสร้างสถานการณ์ที่จอโกหกให้ดูก่อน แล้วค่อยแก้ด้วยกฎ "มีประตูเดียวที่เปลี่ยนสถานะไฟได้"
# ซึ่งเป็นกฎเดียวกับ set_led() ที่เราจะเติมกันในท่าที่ 4 ข้างล่างนี้
#
# ดูที่จอ: ซ้ายคือสามแถว แถวละหนึ่งดวง มีไฟสถานะ ปุ่มเปิด และปุ่มปิด แยกกันคนละปุ่ม
#         ขวาคือคำสั่งทั้งชุด และล่างคือบรรทัดสถานะกับกล่องยืนยันที่ซ่อนไว้
# กับดัก : ปุ่มเดียวที่กดแล้วสลับไปมา บอกไม่ได้ว่าตอนนี้อยู่สถานะไหน คนกดต้องเดา
#         แผงควบคุมจริงจึงแยกเปิดกับปิดเสมอ ปุ่ม "เปิด" ที่กดซ้ำสิบครั้ง
#         ต้องได้ผลเดียวกับกดครั้งเดียว

import ui
import gpio
import time

# ---------- ข้อมูลของแผงควบคุม (ปรับสีหรือข้อความได้ตามใจทีม) ----------
BTN_TEXT = ["แดง", "เขียว", "น้ำเงิน"]              # ดวงที่ 2 คือน้ำเงิน แม้ .name() จะคืน "RGB_RED"
COL_ON = [0xE53935, 0x43A047, 0x1E88E5]           # สีไฟสถานะตอนติด เรียงตรงกับ BTN_TEXT
COL_OFF = 0x37474F                                 # สีเทาของปุ่มที่ไม่ได้กำลังทำงาน
COL_TEXT, COL_DIM, COL_CARD = 0xFFFFFF, 0xA0B4CC, 0x142240

# ความจริงของโปรแกรมอยู่ที่ list นี้ที่เดียว
# ห้ามไปอ่านจากฮาร์ดแวร์: gpio.led(2).value() ตอบระดับของขา ไม่ใช่สิ่งที่เราสั่ง
# และหลัง brightness() หรือ hold() ขาจะถูกทิ้งไว้ต่ำ ค่าที่ได้จึงเป็น 0
led_on = [False, False, False]

# --- ท่าที่ 1: เตรียมหน้าจอให้ว่าง แล้วปักหัวเรื่อง ---
# ui.screen() ล้าง widget ที่กลุ่มก่อนหน้าทิ้งค้างไว้ ไม่งั้นเรานับโควตาผิด
ui.screen()
time.sleep_ms(200)                                 # ให้ CM55 ล้างเสร็จก่อนยิงคำสั่งชุดใหม่

# value= ของ Label คือ "ขนาดฟอนต์" (14/16/20/24/28) ไม่ใช่ค่าตัวเลขใด ๆ
ui.Label("แผงควบคุม LED ของทีม", x=16, y=6, color=COL_TEXT, value=24)

# --- ท่าที่ 2: สามแถว แถวละหนึ่งดวง เปิดกับปิดแยกกันคนละปุ่ม ---
# ทำไมไม่ใช้ปุ่มเดียวสลับ: ปุ่มสลับบอกไม่ได้ว่าตอนนี้อยู่สถานะไหน คนกดต้องเดา
# ส่วนปุ่มเปิดกับปุ่มปิดที่แยกกัน กดแล้วได้ผลเดิมเสมอไม่ว่าจะกดกี่ครั้ง
ui.Panel(x=16, y=38, w=520, h=232, color=COL_CARD, min=COL_DIM, max=12, value=1)
lamps = []
btn_on = []
btn_off = []
for i in range(3):
    y = 46 + i * 76
    # ไฟสถานะบอกว่า "ตอนนี้เป็นยังไง" ปุ่มบอกว่า "สั่งอะไรได้" - คนละหน้าที่ คนละชิ้น
    lamps.append(ui.Led(x=32, y=y + 8, w=34, h=34, color=COL_ON[i], value=0))
    ui.Label(BTN_TEXT[i], x=78, y=y + 14, color=COL_DIM, value=18)

    # เติม: btn_on.append(ui.Button("เปิด", x=200, y=y, w=140, h=54, color=0x1B5E20, value=18))
    # ยังไม่ชินกับอาร์กิวเมนต์ของ widget: examples/s04/01_first_widgets.py สร้างทีละตัวช้า ๆ
    #   และอธิบายว่าทำไมต้องใส่ x= y= ทุกครั้ง (ถ้าไม่ใส่ จอจะจัดเองบนกริด 200 พิกเซล
    #   แล้วข้อความยาวจะล้นไปทับช่องถัดไป) ส่วน examples/s04/06_layout_budget.py คือเรื่องโควตา
    #   64 ตัวต่อหน้า กับมุมขวาล่างที่ปุ่ม Console จองไว้ ห้ามวางปุ่มทับ
    pass

    btn_off.append(ui.Button("ปิด", x=352, y=y, w=140, h=54, color=COL_OFF, value=18))

# เก็บหมายเลขประจำตัวไว้ เพราะเหตุการณ์บอกมาแค่ handle ไม่ได้บอกชื่อปุ่ม
on_ids = [b.id() for b in btn_on]
off_ids = [b.id() for b in btn_off]

# --- ท่าที่ 3: คำสั่งทั้งชุด กับบรรทัดสถานะ ---
ui.Panel(x=552, y=38, w=224, h=232, color=COL_CARD, min=COL_DIM, max=12, value=1)
ui.Label("คำสั่งทั้งชุด", x=566, y=44, color=COL_DIM, value=16)
btn_all_on = ui.Button("เปิดทั้งหมด", x=566, y=72, w=196, h=54, color=0x1B5E20, value=18)
btn_all_off = ui.Button("ปิดทั้งหมด", x=566, y=136, w=196, h=54, color=COL_OFF, value=18)
ui.Label("สถานะรวม", x=566, y=204, color=COL_DIM, value=14)
lbl_count = ui.Label("ติดอยู่ 0 จาก 3 ดวง", x=566, y=226, color=COL_TEXT, value=18)

status = ui.Label("พร้อมรับคำสั่ง", x=16, y=284, color=COL_DIM, value=18)

# กล่องยืนยัน: "ปิดทั้งหมด" แตะทีเดียวเปลี่ยนของจริงสามดวงพร้อมกัน
# คำยืนยันจึงต้องบอกสิ่งที่จะเกิด ไม่ใช่ถามลอย ๆ ว่า "แน่ใจไหม"
box = ui.MsgBox("ปิดทั้งหมด\nไฟสามดวงจะดับพร้อมกัน", x=16, y=278, w=520, h=110,
                color=COL_CARD)
btn_yes = ui.Button("ปิดทั้งหมด", x=552, y=284, w=104, h=44, color=COL_OFF, value=16)
btn_no = ui.Button("ไม่ปิด", x=552, y=336, w=104, h=44, color=COL_OFF, value=16)
box.hide()
btn_yes.hide()
btn_no.hide()

# --- ท่าที่ 4: ประตูเดียวที่เปลี่ยนสถานะไฟได้ ---
def show_status():
    # อ่านจาก led_on อย่างเดียว ไม่ถามฮาร์ดแวร์ จึงเชื่อถือได้เสมอ
    n = 0
    for i in range(3):
        if led_on[i]:
            n += 1
    # ตัวเลขมาพร้อมพิสัยของมันเสมอ "ติดอยู่ 2" ไม่บอกอะไร "2 จาก 3" บอกทันที
    lbl_count.text("ติดอยู่ " + str(n) + " จาก 3 ดวง")

def set_led(i, on):
    led_on[i] = on                                 # 1) จำไว้ก่อน
    if on:
        # 2) สั่งของจริง แล้วให้ไฟบนจอรายงานตรงกัน
        # เติม: gpio.led(i).on()
        # สามบรรทัดในฟังก์ชันนี้ (จำ - สั่งของจริง - รายงาน) ต้องอยู่ครบทุกครั้ง
        #   examples/s04/03_switch_matches_led.py ให้ปุ่ม ALL OFF ที่ดับไฟจริงแต่ลืมดึงสวิตช์
        #   บนจอกลับ แล้วชี้ว่าตั้งแต่วินาทีนั้นจอก็โกหกผู้ใช้ไปแล้ว โดยไม่มี error อะไรเลย
        pass
        lamps[i].value(1)
    else:
        # เติม: gpio.led(i).off()
        pass
        # value(0) ทำให้ไฟหรี่ ไม่ใช่หาย โดยตั้งใจ - ดวงที่หายไปตอนดับ
        # ทำให้คนดูแยกไม่ออกว่าดับจริงหรือจอเสีย
        lamps[i].value(0)
    show_status()                                  # 3) รายงานขึ้นจอทุกครั้ง ไม่มีข้อยกเว้น

# --- ท่าที่ 5: เริ่มจากสถานะที่เรารู้แน่ ---
# ไม่ "สมมติ" ว่าไฟดับอยู่ แต่สั่งให้ดับ เผื่อโปรแกรมก่อนหน้าทิ้งไฟติดค้างไว้
for i in range(3):
    set_led(i, False)

asking = False
print("แผงควบคุมพร้อมแล้ว แตะปุ่มบนจอ แล้วมองหลอดไฟจริงบนบอร์ดด้วย")

# --- ท่าที่ 6: event loop - poll แล้ว dispatch แล้ว act แล้ว sleep ---
while True:
    # กฎข้อ 1: ต้องเรียก ui.poll() ทุกรอบ ไม่งั้นจอจะซ่อน widget ไว้ราว 2 วินาที
    for ev in ui.poll():
        h = ev['handle']
        t = ev['type']
        if t != 'clicked':
            # ตัวควบคุมแต่ละชนิดส่ง type ไม่เหมือนกัน examples/s04/02_event_types.py
            # วางของจริงสี่ตัวให้แตะ แล้วพิมพ์เหตุการณ์ที่เข้ามาจริง ๆ ทีละใบ
            # ไปรอ type ผิดตัวเมื่อไร โปรแกรมจะเงียบสนิททั้งที่นิ้วแตะติดทุกครั้ง
            continue

        if h in on_ids:
            # เติม: set_led(on_ids.index(h), True)
            # สั่งเปิด ไม่ใช่สั่งสลับ กดซ้ำสิบครั้งต้องได้ผลเดียวกับกดครั้งเดียว
            pass

            status.text("สั่งเปิด " + BTN_TEXT[on_ids.index(h)])
        elif h in off_ids:
            # เติม: set_led(off_ids.index(h), False)
            pass

            status.text("สั่งปิด " + BTN_TEXT[off_ids.index(h)])
        elif h == btn_all_on.id():
            for i in range(3):
                set_led(i, True)
            status.text("เปิดครบทั้งสามดวง")
        elif h == btn_all_off.id() and not asking:
            # คำสั่งที่เปลี่ยนของจริงหลายชิ้นพร้อมกัน ต้องถามก่อนเสมอ (เขียนมาให้แล้ว)
            asking = True
            box.show()
            btn_yes.show()
            btn_no.show()
            status.hide()
        elif h == btn_yes.id() and asking:
            asking = False
            for i in range(3):
                set_led(i, False)
            box.hide()
            btn_yes.hide()
            btn_no.hide()
            status.text("ปิดครบทั้งสามดวง")
            status.show()
        elif h == btn_no.id() and asking:
            asking = False
            box.hide()
            btn_yes.hide()
            btn_no.hide()
            status.show()

    # กฎข้อ 2: หน่วงอย่างน้อย 50 ms คืนเวลาให้ระบบไปวาดจอ
    # เติม: time.sleep_ms(50)
    # อยากได้เสียงตอบรับตอนแตะปุ่มด้วย: examples/s04/05_sound_feedback.py ต่อ ui.sfx และ ui.tone
    #   เข้ากับลูปแบบนี้ พร้อมกับดักที่เจอกันบ่อย - ui.tone รับโน้ต MIDI 0-127 ไม่ใช่เฮิรตซ์
    pass
